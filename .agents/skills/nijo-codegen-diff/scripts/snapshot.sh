#!/bin/bash

# Task/ソース最新化.sh で自動生成をかけなおし、全デモの生成物を temp_ソース現新比較用/<ラベル> に退避する。
#
# 使い方:
#   snapshot.sh <ラベル> [git ref]
#
#   git ref 省略時 : 作業ツリーで ソース最新化.sh を実行し、その生成物を退避する。
#   git ref 指定時 : その ref を一時 worktree に展開して ソース最新化.sh を実行し、その生成物を退避する。
#                    作業ツリーを改修済みで、改修前の状態を取りたい場合に使う。作業ツリーのファイルには触れない。

set -u

LABEL="${1:-}"
GIT_REF="${2:-}"

if [ -z "$LABEL" ]; then
  echo "ラベルが指定されていません。 使い方: snapshot.sh <ラベル> [git ref]"
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
COMPARE_ROOT="$REPO_ROOT/temp_ソース現新比較用"

# 実行対象のリポジトリの決定
if [ -n "$GIT_REF" ]; then
  WORKTREE_DIR="$(mktemp -d)"
  trap 'git -C "$REPO_ROOT" worktree remove --force "$WORKTREE_DIR"' EXIT
  git -C "$REPO_ROOT" worktree add --detach "$WORKTREE_DIR" "$GIT_REF" || exit 1
  TARGET_ROOT="$WORKTREE_DIR"
else
  TARGET_ROOT="$REPO_ROOT"
fi

# 自動生成かけなおし
"$TARGET_ROOT/Task/ソース最新化.sh"
if [ $? -ne 0 ]; then
  echo "ソース最新化.sh が失敗しました。"
  exit 1
fi

# 生成物の退避
"$TARGET_ROOT/Task/各AutoGeneratedを一時フォルダにコピー.sh" "$LABEL" || exit 1

# worktree 内に退避した場合は、作業ツリー側の比較用フォルダへ移す
if [ "$TARGET_ROOT" != "$REPO_ROOT" ]; then
  mkdir -p "$COMPARE_ROOT"
  rm -rf "$COMPARE_ROOT/$LABEL"
  mv "$TARGET_ROOT/temp_ソース現新比較用/$LABEL" "$COMPARE_ROOT/$LABEL" || exit 1
fi

echo "退避先: $COMPARE_ROOT/$LABEL"
