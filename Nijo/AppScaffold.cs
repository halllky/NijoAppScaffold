using Microsoft.Extensions.Logging;
using Nijo.CodeGenerating;
using Nijo.ImmutableSchema;
using Nijo.Models;
using Nijo.Parts.Common;
using Nijo.Parts.CSharp;
using Nijo.Parts.JavaScript;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

namespace Nijo;

/// <summary>
/// スキーマ定義からどういったソースコードが生成されるかの定義。
/// </summary>
internal static class AppScaffold {

    /// <summary>
    /// ソースコードを生成し、複数の集約から1つのファイルが生成される類のファイル（<see cref="IMultiAggregateSourceFile"/>）を登録します。
    /// </summary>
    internal static void GenerateCode(CodeRenderingContext ctx, ILogger logger) {
        var schema = ctx.Schema;
        var dataStructures = schema.GetDataStructures().ToArray();

        // ルート集約ごとのソースコード
        RenderEach(dataStructures, root => RenderDataStructure(ctx, root), logger);
        RenderEach(schema.GetCommands(), root => CommandModel.Render(ctx, root), logger);
        RenderEach(schema.GetStaticEnums(), root => StaticEnumModel.Render(ctx, root), logger);
        RenderEach(schema.GetValueObjects(), root => ValueObjectModel.Render(ctx, root), logger);
        RenderEach(schema.GetConstants(), root => ConstantModel.Render(ctx, root), logger);

        // 特定の種類のデータ構造が1個以上存在する場合にのみ生成されるソースコード
        if (dataStructures.Any(root => root.IsStored)) DataModel.RenderCommonModules(ctx);
        if (dataStructures.Any(root => root.IsQueryable)) QueryModel.RenderCommonModules(ctx);
        if (dataStructures.Any(root => !root.IsStored && !root.IsQueryable)) StructureModel.RenderCommonModules(ctx);

        // スキーマ定義にかかわらず必ず生成されるソースコード
        ctx.Use<ApplicationService>();
        ctx.Use<EnumFile>();
        ctx.Use<AggregateMetadata>();
        ctx.Use<ValueObjectModel.ValueObjectJsonConverter>();
        ctx.Use<MessageContainer.BaseClass>();
        ctx.Use<CommandQueryMappings>();
        ctx.Use<AspNetController.HandlerInterfaceFile>();
        ctx.Use<DbContextClass>();
        Models.DataModelModules.ValidateCustom.RegisterApplicationServiceHooks(ctx);
        ctx.CoreLibrary(dir => {
            dir.Directory("Util", utilDir => {
                utilDir.Generate(NijoAttr.RenderDeclaration(ctx));
                utilDir.Generate(PresentationContext.RenderStaticCore(ctx));
                utilDir.Generate(FromTo.Render(ctx));
            });
        });

        // 値メンバーの型ごとのソースコード
        foreach (var vmType in ctx.SchemaParser.GetValueMemberTypes()) {
            vmType.RegisterDependencies(ctx);
            vmType.RenderStaticSources(ctx);
        }
    }

    /// <summary>
    /// 他のすべてのソースコードが生成された後でなければ生成できないソースコードを生成します。
    /// </summary>
    internal static void GenerateCodeAfterAll(CodeRenderingContext ctx) {
        ctx.ReactProject(autoGenerated => {
            IndexTs.Render(autoGenerated, ctx);
        });
    }

    /// <summary>
    /// データ構造のルート集約1個と対応するソースコードを、IsStored, IsQueryable 属性に応じて生成します。
    /// </summary>
    private static void RenderDataStructure(CodeRenderingContext ctx, RootAggregate rootAggregate) {
        var aggregateFile = new SourceFileByAggregate(rootAggregate);

        if (rootAggregate.IsStored) DataModel.Render(ctx, rootAggregate, aggregateFile);
        if (rootAggregate.IsQueryable) QueryModel.Render(ctx, rootAggregate, aggregateFile);
        if (!rootAggregate.IsStored && !rootAggregate.IsQueryable) StructureModel.Render(ctx, rootAggregate, aggregateFile);

        aggregateFile.ExecuteRendering(ctx);
    }

    private static void RenderEach(IEnumerable<RootAggregate> rootAggregates, Action<RootAggregate> render, ILogger logger) {
        var parallelOptions = new ParallelOptions {
            MaxDegreeOfParallelism = Math.Min(Environment.ProcessorCount, 4),
        };
        Parallel.ForEach(rootAggregates, parallelOptions, rootAggregate => {
            logger.LogInformation("レンダリング開始: {name}", rootAggregate.DisplayName);
            try {
                render(rootAggregate);
            } catch (Exception ex) {
                throw new InvalidOperationException($"{rootAggregate}のレンダリングで例外が発生", ex);
            }
        });
    }
}
