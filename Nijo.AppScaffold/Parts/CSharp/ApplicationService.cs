using Nijo.CodeGenerating;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace Nijo.Parts.CSharp {
    public class ApplicationService : ISharedSourceFile<CodeRenderingContext> {
        public const string ABSTRACT_CLASS = "AutoGeneratedApplicationService";
        /// <summary>
        /// アプリケーションサービスの型引数。クエリ・コマンドの呼び出し1回について、全処理に共通の入出力の型。
        /// 中身はアプリケーションが定義し、自動生成されるソースはその中身を参照しない。
        /// </summary>
        public const string CONTEXT_TYPE_PARAMETER = "TOperationContext";
        /// <summary>型引数を含めたアプリケーションサービスの型名</summary>
        public const string ABSTRACT_CLASS_WITH_TYPE_PARAMETER = $"{ABSTRACT_CLASS}<{CONTEXT_TYPE_PARAMETER}>";

        public const string SERIALIZE_FOR_LOG = "SerializeForLog";

        private readonly Lock _lock = new();
        private readonly List<string> _sourceCode = [];

        public ApplicationService Add(string sourceCode) {
            lock (_lock) {
                _sourceCode.Add(sourceCode);
                return this;
            }
        }

        public void RegisterDependencies(CodeRenderingContext ctx) {
            // 特になし
        }

        public void Render(CodeRenderingContext ctx) {
            ctx.CoreLibrary(dir => {
                dir.Generate(RenderDeclaring(ctx));
            });
        }

        private SourceFile RenderDeclaring(CodeRenderingContext ctx) {
            return new SourceFile {
                FileName = "ApplicationService.cs",
                Contents = $$"""
                    using Microsoft.Extensions.DependencyInjection;
                    using Microsoft.Extensions.Logging;

                    namespace {{ctx.Config.RootNamespace}};

                    /// <summary>
                    /// アプリケーションのための各種機能を提供する。
                    /// </summary>
                    /// <typeparam name="{{CONTEXT_TYPE_PARAMETER}}">
                    /// クエリ・コマンドの呼び出し1回について、全処理に共通の入出力の型。
                    /// 各処理はこの型のインスタンスを引数として受け取る。中身はアプリケーションが定義し、このクラスは中身を参照しない。
                    /// </typeparam>
                    public abstract partial class {{ABSTRACT_CLASS_WITH_TYPE_PARAMETER}} {
                        protected {{ABSTRACT_CLASS}}(IServiceProvider serviceProvider) {
                            ServiceProvider = serviceProvider;
                        }

                        public IServiceProvider ServiceProvider { get; }

                        private {{ctx.Config.DbContextName}}? _dbContext;
                        public {{ctx.Config.DbContextName}} DbContext => _dbContext ??= ServiceProvider.GetRequiredService<{{ctx.Config.DbContextName}}>();

                        /// <summary>
                        /// ログ出力はこのプロパティを通して行われる想定
                        /// </summary>
                        public ILogger Log => _logger ??= ServiceProvider.GetRequiredService<ILogger<{{ABSTRACT_CLASS_WITH_TYPE_PARAMETER}}>>();
                        private ILogger? _logger;

                        /// <summary>
                        /// ログ出力用にオブジェクトをシリアライズする。
                        /// </summary>
                        public virtual string {{SERIALIZE_FOR_LOG}}<T>(T obj) {
                            return System.Text.Json.JsonSerializer.Serialize(obj, new System.Text.Json.JsonSerializerOptions {
                                // Unicode文字のエスケープを抑制
                                Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
                                WriteIndented = false,
                            });
                        }

                        /// <summary>
                        /// 現在のセッションの識別子。ログ出力に使用。
                        /// </summary>
                        public virtual string? LogSessionKey => null;
                    {{_sourceCode.OrderBy(source => source).SelectTextTemplate(source => $$"""

                        {{WithIndent(source)}}
                    """)}}
                    }
                    """,
            };
        }
    }
}
