using Nijo.SchemaParsing;
using System.Linq;
using System.Xml.Linq;

namespace Nijo.Constants;

/// <summary>
/// テンプレート文字列の種類を指定する属性。
/// グループに指定するとその中のテンプレート文字列すべての既定値になり、テンプレート文字列の定数に指定すると既定値を上書きする。
/// </summary>
internal sealed class TemplateKindOption : NodeOption {
    internal const string ATTRIBUTE_NAME = "TemplateKind";

    public override string AttributeName => ATTRIBUTE_NAME;
    public override string DisplayName => "テンプレートの種類";
    public override E_NodeOptionType Type => E_NodeOptionType.String;
    public override string HelpText => $$"""
        テンプレート文字列の種類を指定します（URL、文言 など）。
        引数の値は、種類ごとの変換（URL ならエンコードなど）を通してから埋め込まれます。
        変換の中身は {{ConstantTemplateKind.CLASS_NAME}} に、種類と同じ名前の関数として書いてください。
        C# は自動生成されるプロジェクト（Core.AutoGenerated）の直下、TypeScript は React プロジェクトの src フォルダに置きます。
        グループに指定すると、その中のテンプレート文字列すべての既定値になります。
        """;

    public override bool IsAvailable(NodeOptionTarget target) {
        return target.Section == E_Section.Constants;
    }

    public override void Validate(NodeOptionValidateContext ctx) {
        var constantType = ctx.XElement.Attribute(ConstantTypeOption.ATTRIBUTE_NAME)?.Value;
        var isRootGroup = ctx.XElement.Parent?.Parent == ctx.XElement.Document?.Root;
        if (!isRootGroup
            && constantType != ConstantValueDef.CONSTTYPE_CHILD
            && constantType != ConstantValueDef.CONSTTYPE_TEMPLATE) {
            ctx.AddError($"{ATTRIBUTE_NAME} 属性は、グループかテンプレート文字列の定数にだけ指定できます。");
        }

        if (!ConstantsSection.IsValidIdentifier(ctx.Value)) {
            ctx.AddError($"テンプレートの種類「{ctx.Value}」は、関数名として使えないため指定できません。");
        }
    }

    /// <summary>
    /// 定数のテンプレートの種類を、自身から親のグループへ順にさかのぼって探します。
    /// </summary>
    internal static string? Resolve(XElement constantElement) {
        return constantElement
            .AncestorsAndSelf()
            .Select(el => el.Attribute(ATTRIBUTE_NAME)?.Value)
            .FirstOrDefault(kind => kind != null);
    }
}
