using Microsoft.Extensions.Logging;
using Nijo.CodeGenerator;
using Nijo.ImmutableSchema;
using Nijo.SchemaParsing;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Xml.Linq;

namespace Nijo.CodeGenerating {
    /// <summary>
    /// スキーマ定義からアプリケーションのソースコードを自動生成するときのコンテキスト情報
    /// </summary>
    public sealed class CodeRenderingContext : CodeRenderingContext<CodeRenderingContext> {
        internal CodeRenderingContext(GeneratedProject project, GeneratedProjectOptions projectOptions, CodeRenderingOptions renderingOptions, SchemaParseContext xmlParseContext, ApplicationSchema immutableSchema, ILogger logger)
            : base(GetAutoGeneratedDirectories(project)) {
            Project = project;
            Config = projectOptions;
            RenderingOptions = renderingOptions;
            SchemaParser = xmlParseContext;
            Schema = immutableSchema;
            Logger = logger;
        }

        public GeneratedProject Project { get; }
        public GeneratedProjectOptions Config { get; }
        public CodeRenderingOptions RenderingOptions { get; }
        public ApplicationSchema Schema { get; }

        /// <inheritdoc cref="SchemaParseContext"/>
        internal SchemaParseContext SchemaParser { get; }
        internal ILogger Logger { get; }


        #region 自動生成フォルダ
        private const string AUTOGENERATED_CORE = "__AutoGenerated";
        private const string AUTOGENERATED_WEBAPI = "__AutoGenerated";
        private const string AUTOGENERATED_UNIT_TEST = "__AutoGenerated";
        private const string AUTOGENERATED_REACT = "__autoGenerated";

        /// <summary>
        /// C#のクラスライブラリのソースコード自動生成フォルダのルート。
        /// コードが自動生成される主たるプロジェクト。
        /// </summary>
        public void CoreLibrary(Action<DirectorySetupper> setup) {
            Directory(Path.Combine(Project.CoreLibraryRoot, AUTOGENERATED_CORE), setup);
        }
        /// <summary>
        /// ASP.NET Core プロジェクトのソースコード自動生成フォルダのルート。
        /// </summary>
        public void WebapiProject(Action<DirectorySetupper> setup) {
            Directory(Path.Combine(Project.WebapiProjectRoot, AUTOGENERATED_WEBAPI), setup);
        }
        /// <summary>
        /// React.js プロジェクトのソースコード自動生成フォルダのルート。
        /// </summary>
        public void ReactProject(Action<DirectorySetupper> setup) {
            Directory(Path.Combine(Project.ReactProjectRoot, AUTOGENERATED_REACT), setup);
        }
        /// <summary>
        /// ユニットテストのソースコード自動生成フォルダのルート。
        /// </summary>
        public void UnitTestProject(Action<DirectorySetupper> setup) {
            Directory(Path.Combine(Project.UnitTestProjectRoot, AUTOGENERATED_UNIT_TEST), setup);
        }

        private static IEnumerable<string> GetAutoGeneratedDirectories(GeneratedProject project) {
            yield return Path.Combine(project.CoreLibraryRoot, AUTOGENERATED_CORE);
            yield return Path.Combine(project.WebapiProjectRoot, AUTOGENERATED_WEBAPI);
            yield return Path.Combine(project.ReactProjectRoot, AUTOGENERATED_REACT);
            yield return Path.Combine(project.UnitTestProjectRoot, AUTOGENERATED_UNIT_TEST);
        }
        #endregion 自動生成フォルダ
    }
}
