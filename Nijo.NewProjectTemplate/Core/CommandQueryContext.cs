namespace MyApp;

/// <summary>
/// クエリ・コマンドの呼び出し1回について、全処理に共通の入出力。
/// 呼び出し元（Web、バッチ、単体テストなど）が呼び出しのたびに作成して処理に渡し、処理の終了後に中身を読む。
/// 自動生成されたソースはこのクラスの中身を参照しないので、アプリケーションの要件に応じて自由に変更してよい。
/// </summary>
public class CommandQueryContext {

    /// <summary>
    /// コマンドについて、入力チェックのみを行うか、それとも実際の更新処理も行うかを表す。
    ///
    /// Webアプリケーションで何らかのデータを更新する場合、
    /// 1回目のHTTPリクエストでは入力チェックのみを行い、ユーザーに確認メッセージを表示した上で
    /// 2回目のHTTPリクエストで再度入力チェックしたうえで実際の更新処理を行う、という2段階の処理を行うことが多い。
    /// このプロパティが true の場合、入力チェックのみを行い、DB更新などの副作用を起こさない。
    /// </summary>
    public required bool ValidationOnly { get; init; }

    /// <summary>
    /// この処理中で発生した、利用者に向けた確認メッセージ（「保存しますか？」など）の一覧。
    /// 画面で利用者に確認を求めるのか、確認できない呼び出し元（定周期バッチなど）として無視するのかは、呼び出し元が決める。
    /// </summary>
    public List<string> Confirms { get; } = [];
}
