import * as AutoGenerated from "../__autoGenerated"
import { callAspNetCoreApiAsync } from "./callAspNetCoreApiAsync"

/**
 * 自動生成されたクエリ（一覧検索、参照検索）またはコマンドのエンドポイントを呼び出す。
 *
 * HTTPリクエスト・レスポンスの形は NijoAppScaffold として決まった仕様があるわけではなく、
 * サーバー側のエンドポイントの処理と整合性がとれていればよい。
 * ここでは引数を JSON で送り、戻り値とメッセージを JSON で受け取る最も単純な形にしている。
 * アプリケーションの要件に応じて自由に変更してよい。
 *
 * サーバー側で処理が実行されなかった場合（通信エラー、サーバー側の予期しない例外など）は例外を送出する。
 */
export async function callCommandQueryAsync<TName extends AutoGenerated.CommandQuery.Name>(
  name: TName,
  parameter: AutoGenerated.CommandQuery.ParamType[TName],
  signal?: AbortSignal,
): Promise<CommandQueryResult<AutoGenerated.CommandQuery.ReturnType[TName]>> {

  const response = await callAspNetCoreApiAsync(AutoGenerated.CommandQuery.Endpoint[name], {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(parameter ?? {}),
    signal,
  })

  // 200: 処理が成功した。422: 処理は実行されたが、エラーのメッセージがある
  if (response.status !== 200 && response.status !== 422) {
    throw new Error(`HTTP ${response.status} ${response.statusText}: ${await response.text()}`)
  }

  const json = await response.json() as {
    returnValue: AutoGenerated.CommandQuery.ReturnType[TName]
    messages: CommandQueryMessages
  }
  return response.status === 200
    ? { ok: true, returnValue: json.returnValue, messages: json.messages }
    : { ok: false, messages: json.messages }
}

/** {@link callCommandQueryAsync} の結果 */
export type CommandQueryResult<TReturnValue>
  = { ok: true, returnValue: TReturnValue, messages: CommandQueryMessages }
  | { ok: false, messages: CommandQueryMessages }

/**
 * サーバーから返されるメッセージ。
 * 処理の引数と同じ構造をもち、項目ごとにその項目に対するメッセージが格納される。
 * 配列の要素は、配列のインデックスをキーとして children に格納される。
 */
export type CommandQueryMessages = {
  error?: string[]
  warn?: string[]
  info?: string[]
  children?: { [key: string]: CommandQueryMessages }
}
