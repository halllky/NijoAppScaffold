import { createTemplates } from "./__autoGenerated/templates"

/**
 * nijo.xml に定義したテンプレート文字列。
 * 種類ごとの変換は、サーバー側の変換（Core/テンプレート.cs）と同じ結果になるようにすること。
 */
export const テンプレート = createTemplates({
  /** 画面やログに出す文言に埋め込む値 */
  文言: {
    /** 変換しない */
    string: value => value,
    /** 3桁ごとに区切る */
    int: value => new Intl.NumberFormat("ja-JP").format(value),
  },
  /** JSON の文字列リテラルの中に埋め込む値 */
  JSON: {
    /** 引用符やバックスラッシュ、制御文字をエスケープする */
    string: value => JSON.stringify(value).slice(1, -1),
  },
})
