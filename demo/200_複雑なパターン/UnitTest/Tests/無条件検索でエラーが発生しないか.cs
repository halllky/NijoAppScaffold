namespace MyApp.UnitTest;

partial class DB接続あり_更新なし {

    /// <summary>
    /// LINQ式をSQLに変換できないときはこの例外メッセージになる
    /// </summary>
    private const string CANNOT_TRANSRATE_TO_SQL = @"could not be translated. Either rewrite the query in a form that can be translated, or switch to client evaluation explicitly by inserting a call to 'AsEnumerable', 'AsAsyncEnumerable', 'ToList', or 'ToListAsync'. See https://go.microsoft.com/fwlink/?linkid=2101038 for more information.";

    /// <summary>
    /// 式が複雑すぎてSQLに変換できないが（EFCoreの制約）、
    /// 自動生成されたコードでコンパイルエラーが出ないことを確認したいので、あえて残しているクエリの名前
    /// </summary>
    private static readonly HashSet<string> CANNOT_TRANSLATE_TO_SQL_QUERIES = ["アクション結果", "在庫調査報告", "ref-to:アクション"];

    [Category("無条件検索でエラーが発生しないか")]
    [TestCaseSource(typeof(MetadataBasedTestCases), nameof(MetadataBasedTestCases.無条件検索テストケース))]
    public async Task 無条件検索でエラーが発生しないか(
        string queryName,
        Func<AutoGeneratedApplicationService<CommandQueryContext>, Task<IEnumerable<object>>> test) {

        // ダミーデータ投入
        var scope = TestUtilImpl.Instance.CreateScope($"{nameof(無条件検索でエラーが発生しないか)}_{queryName.Replace(':', '_').Replace('/', '_')}");

        var generator = new OverridedDummyDataGenerator();
        await generator.GenerateAsync(scope.App);

        // 無条件検索を実行
        try {
            var result = await test(scope.App);
            scope.App.Log.LogDebug("取得したデータ: {0}", scope.App.SerializeForLog(result));
            Assert.Pass("例外発生せず");

        } catch (InvalidOperationException ex) when (ex.Message.Contains(CANNOT_TRANSRATE_TO_SQL)) {
            if (CANNOT_TRANSLATE_TO_SQL_QUERIES.Contains(queryName)) {
                Assert.Inconclusive(
                    "この集約は式が複雑すぎてSQLに変換できないが（EFCoreの制約）、" +
                    "自動生成されたコードでコンパイルエラーが出ないことを確認したいので、あえて残している。" +
                    "通常の運用では、参照経路が深くなりすぎないよう、RefTo用のQueryModelを別途定義し、それを参照させることで回避する。");
            } else {
                throw;
            }
        }
    }
}

/// <summary>
/// 自動生成されたクエリ（一覧検索、参照検索）の一覧からテストケースを生成するクラス
/// </summary>
public static class MetadataBasedTestCases {

    /// <summary>
    /// 一覧検索と参照検索それぞれについて、検索条件を何も指定せずに検索するテストケース
    /// </summary>
    public static IEnumerable<TestCaseData> 無条件検索テストケース() {
        return CommandQuery<CommandQueryContext>.All
            .Where(commandQuery => commandQuery.IsQuery)
            .Select(commandQuery => new TestCaseData(commandQuery.Name, commandQuery.Accept(new UnconditionalSearch()))
                .SetName($"無条件検索_{commandQuery.Name}"));
    }

    /// <summary>
    /// 検索条件を何も指定せずに検索処理を呼び出し、1ページ目の結果を返す関数を作成する。
    /// </summary>
    private sealed class UnconditionalSearch : ICommandQueryVisitor<CommandQueryContext, Func<AutoGeneratedApplicationService<CommandQueryContext>, Task<IEnumerable<object>>>> {
        public Func<AutoGeneratedApplicationService<CommandQueryContext>, Task<IEnumerable<object>>> Visit<TParameter, TReturnValue, TMessages>(CommandQuery<CommandQueryContext, TParameter, TReturnValue, TMessages> commandQuery)
            where TMessages : IMessageSetter {

            return async app => {
                // 検索条件は1ページ目の件数のみ指定する
                var searchCondition = Activator.CreateInstance<TParameter>();
                typeof(TParameter).GetProperty("Take")?.SetValue(searchCondition, 10);

                var messages = MessageSetter.GetImpl<TMessages>([], new MessageContainer());
                var context = new CommandQueryContext { ValidationOnly = false };
                var result = await commandQuery.InvokeAsync(app, searchCondition, messages, context)
                    ?? throw new Exception(TestFailureMessage.Build($"検索結果が取得できません: {commandQuery.Name}", context, messages));

                // 検索結果の型は検索処理ごとに異なるため、1ページ目のデータはリフレクションで取得する
                var currentPageItems = (IEnumerable?)typeof(TReturnValue)
                    .GetProperty(nameof(LoadReturnType<object>.CurrentPageItems))?
                    .GetValue(result)
                    ?? throw new Exception($"CurrentPageItemsの値が取得できません: {commandQuery.Name}");

                return currentPageItems.Cast<object>();
            };
        }
    }
}
