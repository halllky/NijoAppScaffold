import { createTemplates } from "./__autoGenerated/templates"

/**
 * nijo.xml に定義したテンプレート文字列。画面の URL などを、引数を埋め込んで組み立てる。
 * 使う側では、使うグループを取り出してから呼ぶ（const { PAGES_URL } = テンプレート）。
 * グループの一覧をここに書かないのは、業務ごとのグループを nijo.xml から消したときに、このファイルを直さずに済むようにするため。
 * 種類ごとの変換は、サーバー側の変換（Core/TemplateKind.cs）と同じ結果になるようにすること。
 * サーバーで組み立てた URL と画面で組み立てた URL が食い違わないようにするため。
 */
// 引数の型を書いておくのは、その種類が nijo.xml から無くなっても、この変換をそのまま残しておけるようにするため
export const テンプレート = createTemplates({
  /** 利用者に見せる文言に埋め込む値。変換しない */
  文言: (value: string) => value,
  URL: (value: string) => encodeUrlComponent(value),
})

/**
 * URL のパスやクエリ文字列に埋め込む値。"/" や "?" も含めてパーセントエンコードする。
 * encodeURIComponent は !'()* をエンコードしないが、C# の Uri.EscapeDataString に合わせてこれらもエンコードする。
 */
function encodeUrlComponent(value: string): string {
  return encodeURIComponent(value)
    .replace(/[!'()*]/g, c => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)
}
