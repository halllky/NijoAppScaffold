import React from "react"
import * as AutoGenerated from "../__autoGenerated"
import type * as ログインユーザー情報 from "../__autoGenerated/models/ログインユーザー情報"
import { LoginUserContext } from "./loginUser"

/**
 * ログインユーザーが、そのクエリまたはコマンドを呼び出せるかどうか。
 * nijo.xml で処理ごとに宣言された「呼び出し可能な利用者」と「必要な権限」で決まり、サーバー側の判定（関門）と同じ結果になる。
 * メニュー・ボタン・汎用画面の表示の切り替えに使う。
 * 「内部処理のみ」の処理は WebAPI として公開されていないので、画面からは呼び出せない。
 *
 * @param loginUser ログインユーザー。ログインしていない場合は undefined
 */
export function canInvoke(name: AutoGenerated.Operation.Name, loginUser: ログインユーザー情報.DisplayData | undefined): boolean {
  const metadata = AutoGenerated.Operation.Metadata[name]
  switch (metadata.呼び出し可能な利用者) {
    case 'ログイン不要':
      return true
    case 'ログインユーザー全員':
      return loginUser !== undefined
    case '権限で指定': {
      if (loginUser === undefined) return false
      const permissions = loginUser.ログインユーザー情報の権限.map(x => x.権限区分)
      // システム管理者はすべての権限を持つ
      return permissions.includes('システム管理者')
        || metadata.必要な権限.some(permission => permissions.includes(permission))
    }
    case '内部処理のみ':
      return false
  }
}

/**
 * ログイン中のユーザーが、そのクエリまたはコマンドを呼び出せるかどうかを判定する関数を返す。
 */
export function useCanInvoke(): (name: AutoGenerated.Operation.Name) => boolean {
  const loginUser = React.useContext(LoginUserContext)
  return React.useCallback(name => canInvoke(name, loginUser), [loginUser])
}
