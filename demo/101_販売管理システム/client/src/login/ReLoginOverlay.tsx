import React from "react"
import { createPortal } from "react-dom"
import { Button, PageTitle } from "../ui"
import { useLoginUser } from "./loginUser"
import { LoginForm } from "./LoginForm"
import { useReLoginOverlayRegistration, type ReLoginResult } from "./reLogin"
import type * as ログインユーザー情報 from "../__autoGenerated/models/ログインユーザー情報"

/**
 * ログイン状態が切れていたときに、画面の上に重ねて表示するログインの入力欄。
 * 下の画面は取り除かないので、入力中の内容を失わずにログインし直せる。
 * ページ全体で1つ置く。
 *
 * このページのユーザーとは別のユーザーでログインされた場合は、
 * このページの表示（ログインユーザーや権限）と入力中の内容がそのユーザーのものではなくなるので、ページを読み込み直す。
 */
export function ReLoginOverlay() {
  const pageLoginUser = useLoginUser()

  // 開いている間の、ログインし直しの結果を受け取る呼び出し元の待ち合わせ
  const [pending, setPending] = React.useState<Pending>()
  const pendingRef = React.useRef<Pending>(undefined)

  const open = React.useCallback(() => {
    // 開いている間に呼ばれたら、同じ結果を待たせる
    if (pendingRef.current) return pendingRef.current.promise
    let resolve!: (result: ReLoginResult) => void
    const promise = new Promise<ReLoginResult>(r => { resolve = r })
    const newPending = { promise, resolve }
    pendingRef.current = newPending
    setPending(newPending)
    return newPending.promise
  }, [])
  useReLoginOverlayRegistration(open)

  const close = (result: ReLoginResult) => {
    pending?.resolve(result)
    pendingRef.current = undefined
    setPending(undefined)
  }
  const handleLoggedIn = (user: ログインユーザー情報.DisplayData) => {
    if (user.従業員番号 === pageLoginUser?.従業員番号) {
      close('logged-in')
    } else {
      window.location.reload()
    }
  }

  if (!pending) return null

  return createPortal(
    <div className="fixed inset-0 z-[100] flex items-center justify-center bg-black/50 p-8">
      <div className="bg-white p-8 rounded shadow-md w-full max-w-md">
        <div className="mb-2">
          <PageTitle>ログイン</PageTitle>
        </div>
        <p className="mb-6 text-sm text-gray-700">
          ログイン状態が切れました。ログインし直すと、この画面の操作を続けられます。
        </p>
        <LoginForm defaultUserId={pageLoginUser?.従業員番号 ?? ""} onLoggedIn={handleLoggedIn}>
          <Button onClick={() => close('canceled')}>キャンセル</Button>
        </LoginForm>
      </div>
    </div>,
    document.body,
  )
}

/** ログインし直しの結果を待つ Promise と、それを解決する関数 */
type Pending = {
  promise: Promise<ReLoginResult>
  resolve: (result: ReLoginResult) => void
}
