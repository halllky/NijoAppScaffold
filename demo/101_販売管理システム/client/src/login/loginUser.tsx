import React from "react"
import { createContext, data, isRouteErrorResponse, type MiddlewareFunction } from "react-router-dom"
import { callOperationAsync, type OperationMessages } from "../http/callOperationAsync"
import * as ログインユーザー情報 from "../__autoGenerated/models/ログインユーザー情報"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"

/*
 * ログイン状態は、ページを開いたときにサーバーへ問い合わせ、そのページを開いている間は変えない。
 * ログイン・ログアウトしたときは、ページを読み込み直して問い合わせ直す。
 * ログイン状態はサーバー（とブラウザの Cookie）が持つので、ブラウザの複数のタブで共有される。
 * ログインユーザーが変わったことは、同じブラウザの他のタブにも知らせ、そのタブも読み込み直させる。
 */

/** ログイン中のユーザーの提供元。ページを開いたときに問い合わせた結果を渡す。ログインしていない場合は undefined */
export const LoginUserContext = React.createContext<ログインユーザー情報.DisplayData | undefined>(undefined)

/** ルーティングの処理（ミドルウェアや loader）に渡す、ログイン中のユーザー。ログインしていない場合は undefined */
export const loginUserRouterContext = createContext<ログインユーザー情報.DisplayData | undefined>()

/**
 * 業務画面のルートに付けるミドルウェア。
 * ログインしていなければ、業務画面の読み込み処理（loader）を行わず、ステータス 401 のエラーにする。
 * そのルートのエラー表示（{@link isLoginRequiredError} で判定する）が、業務画面の代わりにログインの入力欄を表示する。
 */
export const requireLogin: MiddlewareFunction = ({ context }) => {
  if (context.get(loginUserRouterContext)) return
  throw data('ログインしていません。', { status: 401 })
}

/** {@link requireLogin} がログインしていないために読み込みを止めたエラーかどうか */
export function isLoginRequiredError(error: unknown): boolean {
  return isRouteErrorResponse(error) && error.status === 401
}

/**
 * ログイン中のユーザー。業務画面の中で使う。
 * 業務画面はログインしていないと表示されないので、常にログイン中のユーザーが返る。業務画面の外で呼んだ場合は例外を投げる。
 */
export function useLoginUser(): ログインユーザー情報.DisplayData {
  const loginUser = React.useContext(LoginUserContext)
  if (!loginUser) throw new Error('ログインしていない状態で、業務画面用のログインユーザーの取得が呼ばれました。')
  return loginUser
}

/**
 * ログイン中のユーザー。ログインしていない場合は undefined。
 * ナビゲーションやログイン画面など、ログインしていなくても表示される部分で使う。
 */
export function useOptionalLoginUser(): ログインユーザー情報.DisplayData | undefined {
  return React.useContext(LoginUserContext)
}

/**
 * ログインする。成功した場合はログインしたユーザーを、失敗した場合はサーバーから返されたメッセージを返す。
 * ログインしたユーザーは同じブラウザの他のタブに知らせる。
 */
export async function loginAsync(data: ログインParameter.DisplayData): Promise<
  | { type: 'ok', user: ログインユーザー情報.DisplayData }
  | { type: 'error', messages: OperationMessages }
> {
  const result = await callOperationAsync('ログイン', data, { confirmed: true })
  if (result.type !== 'ok' || !result.returnValue) {
    return { type: 'error', messages: result.type === 'error' ? result.messages : { error: ['ログインできませんでした。'] } }
  }
  const user = { ...ログインユーザー情報.createNewDisplayData(), ...result.returnValue }
  shareLoginUserId(user.従業員番号 ?? undefined)
  return { type: 'ok', user }
}

/**
 * ログアウトし、同じブラウザの他のタブに知らせる。
 * ログアウト状態をこのページに反映するには、この後でページを読み込み直すこと。
 * サーバー側の原因で失敗しても、読み込み直したページでログイン状態を問い合わせ直すので、結果は返さない。
 */
export async function logoutAsync(): Promise<void> {
  await callOperationAsync('ログアウト', {}, { confirmed: true })
  shareLoginUserId(undefined)
}

/**
 * ページを開いたときに呼ぶ。
 * このページのログインユーザーを同じブラウザの他のタブに知らせ、
 * 以後、他のタブでログインユーザーが変わったら（ログアウトを含む）このページを読み込み直す。
 * 編集中の内容がある場合は、読み込み直す前にブラウザが利用者に確認する。
 */
export function startSharingLoginUser(pageLoginUser: ログインユーザー情報.DisplayData | undefined): void {
  const pageLoginUserId = pageLoginUser?.従業員番号 ?? undefined
  if (pageLoginUserId !== undefined) shareLoginUserId(pageLoginUserId)

  window.addEventListener("storage", e => {
    if (e.key === LOGIN_USER_ID_STORAGE_KEY && e.newValue !== (pageLoginUserId ?? null)) {
      window.location.reload()
    }
  })
}

/**
 * ログインユーザーを同じブラウザの他のタブに知らせる。ログアウトした場合は undefined。
 * 正本はサーバーのログイン状態なので、知らせるのはユーザーを識別する値だけにする。
 * localStorage を使えない環境では、他のタブに知らせないだけで、このタブの動作には影響しない。
 */
function shareLoginUserId(id: string | undefined): void {
  try {
    if (id === undefined) localStorage.removeItem(LOGIN_USER_ID_STORAGE_KEY)
    else localStorage.setItem(LOGIN_USER_ID_STORAGE_KEY, id)
  } catch { /* 上記のとおり無視する */ }
}

/** 同じブラウザの他のタブに、ログインユーザーを知らせるための localStorage のキー */
const LOGIN_USER_ID_STORAGE_KEY = "nijo-login-user-id"
