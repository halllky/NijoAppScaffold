import { Outlet, redirect, RouteObject } from "react-router-dom"
import AutoIndex from "./auto-pages/自動生成画面一覧"
import AutoSearch from "./auto-pages/自動生成QueryModel"
import AutoCommand from "./auto-pages/自動生成CommandModel"
import { 検索ダイアログ一覧 } from "./auto-pages/検索ダイアログ一覧"
import DbViewer from "./debug-rooms/db-viewer/DbViewer"
import UiSamples from "./debug-rooms/ui"
import { loginRoute } from "./pages/P001_ログイン"
import { ErrorPage, SearchDialogHost } from "./ui"
import { toLoginUrl } from "./login/sessionExpiry"
import type * as ログインユーザー情報 from "./__autoGenerated/models/ログインユーザー情報"

/**
 * React Router ルーティング定義。
 * URLと画面の対応関係などを規定する。
 *
 * ログインしていない場合は業務画面を登録せず、業務画面の URL はすべてログイン画面に移す。
 * 業務画面の loader がサーバーを呼んでから、ログインしていないことが分かるのを防ぐため。
 * ログイン状態はページを開いている間は変わらないので、ページを開いたときに一度だけ組み立てる。
 */
export function createRoutes(loginUser: ログインユーザー情報.DisplayData | undefined): RouteObject[] {
  return [
    // ログイン画面。ログインしていなくても開けるよう、業務画面とは別に登録する
    loginRoute,

    // 業務画面
    loginUser ? {
      element: (
        <SearchDialogHost dialogs={検索ダイアログ一覧}>
          <Outlet />
        </SearchDialogHost>
      ),
      children: [
        // 業務画面のフォルダ直下の各画面
        ...collectPageRoutes(),
        // メタデータから組み立てた画面
        AutoIndex,
        AutoSearch,
        AutoCommand,
      ],
      // loader などでエラーが発生した場合に表示するエラーページ
      errorElement: <ErrorPage />,
    } : {
      path: "*",
      loader: ({ request }) => {
        const url = new URL(request.url)
        return redirect(toLoginUrl(url.pathname + url.search))
      },
    },

    // デバッグ用画面。開発環境でのみ表示。
    // ログインしていなくても表示できる。
    ...(!import.meta.env.DEV ? [] : [
      {
        element: (
          <Outlet />
        ),
        children: [
          // ui の部品の動作確認画面
          ...UiSamples,
          DbViewer,
        ]
      },
    ]),
  ]
}

/**
 * 業務画面のフォルダ直下のモジュールが default export するルーティング定義を集める。
 * default export はルーティング定義1つでも配列でもよい。default export を持たないモジュールは対象外。
 */
function collectPageRoutes(): RouteObject[] {
  const modules = import.meta.glob<{ default?: RouteObject | RouteObject[] }>("./pages/*.tsx", { eager: true })
  return Object.values(modules).flatMap(module => module.default ?? [])
}
