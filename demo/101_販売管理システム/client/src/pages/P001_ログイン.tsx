import React from "react"
import useEvent from "react-use-event-hook"
import { Button, FieldColumn, FieldGroup, NowLoading, PageTitle, useDisplayDataForm } from "../ui"
import { loginAsync, useOptionalLoginUser } from "../login/loginUser"
import { finishLoginRequest, useIsLoginRequested, type LoginRequestResult } from "../login/loginRequest"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"

/**
 * P001 ログイン。
 * ログインが要求されたら、画面を覆うようにログインの入力欄をモーダルダイアログで表示する。ページ全体で1つ置く。
 *
 * - ページを開いたときにログインしていなかった場合は（業務画面を開こうとしたときに要求される）、ページ全体を覆って表示する。
 *   ログインしたら、ログイン状態を画面全体に反映するためページを読み込み直す。URL はそのままなので、開こうとした画面が表示される。
 * - 操作中にログイン状態が切れていた場合は（サーバーの呼び出しから要求される）、画面の上に重ねて表示する。
 *   画面は取り除かないので、入力中の内容は残る。同じユーザーでログインし直したら、要求した呼び出しを続けさせる。
 *   別のユーザーでログインした場合は、画面の表示と入力中の内容がそのユーザーのものではなくなるので、ページを読み込み直す。
 */
export function P001_ログイン() {
  const pageLoginUser = useOptionalLoginUser()
  const isShown = useIsLoginRequested()
  const close = (result: LoginRequestResult) => {
    setServerMessages(undefined)
    finishLoginRequest(result)
  }

  // ログイン情報のフォーム。
  // 開発環境では、動作確認の手間を省くため、ダミーデータの管理者アカウントを入れておく
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(ログインParameter, {
    defaultValues: {
      ...ログインParameter.createNewDisplayData(),
      従業員番号: pageLoginUser?.従業員番号 ?? (import.meta.env.DEV ? "admin" : ""),
      パスワード: import.meta.env.DEV ? "password123" : "",
    },
  })
  const { setFocus, handleSubmit, formState: { isSubmitting } } = formMethods
  const [isReloading, setIsReloading] = React.useState(false)

  // モーダルダイアログとして開き、背後の画面を操作できないようにする（ブラウザ標準の dialog の振る舞い）。
  // 開いたら、まだ入力されていない欄にフォーカスする
  const dialogRef = React.useRef<HTMLDialogElement>(null)
  React.useEffect(() => {
    const dialog = dialogRef.current
    if (!dialog) return
    if (isShown && !dialog.open) {
      dialog.showModal()
      setFocus(pageLoginUser ? "パスワード" : "従業員番号")
    } else if (!isShown && dialog.open) {
      dialog.close()
    }
  }, [isShown, pageLoginUser, setFocus])

  // Esc キーで閉じようとしたとき。ログインし直しの場合はキャンセルと同じ。ページを開いたときのログインは閉じられない
  const handleCancel = (e: React.SyntheticEvent<HTMLDialogElement>) => {
    e.preventDefault()
    if (pageLoginUser) close('canceled')
  }

  // ログイン実行。失敗した場合はサーバーから返されたメッセージを表示する
  const onSubmit = useEvent(async (data: ログインParameter.DisplayData) => {
    const result = await loginAsync(data)
    if (result.type === 'error') {
      setServerMessages(result.detail)
    } else if (pageLoginUser && result.user.従業員番号 === pageLoginUser.従業員番号) {
      close('logged-in')
    } else {
      setIsReloading(true)
      window.location.reload()
    }
  })

  return (
    <dialog
      ref={dialogRef}
      onCancel={handleCancel}
      className={`m-auto bg-white p-8 rounded shadow-md w-full max-w-md ${pageLoginUser ? 'backdrop:bg-black/50' : 'backdrop:bg-gray-100'}`}
    >
      <div className="relative">
        <div className="mb-6">
          <PageTitle>ログイン</PageTitle>
          {pageLoginUser && (
            <p className="mt-2 text-sm text-gray-700">
              ログイン状態が切れました。ログインし直すと、この画面の操作を続けられます。
            </p>
          )}
        </div>
        <form noValidate onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-4">
          <RootErrors />
          <FieldGroup>
            <FieldColumn>
              <FieldLabel name="従業員番号">
                <Input.TextBox name="従業員番号" className="w-full" />
              </FieldLabel>
              <FieldLabel name="パスワード">
                <Input.TextBox name="パスワード" masked className="w-full" />
              </FieldLabel>
            </FieldColumn>
          </FieldGroup>
          <div className="flex gap-2 mt-4">
            <Button submit fill disabled={isSubmitting} className="flex-1 justify-center">ログイン</Button>
            {pageLoginUser && <Button onClick={() => close('canceled')}>キャンセル</Button>}
          </div>
        </form>
        {(isSubmitting || isReloading) && <NowLoading />}
      </div>
    </dialog>
  )
}
