import React from "react"
import * as ReactRouter from "react-router-dom"
import useEvent from "react-use-event-hook"
import { Button, ErrorPage, FieldColumn, FieldGroup, NowLoading, PageBase, PageTitle, useDisplayDataForm } from "../ui"
import { isLoginRequiredError, loginAsync, useOptionalLoginUser } from "../login/loginUser"
import { finishLoginRequest, useIsLoginRequested, type LoginRequestResult } from "../login/loginRequest"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"
import type * as ログインユーザー情報 from "../__autoGenerated/models/ログインユーザー情報"

/**
 * P001 ログイン。ログインの入力欄は、ログインが必要になった場面に応じて次の2通りで表示する。
 *
 * - ログインしていない状態で業務画面を開こうとした場合は、業務画面の代わりに表示する（{@link P001_ログイン}）。
 *   ナビゲーションは隠さないので、ログインしなくても開ける画面（開発環境のデバッグメニューなど）にはそのまま移れる。
 *   ログインしたら、ログイン状態を画面全体に反映するためページを読み込み直す。URL はそのままなので、開こうとした画面が表示される。
 * - 操作中にログイン状態が切れていた場合は（サーバーの呼び出しから要求される）、画面の上にモーダルダイアログで重ねて表示する（{@link P001_ログインし直しダイアログ}）。
 *   画面は取り除かないので、入力中の内容は残る。同じユーザーでログインし直したら、要求した呼び出しを続けさせる。
 *   別のユーザーでログインした場合は、画面の表示と入力中の内容がそのユーザーのものではなくなるので、ページを読み込み直す。
 */
export function P001_ログイン() {
  const error = ReactRouter.useRouteError()
  if (!isLoginRequiredError(error)) return <ErrorPage />

  return (
    <PageBase
      browserTitle="ログイン"
      className="items-center justify-center"
      contents={(
        <div className="bg-white p-8 rounded shadow-md w-full max-w-md">
          <LoginForm onLoggedIn={() => window.location.reload()} />
        </div>
      )}
    />
  )
}

/**
 * 操作中にログイン状態が切れていたときに、画面の上に重ねて表示するログインの入力欄。ページ全体で1つ置く。
 * 背後の画面を操作できないよう、モーダルダイアログとして開く（ブラウザ標準の dialog の振る舞い）。
 */
export function P001_ログインし直しダイアログ() {
  const pageLoginUser = useOptionalLoginUser()
  const isShown = useIsLoginRequested()
  const close = (result: LoginRequestResult) => finishLoginRequest(result)

  // 入力欄のフォーカスより先に開くため、レイアウトエフェクトで開閉する
  const dialogRef = React.useRef<HTMLDialogElement>(null)
  React.useLayoutEffect(() => {
    const dialog = dialogRef.current
    if (!dialog) return
    if (isShown && !dialog.open) dialog.showModal()
    if (!isShown && dialog.open) dialog.close()
  }, [isShown])

  // Esc キーで閉じようとしたときは、キャンセルと同じにする
  const handleCancel = (e: React.SyntheticEvent<HTMLDialogElement>) => {
    e.preventDefault()
    close('canceled')
  }

  // ページを開いたときと同じユーザーでログインし直したら、要求した呼び出しを続けさせる。それ以外は読み込み直す
  const handleLoggedIn = (user: ログインユーザー情報.DisplayData) => {
    if (pageLoginUser && user.従業員番号 === pageLoginUser.従業員番号) {
      close('logged-in')
    } else {
      window.location.reload()
    }
  }

  return (
    <dialog
      ref={dialogRef}
      onCancel={handleCancel}
      className="m-auto bg-white p-8 rounded shadow-md w-full max-w-md backdrop:bg-black/50"
    >
      {/* 閉じている間は入力欄を描画しない。開くたびに入力欄とメッセージが初期状態に戻る */}
      {isShown && (
        <LoginForm
          message="ログイン状態が切れました。ログインし直すと、この画面の操作を続けられます。"
          onLoggedIn={handleLoggedIn}
          onCancel={() => close('canceled')}
        />
      )}
    </dialog>
  )
}

/**
 * ログインの入力欄。ログインに失敗した場合はサーバーから返されたメッセージを表示する。
 */
function LoginForm({ message, onLoggedIn, onCancel }: {
  /** 見出しの下に表示する説明 */
  message?: string
  /** ログインに成功したとき。ページを読み込み直す場合は、読み込みが終わるまでローディング表示を続ける */
  onLoggedIn: (user: ログインユーザー情報.DisplayData) => void
  /** 指定した場合はキャンセルボタンを表示する */
  onCancel?: () => void
}) {
  const pageLoginUser = useOptionalLoginUser()

  // 開発環境では、動作確認の手間を省くため、ダミーデータの管理者アカウントを入れておく
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(ログインParameter, {
    defaultValues: {
      ...ログインParameter.createNewDisplayData(),
      従業員番号: pageLoginUser?.従業員番号 ?? (import.meta.env.DEV ? "admin" : ""),
      パスワード: import.meta.env.DEV ? "password123" : "",
    },
  })
  const { setFocus, handleSubmit, formState: { isSubmitting } } = formMethods
  const [isLoggedIn, setIsLoggedIn] = React.useState(false)

  // まだ入力されていない欄にフォーカスする
  React.useEffect(() => {
    setFocus(pageLoginUser ? "パスワード" : "従業員番号")
  }, [pageLoginUser, setFocus])

  const onSubmit = useEvent(async (data: ログインParameter.DisplayData) => {
    const result = await loginAsync(data)
    if (result.type === 'error') {
      setServerMessages(result.messages)
    } else {
      setIsLoggedIn(true)
      onLoggedIn(result.user)
    }
  })

  return (
    <div className="relative">
      <div className="mb-6">
        <PageTitle>ログイン</PageTitle>
        {message && (
          <p className="mt-2 text-sm text-gray-700">{message}</p>
        )}
      </div>
      <form noValidate onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-4">
        <RootErrors />
        <FieldGroup>
          <FieldColumn>
            <FieldLabel name="従業員番号">
              <Input.TextBox name="従業員番号" className="w-full" />
            </FieldLabel>
            <FieldLabel name="パスワード">
              <Input.TextBox name="パスワード" masked className="w-full" />
            </FieldLabel>
          </FieldColumn>
        </FieldGroup>
        <div className="flex gap-2 mt-4">
          <Button submit fill disabled={isSubmitting} className="flex-1 justify-center">ログイン</Button>
          {onCancel && <Button onClick={onCancel}>キャンセル</Button>}
        </div>
      </form>
      {(isSubmitting || isLoggedIn) && <NowLoading />}
    </div>
  )
}
