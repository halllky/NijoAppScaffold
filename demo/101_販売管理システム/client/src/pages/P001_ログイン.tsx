import React from "react"
import { createPortal } from "react-dom"
import useEvent from "react-use-event-hook"
import { Button, FieldColumn, FieldGroup, NowLoading, PageTitle, useDisplayDataForm } from "../ui"
import { loginAsync, useLoginUser } from "../login/loginUser"
import { useReLoginOverlayRegistration, type ReLoginResult } from "../login/reLogin"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"

/**
 * P001 ログイン。
 * 業務画面をすべて children として持ち、ログインしていなければ業務画面を覆うようにログインの入力欄を表示する。
 *
 * - ページを開いたときにログインしていなかった場合は、業務画面の代わりにページ全体を覆って表示する。
 *   ログインしたら、ログイン状態を画面全体に反映するためページを読み込み直す。URL はそのままなので、開こうとした画面が表示される。
 * - 操作中にログイン状態が切れていた場合は、業務画面の上に重ねて表示する。業務画面は取り除かないので、入力中の内容は残る。
 *   同じユーザーでログインし直したら、待っていたサーバーの呼び出しを続けさせる。
 *   別のユーザーでログインした場合は、画面の表示と入力中の内容がそのユーザーのものではなくなるので、ページを読み込み直す。
 */
export function P001_ログイン({ children }: { children: React.ReactNode }) {
  const pageLoginUser = useLoginUser()

  // 操作中にログイン状態が切れていた場合の、ログインし直しを待っている呼び出し元との待ち合わせ。
  // 複数の呼び出し元から同時に開かれても、同じ結果を待たせる
  const [pending, setPending] = React.useState<Pending>()
  const pendingRef = React.useRef<Pending>(undefined)
  useReLoginOverlayRegistration(React.useCallback(() => {
    if (pendingRef.current) return pendingRef.current.promise
    let resolve!: (result: ReLoginResult) => void
    const promise = new Promise<ReLoginResult>(r => { resolve = r })
    pendingRef.current = { promise, resolve }
    setPending(pendingRef.current)
    return promise
  }, []))
  const close = (result: ReLoginResult) => {
    pendingRef.current?.resolve(result)
    pendingRef.current = undefined
    setPending(undefined)
    setServerMessages(undefined)
  }

  // ログイン情報のフォーム。パスワードの初期値はデモ用のアカウントのもの
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(ログインParameter, {
    defaultValues: {
      ...ログインParameter.createNewDisplayData(),
      従業員番号: pageLoginUser?.従業員番号 ?? "admin",
      パスワード: "password123",
    },
  })
  const { setFocus, handleSubmit, formState: { isSubmitting } } = formMethods
  const [isReloading, setIsReloading] = React.useState(false)
  const isShown = !pageLoginUser || pending !== undefined

  // 表示されたら、まだ入力されていない欄にフォーカスする
  React.useEffect(() => {
    if (isShown) setFocus(pageLoginUser ? "パスワード" : "従業員番号")
  }, [isShown, pageLoginUser, setFocus])

  // ログイン実行。失敗した場合はサーバーから返されたメッセージを表示する
  const onSubmit = useEvent(async (data: ログインParameter.DisplayData) => {
    const result = await loginAsync(data)
    if (result.type === 'error') {
      setServerMessages(result.detail)
    } else if (pageLoginUser && result.user.従業員番号 === pageLoginUser.従業員番号) {
      close('logged-in')
    } else {
      setIsReloading(true)
      window.location.reload()
    }
  })

  return (
    <>
      {pageLoginUser && children}

      {isShown && createPortal(
        <div className={`fixed inset-0 z-[100] flex items-center justify-center p-8 ${pageLoginUser ? 'bg-black/50' : 'bg-gray-100'}`}>
          <div className="relative bg-white p-8 rounded shadow-md w-full max-w-md">
            <div className="mb-6">
              <PageTitle>ログイン</PageTitle>
              {pageLoginUser && (
                <p className="mt-2 text-sm text-gray-700">
                  ログイン状態が切れました。ログインし直すと、この画面の操作を続けられます。
                </p>
              )}
            </div>
            <form noValidate onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-4">
              <RootErrors />
              <FieldGroup>
                <FieldColumn>
                  <FieldLabel name="従業員番号">
                    <Input.TextBox name="従業員番号" className="w-full" />
                  </FieldLabel>
                  <FieldLabel name="パスワード">
                    <Input.TextBox name="パスワード" masked className="w-full" />
                  </FieldLabel>
                </FieldColumn>
              </FieldGroup>
              <div className="flex gap-2 mt-4">
                <Button submit fill disabled={isSubmitting} className="flex-1 justify-center">ログイン</Button>
                {pageLoginUser && <Button onClick={() => close('canceled')}>キャンセル</Button>}
              </div>
            </form>
            {(isSubmitting || isReloading) && <NowLoading />}
          </div>
        </div>,
        document.body,
      )}
    </>
  )
}

/** ログインし直しの結果を待つ Promise と、それを解決する関数 */
type Pending = {
  promise: Promise<ReLoginResult>
  resolve: (result: ReLoginResult) => void
}
