import React from "react"
import * as ReactRouter from "react-router-dom"
import useEvent from "react-use-event-hook"
import { Button, FieldColumn, FieldGroup, NowLoading, PageTitle, useDisplayDataForm } from "../ui"
import { loginAsync, useLoginUser } from "../login/loginUser"
import { getReturnTo, LOGIN_URL } from "../login/sessionExpiry"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"

/**
 * ルーティング定義。
 *
 * default export していないのは、ログインしていなくても開けるよう、
 * 業務画面のようなワイルドカードでの収集ではなく明示的登録にするため。
 */
export const loginRoute = {
  path: LOGIN_URL,
  element: <P001_ログイン />,
} satisfies ReactRouter.RouteObject

/**
 * P001 ログイン。
 * ログインしたら、ログイン画面に来る前に開こうとしていた画面（URL のクエリパラメータ returnTo）に移る。
 * ログイン状態を画面全体に反映するため、画面の移動はページの読み込み直しで行う。
 */
function P001_ログイン() {
  const loginUser = useLoginUser()
  const [searchParams] = ReactRouter.useSearchParams()
  const returnTo = getReturnTo(searchParams)

  // ログイン情報のフォーム
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(ログインParameter, {
    defaultValues: createInitialValues(),
  })
  const { setFocus, handleSubmit, formState: { isSubmitting } } = formMethods
  const [isReloading, setIsReloading] = React.useState(false)

  // ログイン画面が表示されたら従業員番号の入力欄にフォーカスする
  React.useEffect(() => {
    setFocus("従業員番号")
  }, [setFocus])

  // ログイン実行。失敗した場合はサーバーから返されたメッセージを表示する
  const onSubmit = useEvent(async (data: ログインParameter.DisplayData) => {
    const errors = await loginAsync(data)
    if (errors) {
      setServerMessages(errors)
      return
    }
    setIsReloading(true)
    window.location.assign(returnTo)
  })

  // ログイン済みならログイン画面は不要
  if (loginUser) return <ReactRouter.Navigate to={returnTo} replace />

  return (
    <div className="min-h-full flex items-center justify-center bg-gray-100">
      <div className="relative bg-white p-8 rounded shadow-md w-full max-w-md">
        <div className="mb-6">
          <PageTitle>ログイン</PageTitle>
        </div>
        <form noValidate onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-4">

          {/* どの項目にも表示されないメッセージ */}
          <RootErrors />

          {/* 入力欄 */}
          <FieldGroup>
            <FieldColumn>
              <FieldLabel name="従業員番号">
                <Input.TextBox name="従業員番号" className="w-full" />
              </FieldLabel>
              <FieldLabel name="パスワード">
                <Input.TextBox name="パスワード" masked className="w-full" />
              </FieldLabel>
            </FieldColumn>
          </FieldGroup>

          {/* ログインボタン */}
          <Button submit fill disabled={isSubmitting} className="justify-center mt-4">ログイン</Button>
        </form>

        {/* ログイン中と、ログインに成功してページを読み込み直している間 */}
        {(isSubmitting || isReloading) && <NowLoading />}
      </div>
    </div>
  )
}

/** ログイン画面を開いたときの入力内容。デモ用の管理者アカウントを入れておく */
function createInitialValues(): ログインParameter.DisplayData {
  return {
    ...ログインParameter.createNewDisplayData(),
    従業員番号: "admin",
    パスワード: "password123",
  }
}
