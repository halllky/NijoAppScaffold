import React from "react"
import * as ReactRouter from "react-router-dom"
import useEvent from "react-use-event-hook"
import { Button, FieldColumn, FieldGroup, NowLoading, PageTitle, useDisplayDataForm } from "../ui"
import { useLoginLogout } from "../useLoginLogout"
import * as ログインParameter from "../__autoGenerated/models/ログインParameter"

/**
 * ログイン画面。
 * ログインしていない状態の場合はこのコンポーネント自身が定義するUIを表示。
 * ログインしている状態の場合は、props.childrenで指定されたアプリケーション本体の画面を表示する。
 *
 * ログイン状態は sessionStorage を使ってブラウザの複数タブ間で共有する。
 */
export function P001_ログイン(props: {
  /**
   * ログイン後画面。
   * ログインしていない状態では表示されない。
   */
  children: React.ReactNode
}) {

  // ログイン状態
  const { loginUser, loginAsync, initializing } = useLoginLogout()

  // ログイン情報のフォーム
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(ログインParameter, {
    defaultValues: createInitialValues(),
  })
  const { setFocus, handleSubmit, formState: { isSubmitting } } = formMethods

  // 初期表示時、またはログアウト後。ログイン画面が表示されたら従業員番号の入力欄にフォーカスする
  React.useEffect(() => {
    if (!initializing && !loginUser) {
      setFocus("従業員番号")
    }
  }, [initializing, loginUser, setFocus])

  // ログインしていない間に表示しようとした画面の読み込み処理は失敗しているので、ログインしたらやり直す（SES-005, AUTH-006）
  const { revalidate } = ReactRouter.useRevalidator()
  const wasLoggedOut = React.useRef(false)
  React.useEffect(() => {
    if (initializing) return
    if (!loginUser) {
      wasLoggedOut.current = true
    } else if (wasLoggedOut.current) {
      wasLoggedOut.current = false
      revalidate()
    }
  }, [initializing, loginUser, revalidate])

  // ログイン実行。失敗した場合はサーバーから返されたメッセージを表示する
  const onSubmit = useEvent(async (data: ログインParameter.DisplayData) => {
    setServerMessages(await loginAsync(data))
  })

  // 初期化中の場合は何も表示しない
  if (initializing) return null

  // ログインしていない場合はログイン画面を表示
  if (!loginUser) return (
    <div className="min-h-full flex items-center justify-center bg-gray-100">
      <div className="relative bg-white p-8 rounded shadow-md w-full max-w-md">
        <div className="mb-6">
          <PageTitle>ログイン</PageTitle>
        </div>
        <form noValidate onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-4">

          {/* どの項目にも表示されないメッセージ */}
          <RootErrors />

          {/* 入力欄 */}
          <FieldGroup>
            <FieldColumn>
              <FieldLabel name="従業員番号">
                <Input.TextBox name="従業員番号" className="w-full" />
              </FieldLabel>
              <FieldLabel name="パスワード">
                <Input.TextBox name="パスワード" masked className="w-full" />
              </FieldLabel>
            </FieldColumn>
          </FieldGroup>

          {/* ログインボタン */}
          <Button submit fill disabled={isSubmitting} className="justify-center mt-4">ログイン</Button>
        </form>

        {isSubmitting && <NowLoading />}
      </div>
    </div>
  )

  // ログインしている場合は、子コンポーネントを表示
  return <>{props.children}</>
}

/** ログイン画面を開いたときの入力内容。デモ用の管理者アカウントを入れておく */
function createInitialValues(): ログインParameter.DisplayData {
  return {
    ...ログインParameter.createNewDisplayData(),
    従業員番号: "admin",
    パスワード: "password123",
  }
}
