/**
 * 権限が変わった行の willBeChanged を立てる。
 * 自動生成のディープイコール関数は参照先の子配列を比較しないので、権限の変更はここで判定する。
 */
function mark権限ChangedRows(searched: 従業員一括更新Parameter.DisplayData, current: 従業員一括更新Parameter.DisplayData) {
  const to権限Set = (row: 従業員一括更新Parameter.DisplayData['更新対象従業員一覧'][number]) =>
    new Set(row.従業員.従業員マスタの権限.map(x => x.権限区分))
  const searchedRows = new Map(searched.更新対象従業員一覧.map(row => [row.instanceId, row]))

  for (const row of current.更新対象従業員一覧) {
    const searchedRow = searchedRows.get(row.instanceId)
    if (!searchedRow) continue
    const before = to権限Set(searchedRow)
    const after = to権限Set(row)
    if (before.size !== after.size || [...after].some(x => !before.has(x))) row.willBeChanged = true
  }
}

