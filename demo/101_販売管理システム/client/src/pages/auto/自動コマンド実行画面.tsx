/** パラメータ・戻り値の見出し */
function SectionTitle({ children }: { children: React.ReactNode }) {
  return (
    <h2 className="font-bold text-gray-700 border-b border-gray-400 select-none">
      {children}
    </h2>
  )
}

/** 項目の無いメタデータの表。引数なしのコマンドのパラメータに使う。描画のたびに別の参照にならないようモジュールのトップレベルに置く */
const EMPTY_TABLE: AutoGenerated.AggregateMetadata.Table = {}

/** URL で指定された文字列がコマンドの種類かどうか */
function isCommandModelType(value: string | undefined): value is AutoGenerated.CommandModelType {
  return (AutoGenerated.getCommandModelTypeList() as string[]).includes(value ?? '')
}
