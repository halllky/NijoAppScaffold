import React from "react"
import * as ReactRouter from "react-router-dom"
import * as AutoGenerated from "../../__autoGenerated"
import { AutoDisplayDataFields, AutoSearchConditionFields, Breadcrumb, Button, PageBase, PageTitle, useDisplayDataForm, useSearchConditionForm, type DisplayDataBase, type SearchConditionBase } from "../../ui"
import { callComplexPostEndpointAsync } from "../../example/callComplexPostEndpointAsync"
import { AUTO_INDEX_PAGE_URL, AUTO_PAGE_BREADCRUMB } from "./自動生成画面URL"

/**
 * ルーティング定義
 */
export default {
  path: `${AUTO_INDEX_PAGE_URL}/command/:commandModel`,
  element: <自動コマンド実行画面Route />,
} satisfies ReactRouter.RouteObject

/** URL で指定されたコマンドの実行画面を表示する */
function 自動コマンド実行画面Route() {
  const { commandModel } = ReactRouter.useParams()
  if (!isCommandModelType(commandModel)) {
    return <div className="p-8">コマンド「{commandModel}」はありません。</div>
  }
  // コマンドが変わったら画面を作り直す。フォームはメタデータを最初に渡したものから変えられないため
  return <自動コマンド実行画面 key={commandModel} commandModel={commandModel} />
}

/**
 * コマンドのパラメータと戻り値のメタデータから組み立てたコマンド実行画面。
 * パラメータを入力して実行し、成功したら戻り値を読み取り専用で表示する。
 * 確認メッセージの表示とサーバー側の検証はサーバー呼び出しの仕組みに任せ、画面では入力制約のほかの検証を行わない。
 *
 * パラメータを編集中は画面離脱時に確認する。編集中かどうかはパラメータのフォームが知っているので、
 * ページの枠はパラメータの形ごとのコンポーネントが描画し、この関数はどちらを使うかと戻り値の表示だけを受け持つ。
 */
function 自動コマンド実行画面({ commandModel }: { commandModel: AutoGenerated.CommandModelType }) {
  const paramMetadata = AutoGenerated.CommandParam.metadata[commandModel]
  const returnValueMetadata = AutoGenerated.CommandReturnValue.metadata[commandModel]

  // 最後に成功した実行の戻り値。戻り値の表示欄は実行のたびに作り直すので、何回目の実行かも持つ
  const [executed, setExecuted] = React.useState<{ returnValue: unknown, count: number }>()
  const handleExecuted = (returnValue: unknown) => {
    setExecuted(prev => ({ returnValue, count: (prev?.count ?? 0) + 1 }))
  }

  // 戻り値の欄。まだ成功していなければ表示しない
  const returnValueSection = executed && (
    <section className="flex flex-col gap-2">
      <SectionTitle>戻り値</SectionTitle>
      {returnValueMetadata === null ? (
        <p className="text-sm">正常に終了しました。</p>
      ) : returnValueMetadata.kind === 'search-condition' ? (
        <SearchConditionReturnValue key={executed.count} commandModel={commandModel} entry={returnValueMetadata.entry} returnValue={executed.returnValue} />
      ) : (
        <DisplayDataReturnValue key={executed.count} commandModel={commandModel} table={returnValueMetadata.entry.displayData} returnValue={executed.returnValue} />
      )}
    </section>
  )

  // パラメータの形ごとの画面。引数なしのコマンドは項目の無いフォームになる
  return paramMetadata?.kind === 'search-condition' ? (
    <SearchConditionParameterPage
      commandModel={commandModel}
      entry={paramMetadata.entry}
      onExecuted={handleExecuted}
      returnValueSection={returnValueSection}
    />
  ) : (
    <DisplayDataParameterPage
      commandModel={commandModel}
      table={paramMetadata?.entry.displayData ?? EMPTY_TABLE}
      onExecuted={handleExecuted}
      returnValueSection={returnValueSection}
    />
  )
}

/** パラメータの形ごとの画面が共通で受け取る props */
type ParameterPageProps = {
  commandModel: AutoGenerated.CommandModelType
  /** 実行が成功したときに、サーバーからの戻り値を受け取る */
  onExecuted: (returnValue: unknown) => void
  /** パラメータの欄の下に表示する戻り値の欄 */
  returnValueSection: React.ReactNode
}

/** 画面表示用データの形のパラメータを入力して実行する画面 */
function DisplayDataParameterPage({ commandModel, table, onExecuted, returnValueSection }: ParameterPageProps & {
  table: AutoGenerated.AggregateMetadata.Table
}) {
  // パラメータのフォーム
  const form = useDisplayDataForm<DisplayDataBase, AutoGenerated.AggregateMetadata.Table>({
    metadata: { displayData: table },
    createNewDisplayData: AutoGenerated.CommandParam.create[commandModel] as () => DisplayDataBase,
  })
  const { formMethods: { handleSubmit, reset, formState: { isDirty, isSubmitting } }, RootErrors, setServerMessages } = form

  // 実行。サーバーからのメッセージは成功・失敗のどちらでも表示する。
  // 成功したら、実行したパラメータを編集前の状態とする。実行済みの内容で画面離脱時の確認が出ないようにするため
  const handleExecute = handleSubmit(async values => {
    const result = await callComplexPostEndpointAsync(commandModel, values as AutoGenerated.ExecuteFeature.ParamType[typeof commandModel])
    if (result.type === 'canceled') return
    setServerMessages(result.detail)
    if (result.type === 'ok') {
      reset(values)
      onExecuted(result.returnValue)
    }
  })

  return (
    <CommandPageLayout commandModel={commandModel} isDirty={isDirty} returnValueSection={returnValueSection}>
      {/* 検証はブラウザに任せず react-hook-form の検証ルールで行う */}
      <form noValidate onSubmit={handleExecute} className="flex flex-col gap-2">
        <RootErrors />
        <AutoDisplayDataFields table={table} form={form} />
        {/* 実行ボタン */}
        <div>
          <Button submit fill loading={isSubmitting}>実行</Button>
        </div>
      </form>
    </CommandPageLayout>
  )
}

/** 検索条件の形のパラメータを入力して実行する画面 */
