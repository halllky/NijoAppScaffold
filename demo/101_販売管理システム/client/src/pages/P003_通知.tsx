/**
 * P003 通知。
 * ログインユーザー宛ての通知の一覧。一覧を表示しただけでは既読にしない。
 * 通知のリンクをたどるか、既読と未読を切り替える操作をしたときだけ既読にする。
 */
function P003_通知() {

  // 検索条件のフォーム
  const form = useSearchConditionForm(通知一覧)
  const { Input, FieldLabel, setServerMessages } = form

  // 既読と未読を変えたら、同じ条件で検索し直す。
  // 画面の移動として扱うので、ナビゲーションの未読の件数も取り直される
  const location = ReactRouter.useLocation()
  const navigate = ReactRouter.useNavigate()
  const reload = () => navigate({ pathname: location.pathname, search: location.search }, { replace: true })

  // 既読と未読の切り替えと、すべて既読は、取り消しが容易な操作なので確認を挟まない
  const set既読 = async (row: 通知一覧.DisplayData, 既読: boolean) => {
    const param = { ...通知既読設定Parameter.createNewDisplayData(), 通知ID: row.通知ID, 既読 }
    const result = await callOperationAsync('通知既読設定', param, { confirmed: true })
    if (result.type === 'error') setServerMessages(result.messages)
  }
  const handleToggle既読 = async (row: 通知一覧.DisplayData) => {
    await set既読(row, !row.既読日時)
    reload()
  }
  const handleすべて既読 = async () => {
    const result = await callOperationAsync('通知すべて既読', {}, { confirmed: true })
    if (result.type === 'error') setServerMessages(result.messages)
    reload()
  }

  return (
    <SearchPageBase
      form={form}
      pageTitle="通知"
      searchConditionDefaultSize={120}
      search={(condition, signal) => callOperationAsync('通知一覧', condition, { signal })}
      searchResultActions={(
        <Button outline mini onClick={handleすべて既読}>
          すべて既読にする
        </Button>
      )}
      searchCondition={(
        <FieldGroup>
          <FieldColumn>
            <FieldLabel name="本文">
              <Input.TextArea name="本文" />
            </FieldLabel>
            <FieldLabel name="作成日時">
              <Input.DateInput name="作成日時" />
            </FieldLabel>
          </FieldColumn>
        </FieldGroup>
      )}
      defineSearchResultColumns={[() => [
        // リンクをたどったら既読にする。画面を移動するので、検索し直しは要らない
        ReadOnlyColumn.link<通知一覧.DisplayData>(
          row => isアプリケーションの中のパス(row.リンク先) ? [{ text: '開く', to: row.リンク先 }] : [],
          { columnId: 'リンク', defaultWidth: 60, disableResizing: true, isFixed: true, onBeforeNavigate: row => set既読(row, true) }),
        ReadOnlyColumn.text<通知一覧.DisplayData>('', row => row.既読日時 ? '' : '未読', { columnId: '未読', defaultWidth: 52, disableResizing: true }),
        ReadOnlyColumn.text<通知一覧.DisplayData>('日時', row => row.作成日時, { columnId: '作成日時', defaultWidth: 160 }),
        ReadOnlyColumn.text<通知一覧.DisplayData>('本文', row => row.本文, { columnId: '本文', defaultWidth: 480, wrap: true }),
        // 値を変える操作だが、変えるのはグリッドの値ではなく通知の既読なので、読み取り専用のグリッドでもボタンを表示する
        ReadOnlyColumn.button<通知一覧.DisplayData>('既読/未読', handleToggle既読, { defaultWidth: 80, showWhenReadOnly: true }),
      ], [location]]}
    />
  )
}

/**
 * ナビゲーションに表示する、自分宛ての未読の通知の件数。
 * 画面を開いたときと、画面を移動するたびに取り直す。サーバーから即時に知らせる仕組みはない。
 */
function 未読件数() {
  const location = ReactRouter.useLocation()
  const [count, setCount] = React.useState<number>()

  React.useEffect(() => {
    const abortController = new AbortController()
    callOperationAsync('未読通知件数', {}, { confirmed: true, signal: abortController.signal }).then(result => {
      // 次の画面の移動で取り直しが始まった場合は、そちらの結果を表示する
      if (result.type === 'canceled') return
      // 件数が取れなかったときは、表示を消すだけで利用者には知らせない
      setCount(result.type === 'ok' ? Number(result.returnValue.件数) || undefined : undefined)
    })
    return () => abortController.abort()
  }, [location.key])

  if (!count) return null
  return (
    <span className="inline-flex items-center justify-center min-w-5 h-5 px-1.5 rounded-full bg-rose-600 text-xs text-white">
      {count}
    </span>
  )
}

/**
 * このアプリケーションの中の URL のパスかどうか。
 * サーバーは通知を作るときに確かめているが、別のサイトへ誘導されないよう、リンクとして表示する前にも確かめる。
 * "//" や "/\" で始まるものは、ブラウザが別のサイトの URL として扱うので除く。
 */
function isアプリケーションの中のパス(path: string | null | undefined): path is string {
  return !!path
    && path.startsWith('/')
    && !path.startsWith('//')
    && !path.startsWith('/\\')
}
