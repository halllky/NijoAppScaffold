import * as ReactRouter from "react-router-dom"
import * as Icon from "@heroicons/react/24/solid"
import { FieldColumn, FieldGroup, ReadOnlyColumn, SearchPageBase, useSearchConditionForm } from "../ui"
import { callOperationAsync } from "../http/callOperationAsync"
import * as ジョブ一覧 from "../__autoGenerated/models/ジョブ一覧"
import { テンプレート } from "../テンプレート"
import type { RootNavigationItem } from "../navigationItems"

const { 画面のURL } = テンプレート

export const URL = 画面のURL.ジョブ()

/**
 * ルートナビゲーションに表示する項目
 */
export const navigationItem = { to: URL, label: "ジョブ", icon: Icon.QueueListIcon, iconOnly: true, operation: 'ジョブ一覧' } satisfies RootNavigationItem

/**
 * ルーティング定義
 */
export default {
  path: URL,
  element: <P004_ジョブ />,
} satisfies ReactRouter.RouteObject

/**
 * P004 ジョブ。
 * 自分が起動したジョブの一覧と結果を表示する。システム管理者は全員のジョブを閲覧できる。
 * スプールのファイルは、ファイル名のリンクからダウンロードする。
 * ジョブの状態は自動では更新しないので、終了したかどうかは再検索して確認する。
 */
function P004_ジョブ() {

  // 検索条件のフォーム
  const form = useSearchConditionForm(ジョブ一覧)
  const { Input, FieldLabel } = form

  return (
    <SearchPageBase
      form={form}
      pageTitle="ジョブ"
      searchConditionDefaultSize={120}
      search={(condition, signal) => callOperationAsync('ジョブ一覧', condition, { signal })}
      searchCondition={(
        <FieldGroup>
          <FieldColumn>
            <FieldLabel name="種類">
              <Input.TextBox name="種類" />
            </FieldLabel>
            <FieldLabel name="状態">
              <Input.EnumSelection name="状態" />
            </FieldLabel>
          </FieldColumn>
          <FieldColumn>
            <FieldLabel name="登録日時">
              <Input.DateInput name="登録日時" />
            </FieldLabel>
            <FieldLabel name="起動したユーザー">
              <Input.TextBox name="起動したユーザー" />
            </FieldLabel>
          </FieldColumn>
        </FieldGroup>
      )}
      defineSearchResultColumns={[() => [
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('状態', row => row.状態, { columnId: '状態', defaultWidth: 80, getClassName: getStateClassName }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('種類', row => row.種類, { columnId: '種類', defaultWidth: 160 }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('登録日時', row => row.登録日時, { columnId: '登録日時', defaultWidth: 160 }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('開始日時', row => row.開始日時, { columnId: '開始日時', defaultWidth: 160 }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('終了日時', row => row.終了日時, { columnId: '終了日時', defaultWidth: 160 }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('起動したユーザー', row => row.起動したユーザー, { columnId: '起動したユーザー', defaultWidth: 120 }),
        ReadOnlyColumn.text<ジョブ一覧.DisplayData>('結果', row => row.結果メッセージ, { columnId: '結果メッセージ', defaultWidth: 360, wrap: true }),
        ReadOnlyColumn.link<ジョブ一覧.DisplayData>(
          row => row.スプールのファイル.flatMap(file => file.ファイル名
            ? [{ text: file.ファイル名, to: getSpoolFileUrl(row.ジョブID ?? '', file.ファイル名), download: file.ファイル名 }]
            : []),
          { columnId: 'スプールのファイル', header: 'ファイル', defaultWidth: 240, wrap: true }),
      ], []]}
    />
  )
}

/**
 * スプールのファイルをダウンロードする URL。サーバー側のダウンロードのエンドポイントと合わせる必要がある。
 */
function getSpoolFileUrl(ジョブID: string, ファイル名: string): string {
  return `/api/job/${encodeURIComponent(ジョブID)}/spool/${encodeURIComponent(ファイル名)}`
}

/**
 * 異常終了したジョブの状態を目立たせる。
 */
function getStateClassName(row: ジョブ一覧.DisplayData): string {
  return row.状態 === '異常終了' ? 'text-rose-600 font-bold' : ''
}
