import { defineSearchDialog, FieldColumn, FieldGroup, ReadOnlyColumn } from "../../ui"
import { callComplexPostEndpointAsync } from "../../example/callComplexPostEndpointAsync"
import * as 商品 from "../../__autoGenerated/models/商品"

/**
 * `ref-to:商品` の検索ダイアログ。
 * 外部参照の入力欄からは、検索ダイアログの対応表を通して使われる。
 */
export const 商品検索ダイアログ = defineSearchDialog<商品.SearchCondition, 商品.RefTarget>({
  title: '商品',
  autoGenerated: 商品,

  // 初期の検索条件
  getDefaultSearchCondition: () => ({
    ...商品.createNewSearchCondition(),
    sort: ['商品.外部システム側ID（昇順）'],
  }),

  // 検索条件欄
  SearchCondition: ({ Input, FieldLabel }) => (
    <FieldGroup>
      <FieldColumn>
        <FieldLabel name="外部システム側ID">
          <Input.TextBox name="外部システム側ID" className="w-36" />
        </FieldLabel>
      </FieldColumn>
      <FieldColumn>
        <FieldLabel name="商品名">
          <Input.TextBox name="商品名" />
        </FieldLabel>
      </FieldColumn>
    </FieldGroup>
  ),

  // 検索結果欄
  getResultColumns: () => [
    ReadOnlyColumn.text<商品.RefTarget>('商品コード', row => row.外部システム側ID, { columnId: '外部システム側ID', defaultWidth: 140 }),
    ReadOnlyColumn.text<商品.RefTarget>('商品名', row => row.商品名, { columnId: '商品名', defaultWidth: 256 }),
    ReadOnlyColumn.numeric<商品.RefTarget>('売値単価(税抜)', row => row.売値単価_税抜, { columnId: '売値単価_税抜', defaultWidth: 120, suffix: '円' }),
    ReadOnlyColumn.text<商品.RefTarget>('消費税区分', row => row.消費税区分, { columnId: '消費税区分', defaultWidth: 110 }),
  ],

  // 検索処理
  search: (condition, signal) => callComplexPostEndpointAsync('ref-to:商品', condition, { ignoreConfirm: true, signal }),
  getItemKey: item => item.商品SEQ ?? '',

  // 外部参照の入力欄から使うときの情報
  refField: {
    codePath: '外部システム側ID',
    namePath: '商品名',
    createConditionFromCode: code => {
      const condition = 商品.createNewSearchCondition()
      condition.filter.外部システム側ID = code
      return condition
    },
    toFilter: item => ({
      外部システム側ID: item.外部システム側ID,
      商品名: item.商品名,
    }),
  },
})
