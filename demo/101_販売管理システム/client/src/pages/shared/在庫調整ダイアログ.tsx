import { Button, FieldColumn, FieldGroup, Modal, useDisplayDataForm } from "../../ui"
import { callComplexPostEndpointAsync } from "../../example/callComplexPostEndpointAsync"
import * as 在庫調整Parameter from "../../__autoGenerated/models/在庫調整Parameter"
import * as 商品 from "../../__autoGenerated/models/商品"
import type * as 商品一覧 from "../../__autoGenerated/models/商品一覧"

/**
 * 在庫調整ダイアログ。
 * 表示している間だけ描画すること。描画されるたびに入力内容は空の状態から始まる。
 * 閉じる処理（このコンポーネントを描画しないようにすること）は呼び出し側で実装する。
 */
export function 在庫調整ダイアログ(props: {
  /** 在庫を調整する商品 */
  product: 商品.RefTarget
  /** ダイアログを閉じるときに呼ばれる。在庫調整が成功したときも、キャンセルしたときも呼ばれる */
  onClose: () => void
  /** 在庫調整が成功したときに、onClose より先に呼ばれる。未指定の場合は何もしない */
  onSuccess?: () => void
}) {
  const { product, onClose, onSuccess } = props

  // 在庫調整の入力内容のフォーム
  const { formMethods, Input, FieldLabel, RootErrors, setServerMessages } = useDisplayDataForm(在庫調整Parameter, {
    defaultValues: {
      ...在庫調整Parameter.createNewDisplayData(),
      商品: product,
    },
  })
  const { handleSubmit, formState: { isSubmitting } } = formMethods

  // 在庫調整の実行
  const handleExecute = handleSubmit(async values => {
    const result = await callComplexPostEndpointAsync('在庫調整登録', values)
    if (result.type === 'ok') {
      onSuccess?.()
      onClose()
    } else if (result.type === 'error') {
      setServerMessages(result.detail)
    }
  })

  return (
    <Modal
      isOpen
      onClose={onClose}
      title={`在庫調整: ${product.商品名 ?? ''}`}
      widthClass="max-w-xl"
    >
      <form noValidate onSubmit={handleExecute} className="p-4 flex flex-col gap-4">

        {/* どの項目にも表示されないメッセージ */}
        <RootErrors />

        {/* 調整対象の商品と、調整内容 */}
        <FieldGroup labelWidth="8rem">
          <FieldColumn>
            <FieldLabel name="商品.外部システム側ID">
              <Input.TextBox name="商品.外部システム側ID" isReadOnly />
            </FieldLabel>
            <FieldLabel name="商品.商品名">
              <Input.TextBox name="商品.商品名" isReadOnly />
            </FieldLabel>
            <FieldLabel name="増減数">
              <Input.NumericTextBox name="増減数" />
            </FieldLabel>
            <FieldLabel name="絶対数">
              <Input.NumericTextBox name="絶対数" />
            </FieldLabel>
            <FieldLabel name="在庫調整理由">
              <Input.TextArea name="在庫調整理由" />
            </FieldLabel>
          </FieldColumn>
        </FieldGroup>

        {/* フッタ */}
        <div className="flex justify-end gap-2 mt-4">
          <Button outline onClick={onClose} disabled={isSubmitting}>キャンセル</Button>
          <Button fill submit loading={isSubmitting}>実行</Button>
        </div>
      </form>
    </Modal>
  )
}

/** 商品一覧のデータから、在庫調整ダイアログに渡す商品を作る */
export function toProductRefTarget(product: 商品一覧.DisplayData): 商品.RefTarget {
  const ref = 商品.createNewRefTarget()
  ref.商品SEQ = product.商品SEQ ?? undefined
  ref.商品名 = product.商品名 ?? undefined
  ref.外部システム側ID = product.外部システム側ID ?? undefined
  return ref
}
