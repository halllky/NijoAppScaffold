import React from "react"
import ReactDOM from "react-dom/client"
import { createBrowserRouter, RouterProvider } from "react-router-dom"
import routes from "./routes"
import App from "./App"
import { LoginUserContext, startSharingLoginUser } from "./login/loginUser"
import * as ログインユーザー情報 from "./__autoGenerated/models/ログインユーザー情報"

// CSS の読み込み
import "./style.css"
import "allotment/dist/style.css"
import "@xyflow/react/dist/style.css"
import { callOperationAsync } from "./http/callOperationAsync"

// ログイン状態をサーバーに問い合わせてから、HTML のルート要素に React をレンダリングする。
// ログイン状態はこのページを開いている間は変わらない
callOperationAsync('ログイン状態確認', {}, { confirmed: true })
  .then(result => {
    return result.type !== 'ok' || !result.returnValue
      ? undefined
      : { ...ログインユーザー情報.createNewDisplayData(), ...result.returnValue }
  })
  .then(loginUser => {
    startSharingLoginUser(loginUser)

    ReactDOM.createRoot(document.getElementById("root")!).render(
      <React.StrictMode>
        <LoginUserContext.Provider value={loginUser}>
          <RouterProvider router={createBrowserRouter([{
            element: <App />,
            children: routes,
          }])} />
        </LoginUserContext.Provider>
      </React.StrictMode>,
    )
  })
