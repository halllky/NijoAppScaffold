import React from "react"
import * as ReactRouter from "react-router-dom"
import { Link } from "react-router-dom"
import { UUID } from "uuidjs"
import * as Grid from "../ui/grid"
import { Button } from "../ui/Button"
import { FieldColumn, FieldGroup, SearchPageBase, useSearchConditionForm, type SortComboItem } from "../ui2"
import { callComplexPostEndpointAsync } from "../example/callComplexPostEndpointAsync"
import * as 商品一覧 from "../__autoGenerated/models/商品一覧"
import * as 商品 from "../__autoGenerated/models/商品"
import { StockAdjustmentDialog } from "../pages/shared/StockAdjustmentDialog"

export const URL = "/v2/shohin"

/**
 * ルーティング定義
 */
export default {
  path: URL,
  element: <P300_商品 />,
} satisfies ReactRouter.RouteObject

/**
 * P300 商品
 */
function P300_商品() {

  // 在庫調整ダイアログ。key は開くたびに入力内容を初期化するため
  const [stockAdjDialogState, setStockAdjDialogState] = React.useState<{
    isOpen: boolean
    key: string | undefined
    product: 商品.RefTarget | undefined
  }>({ isOpen: false, key: undefined, product: undefined })

  // 検索条件のフォーム
  const form = useSearchConditionForm(商品一覧)
  const { Input, FieldLabel } = form

  return (
    <>
      <SearchPageBase
        form={form}
        pageTitle="商品"
        searchConditionDefaultSize={160}
        sortOptions={SORT_OPTIONS}
        createInitialCondition={createInitialCondition}
        search={(condition, signal) => callComplexPostEndpointAsync('商品一覧', condition, { ignoreConfirm: true, signal })}
        searchCondition={(
          <FieldGroup labelWidth="10rem">
            {/* 商品の識別 */}
            <FieldColumn>
              <FieldLabel name="外部システム側ID">
                <Input.TextBox name="外部システム側ID" />
              </FieldLabel>
              <FieldLabel name="商品名">
                <Input.TextBox name="商品名" />
              </FieldLabel>
            </FieldColumn>

            {/* 価格と在庫 */}
            <FieldColumn>
              <FieldLabel name="売値単価_税抜">
                <Input.NumericTextBox name="売値単価_税抜" />
              </FieldLabel>
              <FieldLabel name="消費税区分">
                <Input.EnumSelection name="消費税区分" />
              </FieldLabel>
              <FieldLabel name="在庫数">
                <Input.NumericTextBox name="在庫数" />
              </FieldLabel>
            </FieldColumn>
          </FieldGroup>
        )}
        defineSearchResultColumns={[() => [
          Grid.interactiveColumn<商品一覧.DisplayData>('', row => (
            <Link
              className="text-sky-600 underline"
              to={`/shohin/${row.商品SEQ}`}>
              詳細
            </Link>
          ), { columnId: '詳細リンク', defaultWidth: 60, disableResizing: true, isFixed: true }),
          Grid.textColumn<商品一覧.DisplayData>('外部システム側ID', row => row.外部システム側ID, { columnId: '外部システム側ID', defaultWidth: 152 }),
          Grid.textColumn<商品一覧.DisplayData>('商品名', row => row.商品名, { columnId: '商品名', defaultWidth: 300 }),
          Grid.numericColumn<商品一覧.DisplayData>('売値単価(税抜)', row => row.売値単価_税抜, { columnId: '売値単価_税抜', defaultWidth: 140, suffix: '円' }),
          Grid.textColumn<商品一覧.DisplayData>('消費税区分', row => row.消費税区分, { columnId: '消費税区分', defaultWidth: 120 }),
          Grid.numericColumn<商品一覧.DisplayData>('在庫数', row => row.在庫数, { columnId: '在庫数' }),
          Grid.interactiveColumn<商品一覧.DisplayData>('', row => (
            <Button outline mini
              onClick={() => {
                const refTarget = 商品.createNewRefTarget()
                refTarget.商品SEQ = row.商品SEQ ?? undefined
                refTarget.商品名 = row.商品名 ?? undefined
                refTarget.外部システム側ID = row.外部システム側ID ?? undefined
                setStockAdjDialogState({ isOpen: true, key: UUID.generate(), product: refTarget })
              }}
            >
              在庫調整
            </Button>
          ), { columnId: '在庫調整ボタン', defaultWidth: 96, disableResizing: true }),
        ], []]}
      />

      {/* 在庫調整ダイアログ */}
      {stockAdjDialogState.product && (
        <StockAdjustmentDialog
          key={stockAdjDialogState.key}
          isOpen={stockAdjDialogState.isOpen}
          onClose={() => setStockAdjDialogState(prev => ({ ...prev, isOpen: false }))}
          product={stockAdjDialogState.product}
        />
      )}
    </>
  )
}

/** 並び順の選択肢 */
const SORT_OPTIONS: SortComboItem<商品一覧.SortableMember>[] = [
  { key: '商品一覧.商品SEQ', label: '商品SEQ' },
  { key: '商品一覧.外部システム側ID', label: '外部システム側ID' },
  { key: '商品一覧.商品名', label: '商品名' },
  { key: '商品一覧.売値単価_税抜', label: '売値単価(税抜)' },
  { key: '商品一覧.消費税区分', label: '消費税区分' },
  { key: '商品一覧.在庫数', label: '在庫数' },
]

/** 画面を開いたときとクリアしたときの検索条件 */
function createInitialCondition(): 商品一覧.SearchCondition {
  return {
    ...商品一覧.createNewSearchCondition(),
    sort: ['商品一覧.商品SEQ（昇順）'],
  }
}
