import type { AggregateMetadata } from "../__autoGenerated"
import { NumericTextBoxProps } from "../ui/NumericTextBox"

/**
 * 自動生成されたメタデータの表から、フィールドの定義を取得する。
 * table には各集約の metadata.displayData や metadata.searchCondition を渡す。
 * fieldPath は react-hook-form のフィールド名をそのまま渡せる
 * （先頭の "filter." と、配列インデックス（半角数値のみの部分）は自動で読み飛ばす）。
 * 検索条件の範囲指定の場合は、末尾の ".from" / ".to" も読み飛ばす。
 */
export function getFieldMetadata(
  table: AggregateMetadata.Table,
  fieldPath: string,
): AggregateMetadata.Member {
  const parts = fieldPath
    .split('.')
    // 検索条件オブジェクトの場合は最初が "filter" で始まる
    .filter((part, i) => !(i === 0 && part === "filter"))
    // 半角数値のみから構成される部分は配列インデックスなので除外する
    .filter(part => !/^\d+$/.test(part))

  const path = parts.join('.')
  if (path in table) return table[path]

  // 検索条件の範囲指定
  const last = parts[parts.length - 1]
  const pathWithoutRange = parts.slice(0, -1).join('.')
  if ((last === "from" || last === "to") && pathWithoutRange in table) return table[pathWithoutRange]

  console.error(`getFieldMetadata - ${fieldPath}`, { table, parts })
  throw new Error(`フィールドのメタデータが見つかりません: ${fieldPath}`)
}

/**
 * 数値項目のメタデータから NumericTextBox の桁数・単位の props を組み立てる。
 * 金額項目なら "円"、数量なら "個" のサフィックスと3桁カンマ区切りが付く。
 */
export function numericPropsOf(
  table: AggregateMetadata.Table,
  fieldPath: string,
): Pick<NumericTextBoxProps, "integerDigit" | "decimalDigit" | "suffix" | "commaSeparated"> {
  const fieldMetadata = getFieldMetadata(table, fieldPath)
  if (fieldMetadata.kind !== "value" || fieldMetadata.type === undefined) {
    throw new Error(`数値項目ではありません: ${fieldPath}`)
  }

  let decimalDigit: number | undefined = undefined
  if (fieldMetadata.decimalPlace !== undefined) {
    decimalDigit = fieldMetadata.decimalPlace
  } else if (fieldMetadata.type === "decimal") {
    decimalDigit = 7
  } else if (fieldMetadata.type === "int" || fieldMetadata.type === "sequence" || fieldMetadata.type === "year") {
    decimalDigit = 0
  }

  let integerDigit: number | undefined = undefined
  if (fieldMetadata.totalDigit !== undefined) {
    integerDigit = fieldMetadata.totalDigit - (decimalDigit || 0)
  } else if (fieldMetadata.type === "year") {
    integerDigit = 4
  } else {
    integerDigit = 18 - (decimalDigit || 0)
  }

  let suffix: string | undefined = undefined
  let commaSeparated: boolean = false
  if (fieldMetadata.isCurrency) {
    suffix = "円"
    commaSeparated = true
  } else if (fieldMetadata.isQuantity) {
    suffix = "個"
    commaSeparated = true
  }

  return { integerDigit, decimalDigit, suffix, commaSeparated }
}

/** 単語項目のメタデータから最大文字数を取得する。未設定なら undefined。 */
export function maxLengthOf(
  table: AggregateMetadata.Table,
  fieldPath: string,
): number | undefined {
  return getFieldMetadata(table, fieldPath).customMaxLength
}
