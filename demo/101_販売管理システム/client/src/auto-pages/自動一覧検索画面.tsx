import React from "react"
import * as ReactRouter from "react-router-dom"
import * as AutoGenerated from "../__autoGenerated"
import { AutoSearchConditionFields, autoResultColumns, SearchPageBase, useSearchConditionForm, type SearchConditionBase, type SortComboItem } from "../ui"
import { callComplexPostEndpointAsync } from "../example/callComplexPostEndpointAsync"
import { AUTO_INDEX_PAGE_URL, AUTO_PAGE_BREADCRUMB } from "./自動生成画面URL"

/**
 * ルーティング定義
 */
export default {
  path: `${AUTO_INDEX_PAGE_URL}/search/:queryModel`,
  element: <自動一覧検索画面Route />,
} satisfies ReactRouter.RouteObject

/** URL で指定されたクエリモデルの一覧検索画面を表示する */
function 自動一覧検索画面Route() {
  const { queryModel } = ReactRouter.useParams()
  if (!isQueryModelType(queryModel)) {
    return <div className="p-8">クエリモデル「{queryModel}」はありません。</div>
  }
  // クエリモデルが変わったら画面を作り直す。フォームはメタデータを最初に渡したものから変えられないため
  return <自動一覧検索画面 key={queryModel} queryModel={queryModel} />
}

/**
 * クエリモデルのメタデータから組み立てた一覧検索画面。
 * 検索条件欄にはすべての絞り込み条件が、検索結果欄には子配列以外のすべての値項目が並ぶ。
 */
function 自動一覧検索画面({ queryModel }: { queryModel: AutoGenerated.QueryModelType }) {
  const metadata = AutoGenerated.SearchCondition.metadata[queryModel]

  // 検索条件のフォーム
  const form = useSearchConditionForm<AutoSearchCondition, typeof metadata.searchCondition>({
    metadata,
    createNewSearchCondition: AutoGenerated.SearchCondition.create[queryModel] as () => AutoSearchCondition,
  })

  // 並び順の選択肢。ソート可能なメンバーはクエリモデル名から始まるので、表示名ではそれを除く
  const sortOptions = React.useMemo((): SortComboItem<string>[] => AutoGenerated.SearchCondition.getSortableMembers[queryModel]()
    .map(member => ({ key: member, label: member.slice(queryModel.length + 1) })), [queryModel])

  return (
    <SearchPageBase
      form={form}
      pageTitle={queryModel}
      breadcrumb={AUTO_PAGE_BREADCRUMB}
      sortOptions={sortOptions}
      search={(condition, signal) => callComplexPostEndpointAsync(
        queryModel,
        condition as AutoGenerated.LoadFeature.ParamType[typeof queryModel],
        { ignoreConfirm: true, signal })}
      searchCondition={(
        <AutoSearchConditionFields table={metadata.searchCondition} Input={form.Input} FieldLabel={form.FieldLabel} />
      )}
      defineSearchResultColumns={[() => autoResultColumns(metadata.displayData), [metadata]]}
    />
  )
}

/** どのクエリモデルの検索条件も満たす型 */
type AutoSearchCondition = SearchConditionBase & {
  sort: (`${string}${AutoGenerated.ASC_SUFFIX}` | `${string}${AutoGenerated.DESC_SUFFIX}`)[]
  skip?: string | null
  take?: string | null
}

/** URL で指定された文字列がクエリモデルの種類かどうか */
function isQueryModelType(value: string | undefined): value is AutoGenerated.QueryModelType {
  return (AutoGenerated.getQueryModelTypeList() as string[]).includes(value ?? '')
}
