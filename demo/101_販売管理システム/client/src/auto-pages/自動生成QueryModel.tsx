import React from "react"
import * as ReactRouter from "react-router-dom"
import * as AutoGenerated from "../__autoGenerated"
import { AutoDisplayDataFields, AutoSearchConditionFields, autoResultColumns, Button, ReadOnlyColumn, SearchPageBase, useDisplayDataForm, useSearchConditionForm, type DisplayDataBase, type SearchConditionBase, type SortComboItem } from "../ui"
import { callComplexPostEndpointAsync } from "../example/callComplexPostEndpointAsync"
import { AUTO_INDEX_PAGE_URL, AUTO_PAGE_BREADCRUMB } from "./自動生成画面URL"

/**
 * ルーティング定義
 */
export default {
  path: `${AUTO_INDEX_PAGE_URL}/search/:queryModel`,
  element: <自動一覧検索画面Route />,
} satisfies ReactRouter.RouteObject

/** URL で指定されたクエリモデルの一覧検索画面を表示する */
function 自動一覧検索画面Route() {
  const { queryModel } = ReactRouter.useParams()
  if (!isQueryModelType(queryModel)) {
    return <div className="p-8">クエリモデル「{queryModel}」はありません。</div>
  }
  // クエリモデルが変わったら画面を作り直す。フォームはメタデータを最初に渡したものから変えられないため
  return <自動一覧検索画面 key={queryModel} queryModel={queryModel} />
}

/**
 * クエリモデルのメタデータから組み立てた一覧検索画面。
 * 検索条件欄にはすべての絞り込み条件が、検索結果欄には子配列以外のすべての値項目が並ぶ。
 * 検索結果の行の詳細ボタンを押すと、子配列を含むその行のすべての項目を右のペインに読み取り専用で表示する。
 */
function 自動一覧検索画面({ queryModel }: { queryModel: AutoGenerated.QueryModelType }) {
  const metadata = AutoGenerated.SearchCondition.metadata[queryModel]

  // 検索条件のフォーム
  const form = useSearchConditionForm<AutoSearchCondition, typeof metadata.searchCondition>({
    metadata,
    createNewSearchCondition: AutoGenerated.SearchCondition.create[queryModel] as () => AutoSearchCondition,
  })

  // 並び順の選択肢。ソート可能なメンバーはクエリモデル名から始まるので、表示名ではそれを除く
  const sortOptions = React.useMemo((): SortComboItem<string>[] => AutoGenerated.SearchCondition.getSortableMembers[queryModel]()
    .map(member => ({ key: member, label: member.slice(queryModel.length + 1) })), [queryModel])

  // 詳細を表示している行。詳細の表示欄は行を選ぶたびに作り直すので、何回目に選んだかも持つ
  const [detail, setDetail] = React.useState<{ item: unknown, count: number }>()
  const handleShowDetail = (item: unknown) => {
    setDetail(prev => ({ item, count: (prev?.count ?? 0) + 1 }))
  }

  return (
    <SearchPageBase
      form={form}
      pageTitle={queryModel}
      breadcrumb={AUTO_PAGE_BREADCRUMB}
      sortOptions={sortOptions}
      search={(condition, signal) => callComplexPostEndpointAsync(
        queryModel,
        condition as AutoGenerated.LoadFeature.ParamType[typeof queryModel],
        { ignoreConfirm: true, signal })}
      searchCondition={(
        <AutoSearchConditionFields table={metadata.searchCondition} Input={form.Input} FieldLabel={form.FieldLabel} />
      )}
      defineSearchResultColumns={[() => [
        // 詳細ボタン
        ReadOnlyColumn.interactive<unknown>('', row => (
          <Button mini outline onClick={() => handleShowDetail(row)}>詳細</Button>
        ), { columnId: '詳細ボタン', defaultWidth: 60, disableResizing: true, isFixed: true }),
        ...autoResultColumns(metadata.displayData),
      ], [metadata]]}
      sidePane={detail && (
        <SearchResultDetail
          key={detail.count}
          queryModel={queryModel}
          item={detail.item}
          onClose={() => setDetail(undefined)}
        />
      )}
    />
  )
}

/** 検索結果の1行の詳細。子配列も含めたすべての項目を読み取り専用で表示する */
function SearchResultDetail({ queryModel, item, onClose }: {
  queryModel: AutoGenerated.QueryModelType
  /** 詳細を表示する行 */
  item: unknown
  /** 閉じるボタンが押されたとき */
  onClose: () => void
}) {
  const table = AutoGenerated.SearchCondition.metadata[queryModel].displayData

  // 行を表示するためのフォーム。入力部品の読み取り専用の表示を使うため
  const form = useDisplayDataForm<DisplayDataBase, AutoGenerated.AggregateMetadata.Table>({
    metadata: { displayData: table },
    createNewDisplayData: AutoGenerated.DisplayData.create[queryModel] as () => DisplayDataBase,
  }, {
    defaultValues: item as DisplayDataBase,
  })

  return (
    <div className="h-full flex flex-col border-l border-gray-300">
      {/* ペインの見出しと閉じるボタン */}
      <div className="flex items-center gap-2 px-2 py-1 border-b border-gray-300">
        <h2 className="flex-1 font-bold text-gray-700 select-none">詳細</h2>
        <Button mini outline onClick={onClose}>閉じる</Button>
      </div>

      {/* 行のすべての項目 */}
      <div className="flex-1 overflow-auto p-2">
        <AutoDisplayDataFields table={table} form={form} isReadOnly />
      </div>
    </div>
  )
}

/** どのクエリモデルの検索条件も満たす型 */
type AutoSearchCondition = SearchConditionBase & {
  sort: (`${string}${AutoGenerated.ASC_SUFFIX}` | `${string}${AutoGenerated.DESC_SUFFIX}`)[]
  skip?: string | null
  take?: string | null
}

/** URL で指定された文字列がクエリモデルの種類かどうか */
function isQueryModelType(value: string | undefined): value is AutoGenerated.QueryModelType {
  return (AutoGenerated.getQueryModelTypeList() as string[]).includes(value ?? '')
}
