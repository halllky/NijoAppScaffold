// 最終的にはこのようにメタ情報から簡単に画面を組み立てられるようにしたい
function SamplePage() {
  const {
    UI,
    useEditableGrid,
    RootErrors,
    FieldLabel,
    formMethods: { handleSubmit },
    setServerErrors,
  } = useDisplayDataForm(入荷詳細)

  // 更新前後のハンドリング。
  // RHFのエラーが何か起きている場合はここまで来ない
  const onSubmit: RHF.SubmitHandler<入荷詳細.DisplayData> = async data => {
    const res = await callComplexPostEndpointAsync("入荷修正", data)

    // キャンセルされた場合は何もしない
    if (res.type === "canceled") {
      return
    }
    // エラーの場合は画面上に表示
    if (res.type === "error") {
      setServerErrors({}) // 本当は res.detail を設定する。型定義が合わないので割愛
      return
    }
    // ここまできたら更新成功
    window.location.reload()
  }

  const itemsGridProps = useEditableGrid("入荷商品一覧", col => [
    col.text("商品.商品SEQ", { header: "商品SEQ", defaultWidth: 80 }),
    col.text("商品.商品名", { header: "商品名", defaultWidth: 160 }),
  ], [])

  return (
    <form onSubmit={handleSubmit(onSubmit)} className="flex flex-col">
      <RootErrors />

      <FieldLabel name="入荷ID">
        <UI.TextBox name="入荷ID" />
      </FieldLabel>
      <FieldLabel name="備考">
        <UI.TextBox name="備考" />
      </FieldLabel>

      {/* 入荷商品一覧 */}
      <EditableGrid {...itemsGridProps} />
    </form>
  )
}
