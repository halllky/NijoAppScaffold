import React from "react"
import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import type { FormBinding, GridBinding } from "./FormBinding"
import { createGridColumnHelper, type GridColumnHelper } from "../form-input/bindInputs"
import { getColumnRules } from "../form-input/InputProps"
import type { Messages } from "../message/MessageList"
import { useFindSearchDialog, useOpenDialogInHost } from "../search-dialog/SearchDialogHost"

/** グリッドの1行。行の識別に instanceId を使う */
export type GridRow<TValues extends RHF.FieldValues, TArrayPath extends RHF.ArrayPath<TValues>>
  = RHF.FieldArray<TValues, TArrayPath> & { instanceId: string }

/** グリッドの行と列の定義 */
export type UseEditableGridOptions<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table,
  TArrayPath extends RHF.ArrayPath<TValues>,
> = {
  /** 列定義。引数の列定義ヘルパーを使うと、見出しと入力制約がメタデータから決まる */
  columns: (col: GridColumnHelper<GridRow<TValues, TArrayPath>, TTable, TArrayPath>) => EG2.EditableGridColumn<GridRow<TValues, TArrayPath>>[]
  /**
   * 画面に表示する行を絞り込み・並び替えて返す関数。
   * 引数の配列は最新の値のコピーなので、破壊的変更（sort など）をしてよい。
   * 未指定の場合は全行を配列の順に表示する。
   */
  rows?: (rows: GridRow<TValues, TArrayPath>[]) => GridRow<TValues, TArrayPath>[]
}

/**
 * useEditableGrid の戻り値。
 * 1つ目は EditableGrid にスプレッドする props、2つ目はグリッドの各行に対するメッセージの一覧。
 */
export type UseEditableGridReturn<TRow> = readonly [
  gridProps: EG2.EditableGridProps<TRow>,
  rowMessages: React.ReactNode,
]

/**
 * フォーム内の配列を EditableGrid で編集するためのフック。
 * 戻り値の1つ目を EditableGrid にスプレッドし、2つ目をグリッドの近くに置いて使う。
 *
 * ## deps
 * options の columns と rows が画面側の値を参照する場合は、それを deps に列挙すること。
 * deps は行と列の両方の定義にかかる。どちらかの定義が変わった場合は、グリッド全体を再描画する。
 *
 * ## 行の操作
 * このフックが扱うのはグリッドとフォームの値の橋渡しだけで、行の追加・削除・並べ替えの手段は提供しない。
 * それらが必要な場合は同じ配列に対して react-hook-form の useFieldArray を併用すること。
 * フォームの値の変更は購読を通じてグリッドに反映されるので、useFieldArray の操作はそのまま画面に反映される。
 *
 * 行は instanceId で識別する（グリッドの rowKey = instanceId）。行を複製する場合は instanceId を新しく振り直すこと。
 * グリッドが渡す rowIndex は画面上の位置であり、絞り込み・並び替えをすると配列の添字と一致しない。
 * useFieldArray の remove や swap など配列の添字を受け取る操作には、rowKey から求めた添字を渡すこと。
 *
 * ## 読み取り専用
 * グリッド全体を読み取り専用にする場合は、EditableGrid の props で指定する。
 *
 * ## メッセージ
 * 各行とその子孫の項目に対するメッセージ（クライアント側エラーとサーバー側メッセージの両方）は、戻り値の2つ目の一覧に表示される。
 * 列のある項目に対するメッセージは、その一覧に加えてセルにも表示される。
 * 配列そのものに対するメッセージはこの一覧には含めない。配列の項目の FieldLabel などに表示される。
 *
 * 一覧の書式は、行ごとに1行で、行の位置に続けてその行のメッセージを並べる。
 * ```
 * 1行目 数量: 在庫が不足しています。 単価: 必須です。
 * 3行目 品名: 同じ品名の明細が既にあります。
 * 非表示行 数量: 在庫が不足しています。
 * ```
 * - 行の位置は、画面上の表示位置（1始まり）。配列の添字ではない。
 * - rows で表示されていない行は、行の位置の代わりに「非表示行」と示す。
 *   ユーザーは非表示の行を直接直せないので、利用側は、非表示にする行にメッセージが出ないよう気を付けること。
 * - 各メッセージの前には、その項目のメタデータの表示用名称を付ける。行そのものに対するメッセージには付けない。
 * - メッセージが1件も無い場合は何も描画しない。
 * - メッセージの変化はこの一覧が自分で購読して描画し直す。メッセージが変わっても、このフックを呼んだコンポーネントは再描画されない。
 */
export type BoundUseEditableGrid<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table = AggregateMetadata.Table,
> = <TArrayPath extends RHF.ArrayPath<TValues>>(
  name: TArrayPath,
  options: UseEditableGridOptions<TValues, TTable, TArrayPath>,
  deps: React.DependencyList,
) => UseEditableGridReturn<GridRow<TValues, TArrayPath>>

/**
 * BoundUseEditableGrid の実体。
 * 引数の binding 以外の意味は BoundUseEditableGrid を参照。
 */
export function useEditableGrid<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table,
  TArrayPath extends RHF.ArrayPath<TValues>,
>(
  binding: FormBinding<TValues>,
  name: TArrayPath,
  options: UseEditableGridOptions<TValues, TTable, TArrayPath>,
  deps: React.DependencyList,
): UseEditableGridReturn<GridRow<TValues, TArrayPath>> {
  const { formMethods } = binding
  const arrayPath = binding.toFormPath(name as unknown as RHF.Path<TValues>)

  // 列定義ヘルパーがグリッドの行と結びつくための情報
  const findSearchDialog = useFindSearchDialog()
  const openDialogInHost = useOpenDialogInHost()
  const gridBinding = React.useMemo((): GridBinding => ({
    form: binding as FormBinding<RHF.FieldValues>,
    arrayPath,
    arrayName: name,
    findRowIndex: rowKey => {
      const index = getRows(formMethods, arrayPath).findIndex(row => row.instanceId === rowKey)
      return index === -1 ? undefined : index
    },
    findSearchDialog,
    openDialogInHost,
  }), [binding, formMethods, arrayPath, name, findSearchDialog, openDialogInHost])

  // 行と列の定義。deps が変わったときだけ作り直す
  const columns = React.useMemo(
    () => options.columns(createGridColumnHelper<GridRow<TValues, TArrayPath>, TTable, TArrayPath>(gridBinding)),
    [gridBinding, ...deps])
  const filterRows = React.useMemo(() => options.rows, deps)

  // フォームの値の変化のうち、この配列に関するものを購読する
  const subscribeArray = React.useCallback((onChange: () => void) => formMethods.subscribe({
    name: arrayPath,
    formState: { values: true },
    callback: onChange,
  }), [formMethods, arrayPath])

  // 配列の全行と、画面に表示する行の行キー。値が変わるたびに求め直すが、行キーの並びが変わったときだけ再描画するよう文字列にしている
  const allRowKeysText = React.useSyncExternalStore(subscribeArray, () => getRows(formMethods, arrayPath)
    .map(row => row.instanceId)
    .join(ROW_KEY_SEPARATOR))
  const visibleRowKeysText = React.useSyncExternalStore(subscribeArray, () => {
    const rows = structuredClone(getRows(formMethods, arrayPath)) as GridRow<TValues, TArrayPath>[]
    return (filterRows ? filterRows(rows) : rows)
      .map(row => row.instanceId)
      .join(ROW_KEY_SEPARATOR)
  })
  const allRowKeys = React.useMemo(() => splitRowKeys(allRowKeysText), [allRowKeysText])
  const rowKeys = React.useMemo(() => splitRowKeys(visibleRowKeysText), [visibleRowKeysText])

  // 列定義ヘルパーで作った列の検証ルールを、各行の項目に登録する。
  // セルは react-hook-form に登録された入力欄を持たないため、行の増減と列の定義に合わせてここで登録する（react-hook-form との同期）
  React.useEffect(() => {
    const columnRules = flattenLeafColumns(columns)
      .map(column => getColumnRules(column))
      .filter(rules => rules !== undefined)
    allRowKeys.forEach((_, rowIndex) => {
      for (const { path, validate } of columnRules) {
        const cellFormPath = `${arrayPath}.${rowIndex}.${path}`
        formMethods.register(cellFormPath, { validate: value => validate(value, cellFormPath) })
      }
    })
  }, [columns, allRowKeys, formMethods, arrayPath])

  // グリッドに渡す、行の値の取得と変化の購読
  const getLatestRowObject = React.useCallback((_: number, rowKey: string) => {
    const rowIndex = gridBinding.findRowIndex(rowKey)
    return (rowIndex === undefined ? undefined : formMethods.getValues(`${arrayPath}.${rowIndex}`)) as GridRow<TValues, TArrayPath>
  }, [gridBinding, formMethods, arrayPath])
  // セルはメッセージも表示するので、値の変化に加えてメッセージの変化でも描画し直させる
  const subscribe = React.useCallback((onChange: () => void) => {
    const unsubscribeArray = subscribeArray(onChange)
    const unsubscribeMessages = binding.subscribeMessages(onChange)
    return () => {
      unsubscribeArray()
      unsubscribeMessages()
    }
  }, [subscribeArray, binding])

  // グリッドの操作による値の変更をフォームに反映し、変更されたセルの検証を実行する
  const onRowsChange = React.useCallback((updates: EG2.EditableGridRowUpdate<GridRow<TValues, TArrayPath>>[]) => {
    const leafColumns = flattenLeafColumns(columns)
    const changedCellPaths: string[] = []
    for (const { rowKey, row, changedColumnIds } of updates) {
      const rowIndex = gridBinding.findRowIndex(rowKey)
      if (rowIndex === undefined) continue
      formMethods.setValue(`${arrayPath}.${rowIndex}`, row, { shouldDirty: true })
      for (const columnId of changedColumnIds) {
        const rules = getColumnRules(leafColumns.find(column => column.columnId === columnId) ?? {})
        if (rules) changedCellPaths.push(`${arrayPath}.${rowIndex}.${rules.path}`)
      }
    }
    if (changedCellPaths.length > 0) formMethods.trigger(changedCellPaths)
  }, [columns, gridBinding, formMethods, arrayPath])

  const gridProps: EG2.EditableGridProps<GridRow<TValues, TArrayPath>> = {
    rowKeys,
    getLatestRowObject,
    subscribe,
    onRowsChange,
    columns,
  }
  const rowMessages = (
    <GridRowMessages
      form={binding as FormBinding<RHF.FieldValues>}
      arrayPath={arrayPath}
      allRowKeys={allRowKeys}
      visibleRowKeys={rowKeys}
    />
  )
  return [gridProps, rowMessages] as const
}

/** 行キーの並びを1つの文字列にするときの区切り。instanceId に含まれない文字にする */
const ROW_KEY_SEPARATOR = '\n'

function splitRowKeys(text: string): string[] {
  return text === '' ? [] : text.split(ROW_KEY_SEPARATOR)
}

/** フォームの配列の現在の値。値が無い場合（読み込み中など）は空配列 */
function getRows(formMethods: RHF.UseFormReturn<RHF.FieldValues>, arrayPath: string): { instanceId: string }[] {
  const rows = formMethods.getValues(arrayPath)
  return Array.isArray(rows) ? rows : []
}

/** グループ化された列を展開して、リーフ列だけにする */
function flattenLeafColumns<TRow>(columns: EG2.EditableGridColumn<TRow>[]): EG2.EditableGridLeafColumn<TRow>[] {
  return columns.flatMap(column => 'columns' in column ? column.columns : [column])
}

/**
 * グリッドの各行に対するメッセージの一覧。書式は BoundUseEditableGrid の説明を参照。
 * 配列の全行を、その行と子孫の項目に対するメッセージの表示領域として登録する。
 * メッセージの変化は自分で購読して描画し直す。
 */
function GridRowMessages({ form, arrayPath, allRowKeys, visibleRowKeys }: {
  form: FormBinding<RHF.FieldValues>
  arrayPath: string
  /** 配列の全行の行キー。配列の順 */
  allRowKeys: string[]
  /** 画面に表示している行の行キー。表示の順 */
  visibleRowKeys: string[]
}) {
  // 全行を表示領域として登録する。行の位置が変わると項目のパスも変わるので、行の並びが変わるたびに登録し直す
  React.useEffect(() => {
    const unregisters = allRowKeys.map((_, rowIndex) => form.registerMessageArea(
      `${arrayPath}.${rowIndex}`,
      { includesDescendants: true },
    ))
    return () => unregisters.forEach(unregister => unregister())
  }, [form, arrayPath, allRowKeys])

  // 行ごとのメッセージ。画面に表示している行を表示の順に並べ、その後に表示していない行を並べる
  const lines = useRowMessageLines(form, arrayPath, allRowKeys, visibleRowKeys)
  if (lines.length === 0) return null

  return (
    <ul className="flex flex-col text-xs">
      {lines.map(({ rowKey, label, messages }) => (
        <li key={rowKey} className="flex flex-wrap gap-x-2">
          {/* 行の位置。行の先頭のメッセージと同じ色にする */}
          <span className={`select-none ${firstMessageColor(messages)}`}>{label}</span>
          {/* エラー・警告・情報 */}
          {messages.errors.map((message, index) => (
            <span key={`error-${index}`} className="text-rose-700">{message}</span>
          ))}
          {messages.warnings.map((message, index) => (
            <span key={`warning-${index}`} className="text-amber-700">{message}</span>
          ))}
          {messages.informations.map((message, index) => (
            <span key={`information-${index}`} className="text-sky-700">{message}</span>
          ))}
        </li>
      ))}
    </ul>
  )
}

/** 一覧の1行で先頭に表示するメッセージの文字色。エラー・警告・情報の順に表示するので、最初にあるものの色になる */
function firstMessageColor(messages: Messages): string {
  if (messages.errors.length > 0) return 'text-rose-700'
  if (messages.warnings.length > 0) return 'text-amber-700'
  return 'text-sky-700'
}

/** メッセージの一覧の1行 */
type RowMessageLine = {
  rowKey: string
  /** 行の位置。「〇行目」か「非表示行」 */
  label: string
  messages: Messages
}

/**
 * メッセージがある行だけを、一覧に表示する順に返す。
 * メッセージの変化を購読し、一覧の内容が変わったときだけ新しい配列を返す。
 */
function useRowMessageLines(
  form: FormBinding<RHF.FieldValues>,
  arrayPath: string,
  allRowKeys: string[],
  visibleRowKeys: string[],
): RowMessageLine[] {
  const previousRef = React.useRef<RowMessageLine[]>([])

  const getSnapshot = React.useCallback(() => {
    const visibleSet = new Set(visibleRowKeys)
    const hiddenRowKeys = allRowKeys.filter(rowKey => !visibleSet.has(rowKey))
    const lines: RowMessageLine[] = []
    const pushLine = (rowKey: string, label: string) => {
      const rowIndex = allRowKeys.indexOf(rowKey)
      if (rowIndex === -1) return
      const messages = form.getMessages(`${arrayPath}.${rowIndex}`)
      if (messages.errors.length + messages.warnings.length + messages.informations.length > 0) {
        lines.push({ rowKey, label, messages })
      }
    }
    visibleRowKeys.forEach((rowKey, position) => pushLine(rowKey, `${position + 1}行目`))
    hiddenRowKeys.forEach(rowKey => pushLine(rowKey, '非表示行'))

    // getMessages は内容が同じなら同じ参照を返すので、各行の参照と位置が同じなら前回の配列を返す
    const previous = previousRef.current
    const isSame = previous.length === lines.length && lines.every((line, index) =>
      line.rowKey === previous[index].rowKey
      && line.label === previous[index].label
      && line.messages === previous[index].messages)
    if (isSame) return previous
    previousRef.current = lines
    return lines
  }, [form, arrayPath, allRowKeys, visibleRowKeys])

  return React.useSyncExternalStore(form.subscribeMessages, getSnapshot)
}
