import React from "react"
import * as RHF from "react-hook-form"
import useEvent from "react-use-event-hook"
import type { LoadReturnType } from "../../__autoGenerated"
import type { PresentationContextDetail } from "../message/ServerMessages"

/**
 * 画面側から渡される検索処理の結果。
 * サーバー呼び出しの結果を、成功・中断・エラーのいずれかとして返す。
 * detail は、サーバー側メッセージとして検索条件欄に表示される。
 */
export type SearchResult<TItem>
  = { type: 'ok', returnValue: LoadReturnType<TItem>, detail?: PresentationContextDetail }
  | { type: 'canceled' }
  | { type: 'error', detail: PresentationContextDetail }

/** 最後に成功した検索。ui フォルダ内部でのみ使用する */
export type PagedSearchState<TSearchCondition, TItem> = {
  /** 検索に使った条件。skip と take は検索したページのものになっている */
  condition: TSearchCondition
  /** 検索したページ。0始まり */
  pageIndex: number
  /** 1ページの件数 */
  pageSize: number
  /** 検索結果 */
  result: LoadReturnType<TItem>
}

/**
 * 検索処理をページ単位で呼び、最後に成功した検索を保持するフック。ui フォルダ内部でのみ使用する。
 *
 * - 検索中に次の検索を始めた場合は、検索中の処理を中断する。中断された検索の結果は捨てる。
 * - 検索処理が返したメッセージは、成功・エラーのどちらでも setServerMessages に渡す。中断された場合は渡さない。
 * - エラーの場合、最後に成功した検索は変えない。
 * - このフックを呼んだコンポーネントがアンマウントされたら、検索中の処理を中断する。
 *
 * @param search 画面側から渡される検索処理。描画のたびに作り直されてもよい
 * @param setServerMessages 検索条件欄にサーバー側メッセージを表示する関数
 */
export function usePagedSearch<TSearchCondition extends RHF.FieldValues, TItem>(
  search: (condition: TSearchCondition, signal: AbortSignal) => Promise<SearchResult<TItem>>,
  setServerMessages: (detail: PresentationContextDetail | null | undefined) => void,
) {
  const [searched, setSearched] = React.useState<PagedSearchState<TSearchCondition, TItem>>()
  const [isSearching, setIsSearching] = React.useState(false)
  const abortControllerRef = React.useRef<AbortController>(undefined)

  // 指定したページを検索する。
  // 呼び出し側の effect から呼ばれても、検索処理が作り直されるたびに effect が動かないよう、参照を固定する
  const searchPage = useEvent(async (condition: TSearchCondition, pageIndex: number, pageSize: number) => {
    abortControllerRef.current?.abort()
    const abortController = new AbortController()
    abortControllerRef.current = abortController
    setIsSearching(true)

    try {
      const conditionForRequest: TSearchCondition = {
        ...condition,
        skip: String(pageIndex * pageSize),
        take: String(pageSize),
      }
      const result = await search(conditionForRequest, abortController.signal)

      // 次の検索が始まったか、アンマウントされた
      if (abortController.signal.aborted) return
      if (result.type === 'canceled') return

      setServerMessages(result.detail)
      if (result.type === 'ok') {
        setSearched({ condition: conditionForRequest, pageIndex, pageSize, result: result.returnValue })
      }
    } finally {
      // 次の検索が始まっている場合は、そちらの検索中の表示を消さない
      if (abortControllerRef.current === abortController) setIsSearching(false)
    }
  })

  // アンマウントされたら検索中の処理を中断する（サーバーとの同期）
  React.useEffect(() => {
    return () => abortControllerRef.current?.abort()
  }, [])

  return {
    /** 最後に成功した検索。まだ成功していなければ undefined */
    searched,
    /** 検索中かどうか */
    isSearching,
    /** 指定したページを検索する。検索中の処理があれば中断する */
    searchPage,
  }
}
