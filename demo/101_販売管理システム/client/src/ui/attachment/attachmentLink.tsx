import type { GridLink } from "../grid/ClickableColumn"
import type * as 添付ファイルRef from "../../__autoGenerated/models/添付ファイルRef"
import { テンプレート } from "../../テンプレート"

/**
 * 添付ファイルをダウンロードするリンク。ファイルが無ければ何も表示しない。
 */
export function AttachmentLink({ file, className }: {
  file: 添付ファイルRef.RefTarget | null | undefined
  className?: string
}) {
  const link = toAttachmentGridLinks(file)[0]
  if (!link) return null
  return (
    <a href={link.to} download={link.download} className={`text-sky-600 underline ${className ?? ''}`}>
      {link.text}
    </a>
  )
}

/**
 * 添付ファイルをダウンロードするリンクを、グリッドのリンクの列（ReadOnlyColumn.link）に渡す形で返す。ファイルが無ければ空配列。
 */
export function toAttachmentGridLinks(file: 添付ファイルRef.RefTarget | null | undefined): GridLink[] {
  if (!file?.識別子) return []
  const 名前 = file.名前 ?? file.識別子
  return [{
    text: 名前,
    to: テンプレート.API_URL.AttachmentDownload({ 識別子: file.識別子 }),
    download: 名前,
  }]
}
