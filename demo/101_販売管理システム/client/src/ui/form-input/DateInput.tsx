import React from "react"
import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import { findMemberMetadata, type GridBinding } from "../form/FormBinding"
import { assertValueMember, attachColumnRules, inputFrameClassName, toRegisterRules, type ColumnOptionsBase, type InputPropsBase, type WithFormBinding } from "./InputProps"
import { createTextCellEditor, defineCellColumn, findCellMemberMetadata } from "./GridCell"

/*
 * 日付・日時・年月の入力欄。
 * フォーム用とグリッド用で以下の仕様を共有する。
 *
 * - 日付・日時・年月のどれを入力するかは、メタデータの値の型から決める。
 * - 表示の書式と、フォームの値として保持する文字列の書式は、フォームとグリッドで同じ。
 * - 日付として解釈できない入力は、空にせず入力されたまま残し、エラーにする。気付かないまま値が消えるのを防ぐため。
 * - 検索条件のフォームでは、範囲指定（開始〜終了）の2つの入力欄になる。
 */

//#region フォーム用

export type DateInputProps<TValues extends RHF.FieldValues> = InputPropsBase<TValues>

/** 日付・日時・年月の入力欄（フォーム用）。基本的にはブラウザのネイティブな入力コントロールの仕様に従う */
export function DateInput<TValues extends RHF.FieldValues>(props: WithFormBinding<DateInputProps<TValues>, TValues>): React.ReactNode {
  const { binding, name, isReadOnly, rules, className } = props
  const formPath = binding.toFormPath(name)
  const kind = dateKindOf(findMemberMetadata(binding.metadata, name), name)

  // 画面表示用データでは1つの入力欄
  if (binding.kind === 'display-data') {
    return (
      <NativeDateInput
        formPath={formPath}
        control={binding.formMethods.control}
        ruleParams={{ rules }}
        kind={kind}
        isReadOnly={isReadOnly}
        className={className}
      />
    )
  }

  // 検索条件では範囲指定。範囲全体に対する検証は開始の入力欄に付ける
  return (
    <div className={`flex flex-wrap items-center gap-1 ${className ?? ''}`}>
      {/* 開始 */}
      <NativeDateInput
        formPath={`${formPath}.from`}
        control={binding.formMethods.control}
        ruleParams={{
          rules,
          itemValueOf: (_, formValues) => RHF.get(formValues, formPath),
          validators: [range => validateDateRange(range as DateRange | undefined)],
        }}
        kind={kind}
        isReadOnly={isReadOnly}
      />
      <span className="select-none">～</span>
      {/* 終了 */}
      <NativeDateInput
        formPath={`${formPath}.to`}
        control={binding.formMethods.control}
        ruleParams={{ rules: undefined }}
        kind={kind}
        isReadOnly={isReadOnly}
      />
    </div>
  )
}

/**
 * ブラウザのネイティブな日付・日時・年月の入力欄1つ。
 * 入力途中や存在しない日付など、ネイティブの入力欄が値として解釈できない入力が残っている場合はクライアント側エラーにする。
 * ネイティブの入力欄はその場合の値を空文字として渡すので、そのままでは入力が黙って捨てられてしまうため。
 * この検証はブラウザの検証機能には任せない（フォームの検証はすべて react-hook-form の検証ルールで行う）。
 */
function NativeDateInput({ formPath, control, ruleParams, kind, isReadOnly, className }: {
  formPath: string
  control: RHF.Control<RHF.FieldValues>
  /** 検証ルールの組み立てに使う。解釈できない入力の検証はこのコンポーネントが足す */
  ruleParams: Omit<Parameters<typeof toRegisterRules>[0], 'checkUnparsableInput'>
  kind: DateKind
  isReadOnly: boolean | undefined
  className?: string
}) {
  const inputRef = React.useRef<HTMLInputElement>(null)
  /** 検証の時点のフォームの値。検証ルールはこのコンポーネントの描画より前に作るので、参照を通して読む */
  const valueRef = React.useRef<unknown>(undefined)
  const { field } = RHF.useController({
    name: formPath,
    control,
    rules: toRegisterRules({
      ...ruleParams,
      // ブラウザに年月の入力欄が無い場合は文字の入力欄になり、解釈できない入力がフォームの値として残るので、それも確かめる
      checkUnparsableInput: () => inputRef.current?.validity.badInput
        ? `${UNPARSABLE_DATE_LABEL[kind]}を正しく入力してください。`
        : validateDateValue(valueRef.current, kind),
    }),
  })
  valueRef.current = field.value

  return (
    <input
      type={kind === 'date' ? 'date' : kind === 'datetime' ? 'datetime-local' : 'month'}
      ref={element => {
        inputRef.current = element
        field.ref(element)
      }}
      name={field.name}
      value={typeof field.value === 'string' ? field.value : ''}
      onChange={e => field.onChange(toDateValue(e.target.value, kind))}
      onBlur={field.onBlur}
      readOnly={isReadOnly}
      className={`block px-1 py-px outline-none ${inputFrameClassName(isReadOnly)} ${className ?? ''}`}
    />
  )
}

//#endregion フォーム用

//#region グリッド用

export type DateColumnOptions<TRow> = ColumnOptionsBase<TRow>

/** 日付・日時・年月の列（グリッド用） */
export function dateColumn<TRow>(
  binding: GridBinding,
  path: RHF.Path<TRow>,
  options?: DateColumnOptions<TRow>,
): EG2.EditableGridLeafColumn<TRow> {
  const kind = dateKindOf(findCellMemberMetadata(binding, path), path)
  const toText = (value: unknown) => typeof value !== 'string' ? ''
    : validateDateValue(value, kind) === undefined ? formatDate(value)
      : value // 解釈できない入力は、入力されたまま表示する

  const column = defineCellColumn(binding, path, options, {
    render: ({ value }) => toText(value),
    editor: DATE_CELL_EDITOR,
    toText,
    fromText: text => ({ value: toDateValue(text, kind) }),
  })
  return attachColumnRules(column, { path, validate: value => validateDateValue(value, kind) })
}

/** 日付のセルエディタ。区切り文字を含む様々な書式で手入力できるよう、文字列のまま受け付けて確定時に解釈する */
const DATE_CELL_EDITOR = createTextCellEditor({ multiline: false })

