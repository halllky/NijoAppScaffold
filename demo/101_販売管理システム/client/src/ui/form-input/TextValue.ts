import type { AggregateMetadata } from "../../__autoGenerated"

/*
 * 文字列（単語・文章）の入力値の扱い。単語と文章の入力欄で、フォーム用とグリッド用に共有する。
 * ui フォルダ内部でのみ使用する。
 *
 * - 値の確定時の正規化は、メタデータのカスタム属性「文字列の正規化」で項目ごとに決める。
 *   指定がなければ前後の空白だけを削除する。
 * - カスタム属性「最大長」を超える入力は、切り捨てずにエラーにする。気付かないまま値が変わるのを防ぐため。
 *   長さは見た目の1文字を1と数える（サロゲートペアや結合文字も1文字）。
 */

/** 値の確定時の正規化 */
export function normalizeText(value: string, member: AggregateMetadata.Member): string {
  switch (member.stringNormalization) {
    case '正規化しない': return value
    case 'NFKC': return value.trim().normalize('NFKC')
    default: return value.trim()
  }
}

/** 最大長の検証。最大長を超えていればエラーメッセージを、超えていなければ undefined を返す */
export function validateTextLength(value: unknown, member: AggregateMetadata.Member): string | undefined {
  const maxLength = member.customMaxLength
  if (maxLength === undefined || maxLength <= 0) return undefined
  if (typeof value !== 'string') return undefined
  return countCharacters(value) > maxLength ? `${maxLength}文字以内で入力してください。` : undefined
}

/** 見た目の1文字を1と数える */
function countCharacters(value: string): number {
  let count = 0
  for (const _ of GRAPHEME_SEGMENTER.segment(value)) count++
  return count
}

const GRAPHEME_SEGMENTER = new Intl.Segmenter('ja', { granularity: 'grapheme' })
