/*
 * 外部参照の入力欄。参照先のデータを、コードの手入力か検索ダイアログで選ぶ。
 * どの検索ダイアログを使うかは、項目のメタデータの refTo から SearchDialogRegistry の対応表を引いて決める。
 * コードと名称がどの値かは、その検索ダイアログの定義が決める。
 *
 * ## 共通
 * - コードと名称を並べて表示する。
 * - 検索ダイアログでは1件だけ選ぶ。
 * - コードと名称は文字列型の項目だけを想定する。数値や日付など、検索条件で範囲指定になる型の項目は扱えない。
 * - 検索ダイアログのアイテムの型が、この項目の値の型と一致するかはコンパイル時に確かめない。利用側で一致させること。
 *
 * ## 画面表示用データのフォームとグリッド
 * 項目の値は、参照先のデータそのもの。
 *
 * - 名称は表示だけで、手入力できない。
 * - コードを手入力して確定すると、検索ダイアログの定義に従ってコードを照合する。
 *   - ちょうど1件見つかった場合は、それを選んだものとして項目全体を置き換える。
 *   - 見つからなかった場合、2件以上見つかった場合、照合の検索処理がエラーを返した場合は、エラーとする。入力したコードは残し、名称を空にする。
 *   - コードを空にして確定した場合は照合せず、項目全体を空にする。エラーにはしない。
 * - 照合は、この項目の非同期の検証ルールとして react-hook-form に登録する（クライアント側エラーの仕組みに乗る）。
 *   - 照合のエラーは FieldLabel やグリッドのセルに表示され、コードを入力し直して照合し直すまではフォームの送信時の検証でもエラーになる。
 *   - 検証ルールは、照合中ならその完了を待って結果を返す。項目のコードがまだ照合していない値なら、その場で照合を始めて完了を待つ。
 *     照合済みのコードなら、照合し直さずに前回の結果を返す。
 *   - react-hook-form の handleSubmit は非同期の検証ルールの完了を待つので、照合中に送信しても、送信処理は照合の完了後に呼ばれる。
 *     照合がエラーなら送信処理は呼ばれない。そのため利用側は、照合中に保存ボタンを押せないようにする制御を行わなくてよい。
 * - 検索ダイアログで選んだ場合は、選んだデータで項目全体を置き換え、そのコードを照合済みとして扱う。
 *
 * ## 検索条件のフォーム
 * 項目の値は、外部参照の絞り込み条件。
 *
 * - コードと名称のどちらも手入力でき、手入力した値はそのまま絞り込み条件になる。
 *   部分一致などで絞り込めるよう、手入力したコードの照合は行わない。
 * - 絞り込み条件のうちコードと名称の値は、検索ダイアログのアイテムから見たときと同じパスにある。
 *   コードと名称は文字列型なので、絞り込み条件でも範囲指定にならず、パスの形が変わらないため。
 * - 検索ダイアログで選んだ場合は、選んだデータを絞り込み条件に変換して項目全体を置き換える。
 */

//#region フォーム用

export type RefToProps<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table,
  TName extends RHF.Path<TValues>,
> = Omit<InputPropsBase<TValues>, 'name'> & RefToParamsProp<TTable, TName> & {
  /** 入力対象の外部参照項目。配列の要素の項目はインデックスを含めて指定する */
  name: TName
}

/**
 * 外部参照の入力欄（フォーム用）。
 * コードの入力欄、検索ダイアログを開くボタン、名称の欄を横に並べる。
 */
export function RefTo<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table,
  TName extends RHF.Path<TValues>,
>(props: WithFormBinding<RefToProps<TValues, TTable, TName>, TValues>): React.ReactNode {
  const { binding, name, isReadOnly, rules, className } = props
  const params: unknown = props.params
  const formPath = binding.toFormPath(name)
  const member = assertRefMember(findMemberMetadata(binding.metadata, name), name)
  const dialog = useFindSearchDialog()(member.refTo)

  const commonProps = {
    formMethods: binding.formMethods,
    formPath,
    dialog,
    params,
    isReadOnly,
    rules,
    className,
  }
  return binding.kind === 'display-data'
    ? <RefToForDisplayData {...commonProps} />
    : <RefToForSearchCondition {...commonProps} />
}

/** RefTo の、画面表示用データ用と検索条件用の実体が共通で受け取る props */
type RefToBodyProps = {
  formMethods: RHF.UseFormReturn<RHF.FieldValues>
  formPath: string
  dialog: SearchDialog<RHF.FieldValues, unknown>
  params: unknown
  isReadOnly: boolean | undefined
  rules: InputRules | undefined
  className: string | undefined
}

/** 画面表示用データの外部参照の入力欄。コードを手入力したら照合する */
function RefToForDisplayData({ formMethods, formPath, dialog, params, isReadOnly, rules, className }: RefToBodyProps) {
  const openDialogInHost = useOpenDialogInHost()
  const [codeMatching] = React.useState(() => createCodeMatching(dialog, formMethods))

  // 照合を検証ルールとして登録する。項目の値は参照先のデータそのもの
  const { field } = RHF.useController({
    name: formPath,
    control: formMethods.control,
    rules: toRegisterRules({
      rules,
      validators: [value => codeMatching.validate(formPath, codeOf(dialog, value), params)],
    }),
  })
  const code = codeOf(dialog, field.value)
  const refName = RHF.get(field.value, dialog.refField.namePath)

  // 入力中のコード。入力中の1文字ごとに照合しないよう、フォーカスアウトか Enter キーまではフォームの値に反映しない。入力中でなければ undefined。
  // Enter キーでも反映するのは、Enter キーによるフォームの送信で入力中のコードが照合・送信されるようにするため
  const [draftCode, setDraftCode] = React.useState<string>()
  const selectAllOnFocus = useSelectAllOnFocus()

  const commitDraftCode = () => {
    if (draftCode === undefined) return
    const nextCode = draftCode.trim().normalize('NFKC')
    setDraftCode(undefined)
    if (nextCode === code) return
    field.onChange(nextCode === '' ? emptyRefValue(dialog) : withCode(dialog, field.value, nextCode))
    // 照合は検証ルールの中で行うので、検証を実行して照合を始める。コードを空にした場合は前回のエラーを消すために検証する
    formMethods.trigger(formPath)
  }
  const handleKeyDown: React.KeyboardEventHandler<HTMLInputElement> = e => {
    if (e.key === 'Enter' && !e.nativeEvent.isComposing) commitDraftCode()
  }
  const handleBlur = () => {
    commitDraftCode()
    field.onBlur()
  }

  const handleOpenDialog = async () => {
    const item = await dialog.refField.selectOne(openDialogInHost, params)
    if (item === undefined) return
    codeMatching.markAsMatched(formPath, codeOf(dialog, item), params, item)
    formMethods.setValue(formPath, item, { shouldDirty: true })
    formMethods.trigger(formPath)
  }

  return (
    <div className={`flex items-center gap-1 ${className ?? ''}`}>
      {/* コード */}
      <input
        type="text"
        ref={field.ref}
        name={`${field.name}.${dialog.refField.codePath}`}
        value={draftCode ?? code}
        onChange={e => setDraftCode(e.target.value)}
        onKeyDown={handleKeyDown}
        onBlur={handleBlur}
        {...selectAllOnFocus}
        readOnly={isReadOnly}
        spellCheck={false}
        autoComplete="off"
        className={`block w-28 px-1 py-px outline-none ${inputFrameClassName(isReadOnly)}`}
      />
      {/* 検索ダイアログを開くボタン */}
      {!isReadOnly && (
        <SearchButton onClick={handleOpenDialog} />
      )}
      {/* 名称。表示だけ */}
      <span className={`flex-1 min-w-0 min-h-6 px-1 py-px truncate select-all ${isReadOnly ? '' : 'text-gray-700'}`}>
        {typeof refName === 'string' ? refName : ''}
      </span>
    </div>
  )
}

/** 検索条件の外部参照の入力欄。コードも名称も手入力した値がそのまま絞り込み条件になる */
function RefToForSearchCondition({ formMethods, formPath, dialog, params, isReadOnly, rules, className }: RefToBodyProps) {
  const openDialogInHost = useOpenDialogInHost()

  const handleOpenDialog = async () => {
    const item = await dialog.refField.selectOne(openDialogInHost, params)
    if (item === undefined) return
    formMethods.setValue(formPath, dialog.refField.toFilter(item), { shouldDirty: true })
  }

  return (
    <div className={`flex items-center gap-1 ${className ?? ''}`}>
      {/* コード。項目全体に対する検証はここに付ける */}
      <FilterTextInput
        formPath={`${formPath}.${dialog.refField.codePath}`}
        control={formMethods.control}
        rules={toRegisterRules({ rules, itemValueOf: (_, formValues) => RHF.get(formValues, formPath) })}
        isReadOnly={isReadOnly}
        className="w-28"
      />
      {/* 検索ダイアログを開くボタン */}
      {!isReadOnly && (
        <SearchButton onClick={handleOpenDialog} />
      )}
      {/* 名称 */}
      <FilterTextInput
        formPath={`${formPath}.${dialog.refField.namePath}`}
        control={formMethods.control}
        rules={toRegisterRules({ rules: undefined })}
        isReadOnly={isReadOnly}
        className="flex-1 min-w-0"
      />
    </div>
  )
}

/** 検索条件のコードか名称の入力欄。フォーカスアウト時に前後の空白を削除し、Unicode正規化（NFKC）を行う */
function FilterTextInput({ formPath, control, rules, isReadOnly, className }: {
  formPath: string
  control: RHF.Control<RHF.FieldValues>
  rules: Pick<RHF.RegisterOptions, 'validate'>
  isReadOnly: boolean | undefined
  className?: string
}) {
  const { field } = RHF.useController({ name: formPath, control, rules })
  const selectAllOnFocus = useSelectAllOnFocus()

  const handleBlur: React.FocusEventHandler<HTMLInputElement> = e => {
    const normalized = e.target.value.trim().normalize('NFKC')
    if (normalized !== (field.value ?? '')) field.onChange(normalized)
    field.onBlur()
  }

  return (
    <input
      type="text"
      ref={field.ref}
      name={field.name}
      value={typeof field.value === 'string' ? field.value : ''}
      onChange={e => field.onChange(e.target.value)}
      onBlur={handleBlur}
      {...selectAllOnFocus}
      readOnly={isReadOnly}
      spellCheck={false}
      autoComplete="off"
      className={`block px-1 py-px outline-none ${inputFrameClassName(isReadOnly)} ${className ?? ''}`}
    />
  )
}

/** 検索ダイアログを開くボタン */
function SearchButton({ onClick }: { onClick: () => void }) {
  return (
    <button
      type="button"
      title="検索"
      onClick={onClick}
      className="flex-none p-0.5 rounded text-teal-700 hover:bg-gray-100 cursor-pointer"
    >
      <MagnifyingGlassIcon className="w-4 h-4" />
    </button>
  )
}

