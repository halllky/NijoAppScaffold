//#region グリッド用

/**
 * 外部参照の列のオプション。
 * TPath は、メタデータの表のキーと同じ形の、配列の要素の外部参照項目のパス（配列のインデックスは含めてよい）。
 */
export type RefToColumnOptions<TRow, TTable extends AggregateMetadata.Table, TPath extends string>
  = ColumnOptionsBase<TRow> & RefToParamsProp<TTable, TPath>

/**
 * 外部参照の列（グリッド用）。
 * セルの編集はコードの手入力。セルの中の検索ボタンか、セルを選んだ状態での Ctrl+Space で検索ダイアログを開く。
 * コピー&ペーストの文字列表現はコード。貼り付けたコードは、手入力と同じく照合して名称を補う。
 */
export function refToColumn<TRow, TTable extends AggregateMetadata.Table, TPath extends string>(
  binding: GridBinding,
  path: RHF.Path<TRow>,
  options: RefToColumnOptions<TRow, TTable, TPath> | undefined,
): EG2.EditableGridLeafColumn<TRow> {
  const member = assertRefMember(findCellMemberMetadata(binding, path), path)
  const dialog = binding.findSearchDialog(member.refTo)
  const { params, ...columnOptions } = (options ?? {}) as ColumnOptionsBase<TRow> & { params?: unknown }
  const codeMatching = createCodeMatching(dialog, binding.form.formMethods)
  const { formMethods } = binding.form

  /** 行の項目を、検索ダイアログで選んだもので置き換える */
  const openDialogFor = async (rowKey: string) => {
    const item = await dialog.refField.selectOne(binding.openDialogInHost, params)
    if (item === undefined) return
    // ダイアログを開いている間に行が削除されていたら何もしない
    const cellFormPath = toCellFormPath(binding, rowKey, path)
    if (cellFormPath === undefined) return
    codeMatching.markAsMatched(cellFormPath, codeOf(dialog, item), params, item)
    formMethods.setValue(cellFormPath, item, { shouldDirty: true })
    formMethods.trigger(cellFormPath)
  }
  const { editor, requestDialog } = createRefCellEditor(openDialogFor)

  const column = defineCellColumn(binding, path, columnOptions, {
    render: ({ value, rowKey, isReadOnly }) => {
      const refName = RHF.get(value, dialog.refField.namePath)
      return (
        <div className="flex items-center gap-1">
          {/* コード */}
          <span className="flex-none">{codeOf(dialog, value)}</span>
          {/* 名称 */}
          <span className="flex-1 min-w-0 truncate text-gray-600">{typeof refName === 'string' ? refName : ''}</span>
          {/* 検索ダイアログを開くボタン。クリックでセルが選ばれないよう、mousedown の伝播を止める */}
          {!isReadOnly && (
            <button
              type="button"
              title="検索 (Ctrl+Space)"
              tabIndex={-1}
              onMouseDown={e => e.stopPropagation()}
              onClick={() => openDialogFor(rowKey)}
              className="flex-none p-0.5 rounded text-teal-700 hover:bg-gray-100 cursor-pointer"
            >
              <MagnifyingGlassIcon className="w-4 h-4" />
            </button>
          )}
        </div>
      )
    },
    editor,
    toText: value => codeOf(dialog, value),
    fromText: (text, current) => {
      const nextCode = text.trim().normalize('NFKC')
      if (nextCode === codeOf(dialog, current)) return undefined
      return { value: nextCode === '' ? emptyRefValue(dialog) : withCode(dialog, current, nextCode) }
    },
    onCellKeyDown: ({ event, rowKey, requestEditStart }) => {
      if (event.key === ' ' && event.ctrlKey) {
        event.preventDefault()
        requestDialog(rowKey, requestEditStart)
      }
    },
  })

  // 照合は検証ルールとして登録する。コードを書き換えた後にグリッドがこの検証を実行することで照合が始まる
  return attachColumnRules(column, {
    path,
    validate: (value, cellFormPath) => codeMatching.validate(cellFormPath, codeOf(dialog, value), params),
  })
}

/** コードのセルエディタ。参照を使い回すためモジュールのトップレベルで作る */
const CODE_CELL_EDITOR = createTextCellEditor({ multiline: false })

/**
 * 外部参照の列のセルエディタを作る。コードの手入力に加え、Ctrl+Space による検索ダイアログの表示を受け持つ。
 *
 * 読み取り専用かどうかの判定はグリッドの編集開始の処理だけが知っているので、
 * Ctrl+Space ではいったんグリッドの編集開始を求め、編集が始まった（= 読み取り専用でなかった）ら編集を取り消してダイアログを開く。
 * 列ごとに、どの行のダイアログを開くよう求められているかを持つので、列ごとに作る。
 */
function createRefCellEditor(openDialogFor: (rowKey: string) => void): {
  editor: EG2.EditableGridCellEditor
  /** Ctrl+Space が押されたときに呼ぶ。読み取り専用でなければダイアログを開く */
  requestDialog: (rowKey: string, requestEditStart: () => void) => void
} {
  /** ダイアログを開くよう求められている行。編集開始を求めている間だけ値を持つ */
  let requestedRowKey: string | undefined
  /** 編集が始まったらダイアログを開く行 */
  let openingRowKey: string | undefined

  const editor: EG2.EditableGridCellEditor = React.forwardRef(function RefCellEditor(props, ref) {
    const innerRef = React.useRef<EG2.EditableGridCellEditorRef>(null)

    React.useImperativeHandle(ref, () => ({
      getCurrentValue: () => innerRef.current?.getCurrentValue() ?? '',
      setValueAndSelectAll: (value, timing) => {
        if (timing === 'edit-start' && requestedRowKey !== undefined) {
          openingRowKey = requestedRowKey
          return
        }
        innerRef.current?.setValueAndSelectAll(value, timing)
      },
      getDomElement: () => innerRef.current?.getDomElement() ?? null,
    }), [])

    // グリッドが編集中の状態になってからでないと編集を取り消せないため、ここでダイアログを開く
    React.useEffect(() => {
      if (!props.isEditing || openingRowKey === undefined) return
      const rowKey = openingRowKey
      openingRowKey = undefined
      props.requestCancel()
      openDialogFor(rowKey)
    }, [props.isEditing])

    return <CODE_CELL_EDITOR {...props} ref={innerRef} />
  })

  return {
    editor,
    requestDialog: (rowKey, requestEditStart) => {
      // 読み取り専用でなければ、この呼び出しの中でエディタの setValueAndSelectAll が呼ばれる
      requestedRowKey = rowKey
      requestEditStart()
      requestedRowKey = undefined
    },
  }
}

