//#region フォームとグリッドで共有する仕様

/** 外部参照の項目であることを確かめる。外部参照でない場合は例外を投げる */
function assertRefMember(member: AggregateMetadata.Member, path: string): AggregateMetadata.Ref {
  if (member.kind !== 'ref') throw new Error(`RefTo は ${path} の型（${member.kind}）を扱えません。`)
  return member
}

/** 項目の値からコードを読む */
function codeOf(dialog: SearchDialog<RHF.FieldValues, unknown>, value: unknown): string {
  const code = RHF.get(value, dialog.refField.codePath)
  return code === null || code === undefined ? '' : String(code)
}

/** 項目全体を空にした値 */
function emptyRefValue(dialog: SearchDialog<RHF.FieldValues, unknown>): RHF.FieldValues {
  const empty: RHF.FieldValues = {}
  RHF.set(empty, dialog.refField.codePath, '')
  RHF.set(empty, dialog.refField.namePath, '')
  return empty
}

/** コードを書き換え、名称を空にした値。照合が終わるまでは前のコードの名称を表示しないようにするため */
function withCode(dialog: SearchDialog<RHF.FieldValues, unknown>, current: unknown, code: string): RHF.FieldValues {
  const next: RHF.FieldValues = typeof current === 'object' && current !== null ? structuredClone(current) : {}
  RHF.set(next, dialog.refField.codePath, code)
  RHF.set(next, dialog.refField.namePath, '')
  return next
}

/**
 * 手入力されたコードの照合の記録。項目のパスごとに、最後に照合したコードとその結果を持つ。
 * フォーム1つ（グリッドなら列1つ）につき1つ作る。
 */
type CodeMatching = {
  /**
   * 項目のコードを照合し、エラーならメッセージを返す。検証ルールから呼ぶ。
   * 照合中なら同じ照合の完了を待ち、照合済みのコードなら照合し直さずに前回の結果を返す。
   * 照合が終わったときに項目のコードが変わっていなければ、照合の結果を項目に反映する。
   */
  validate: (formPath: string, code: string, params: unknown) => Promise<string | undefined>
  /** 検索ダイアログで選んだものを、照合済みとして記録する */
  markAsMatched: (formPath: string, code: string, params: unknown, item: RHF.FieldValues) => void
}

function createCodeMatching(dialog: SearchDialog<RHF.FieldValues, unknown>, formMethods: RHF.UseFormReturn<RHF.FieldValues>): CodeMatching {
  const records = new Map<string, { key: string, result: Promise<FindByCodeResult<RHF.FieldValues>> }>()
  // パラメータによって照合の結果が変わりうるので、パラメータも照合済みかどうかの判定に含める
  const keyOf = (code: string, params: unknown) => `${code}\u0000${JSON.stringify(params ?? null)}`

  /** 照合の結果を項目に反映する。見つかったらそれで項目全体を置き換え、見つからなければ名称を空にする */
  const applyResult = (formPath: string, code: string, result: FindByCodeResult<RHF.FieldValues>) => {
    const current = formMethods.getValues(formPath)
    if (codeOf(dialog, current) !== code) return
    if (result.type === 'found') {
      formMethods.setValue(formPath, result.item, { shouldDirty: true })
    } else if (RHF.get(current, dialog.refField.namePath)) {
      formMethods.setValue(`${formPath}.${dialog.refField.namePath}`, '', { shouldDirty: true })
    }
  }

  return {
    validate: async (formPath, code, params) => {
      if (code === '') return undefined
      const key = keyOf(code, params)
      let record = records.get(formPath)
      if (record?.key !== key) {
        const result = dialog.refField.findByCode(code, params)
          .catch((): FindByCodeResult<RHF.FieldValues> => ({ type: 'error', detail: {} }))
          .then(result => {
            applyResult(formPath, code, result)
            return result
          })
        record = { key, result }
        records.set(formPath, record)
      }
      return toMatchingError(code, await record.result)
    },
    markAsMatched: (formPath, code, params, item) => {
      records.set(formPath, { key: keyOf(code, params), result: Promise.resolve({ type: 'found', item }) })
    },
  }
}

/** 照合の結果をエラーメッセージにする。見つかった場合は undefined */
function toMatchingError(code: string, result: FindByCodeResult<RHF.FieldValues>): string | undefined {
  switch (result.type) {
    case 'found': return undefined
    case 'not-found': return `「${code}」に該当するデータがありません。`
    case 'ambiguous': return `「${code}」に該当するデータが${result.count}件あります。`
    case 'canceled': return `「${code}」の照合が中断されました。`
    case 'error': return result.detail.error?.join(' ') || `「${code}」の照合に失敗しました。`
  }
}

