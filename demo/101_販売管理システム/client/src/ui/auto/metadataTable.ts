import type { AggregateMetadata } from "../../__autoGenerated"

/*
 * メタデータの表から、画面を機械的に組み立てるための情報を読み取る関数。
 * ui フォルダ内部でのみ使用する。
 */

/** 表の1項目と、そのキー（構造体のルートから見たパス） */
export type TableEntry = {
  path: string
  member: AggregateMetadata.Member
}

/** 値項目に使う入力部品の種類 */
export type ValueInputKind = 'text' | 'textArea' | 'numeric' | 'date' | 'checkBox' | 'enum'

/**
 * 値項目に使う入力部品の種類を返す。
 * 対応する入力部品が無い値（バイナリや値オブジェクト）の場合は undefined。
 */
export function valueInputKindOf(member: AggregateMetadata.Value): ValueInputKind | undefined {
  if (member.enumType) return 'enum'
  switch (member.type) {
    case 'word': return 'text'
    case 'description': return 'textArea'
    case 'int':
    case 'decimal':
    case 'sequence':
    case 'year': return 'numeric'
    case 'date':
    case 'datetime':
    case 'yearmonth': return 'date'
    case 'bool': return 'checkBox'
    default: return undefined
  }
}

/** 表の項目を、表に定義された順に列挙する */
export function entriesOf(table: AggregateMetadata.Table): TableEntry[] {
  return Object.entries(table).map(([path, member]) => ({ path, member }))
}

/** 項目の祖先を、近いものから順に返す。構造体のルートそのものは含まない */
export function ancestorsOf(table: AggregateMetadata.Table, member: AggregateMetadata.Member): TableEntry[] {
  const ancestors: TableEntry[] = []
  let parentPath = member.parent
  while (parentPath !== null) {
    const parent = table[parentPath]
    if (!parent) break
    ancestors.push({ path: parentPath, member: parent })
    parentPath = parent.parent
  }
  return ancestors
}

/**
 * 項目から祖先 ancestorPath（null は構造体のルート）までの間にある祖先が、すべて子集約（1対1）かどうか。
 * 外部参照や子配列の境界を越えずに ancestorPath から辿れる項目かどうかの判定に使う。
 * ancestorPath が項目の祖先でない場合は false。
 */
export function isReachableOnlyThroughChild(table: AggregateMetadata.Table, member: AggregateMetadata.Member, ancestorPath: string | null): boolean {
  for (const ancestor of ancestorsOf(table, member)) {
    if (ancestor.path === ancestorPath) return true
    if (ancestor.member.kind !== 'child') return false
  }
  return ancestorPath === null
}

/** 項目とその祖先の表示用名称を、ルートに近い順に区切り文字でつないで返す。項目の位置を一目で分かるようにするため */
export function displayPathOf(table: AggregateMetadata.Table, path: string): string {
  const member = table[path]
  if (!member) return path
  return [...ancestorsOf(table, member).reverse().map(ancestor => ancestor.member), member]
    .map(m => m.displayName)
    .join(' / ')
}
