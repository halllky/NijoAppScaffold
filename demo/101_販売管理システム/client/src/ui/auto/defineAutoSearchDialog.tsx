import * as RHF from "react-hook-form"
import type { AggregateMetadata } from "../../__autoGenerated"
import type { SearchConditionBase, SearchConditionModule } from "../form/useSearchConditionForm"
import type { SearchResult } from "../search/usePagedSearch"
import { defineSearchDialog, type SearchDialog, type SearchDialogRefFieldDefinition } from "../search-dialog/defineSearchDialog"
import { STRING_SEARCH_BEHAVIOR_RANGE } from "../form-input/TextBox"
import { AutoSearchConditionFields } from "./AutoSearchConditionFields"
import { autoResultColumns } from "./autoResultColumns"
import { entriesOf } from "./metadataTable"

/** defineAutoSearchDialog に渡す、検索ダイアログごとに異なる部分 */
export type AutoSearchDialogDefinition<TSearchCondition extends SearchConditionBase, TItem> = {
  /** ダイアログのタイトル。「〇〇 検索」の〇〇の部分 */
  title: string
  /**
   * 参照先のクエリモデルの自動生成モジュールのうち、メタデータと検索条件の新規作成関数。
   * 検索条件欄は検索条件の表から、検索結果欄は画面表示用データの表から組み立てる。
   */
  autoGenerated: SearchConditionModule<TSearchCondition> & {
    metadata: { displayData: AggregateMetadata.Table }
  }
  /**
   * サーバー側の参照検索処理を呼ぶ。
   * condition の skip と take はダイアログが設定したものになっている。signal はサーバー呼び出しに渡すこと。
   */
  search: (condition: TSearchCondition, signal: AbortSignal) => Promise<SearchResult<TItem>>
  /**
   * 外部参照の入力欄にコード・名称として表示する値の、アイテムから見たパス。
   * 未指定の場合はメタデータから決める（defineAutoSearchDialog を参照）。
   */
  refField?: Pick<SearchDialogRefFieldDefinition<TSearchCondition, TItem, void>, 'codePath' | 'namePath'>
}

/**
 * 検索ダイアログを、参照先のクエリモデルのメタデータから機械的に組み立てて定義する。
 * モジュールのトップレベルで呼び、戻り値を検索ダイアログの対応表に登録して使う。
 * 見た目や振る舞いを調整したい場合はこの関数を使わず、defineSearchDialog で個別に定義すること。
 *
 * - 検索条件欄: 参照先の絞り込み条件のすべての値項目に入力欄を置く。外部参照先の項目も個別に指定できる。
 * - 検索結果欄: 参照先の画面表示用データの値項目を列にする。子配列の中の項目は表示しない。
 * - 初期の検索条件: 空の検索条件。並び順は指定しない。
 * - 開くときのパラメータ: 受け取らない。
 *
 * ## 外部参照の入力欄で使うコードと名称
 * refField を指定しなかった場合は、参照先の直下の文字列型（単語）の項目から次の順で決める。
 * 検索条件で範囲指定になる項目はコードの照合に使えないので候補にしない。
 *
 * - コード: キーの項目、完全一致で検索する項目、それ以外の項目 の順で、最初に見つかったもの
 * - 名称: コード以外で最初の項目。無ければコードと同じ項目
 *
 * 候補が1つも無い場合は例外を投げる。その参照先の検索ダイアログは個別に定義すること。
 */
export function defineAutoSearchDialog<TSearchCondition extends SearchConditionBase, TItem extends RHF.FieldValues>(
  definition: AutoSearchDialogDefinition<TSearchCondition, TItem>,
): SearchDialog<TItem> {
  const { title, autoGenerated, search } = definition
  const { searchCondition: conditionTable, displayData: displayDataTable } = autoGenerated.metadata
  const { codePath, namePath } = definition.refField ?? findCodeAndNamePath(title, displayDataTable, conditionTable)

  return defineSearchDialog<TSearchCondition, TItem>({
    title,
    autoGenerated,
    SearchCondition: ({ Input, FieldLabel }) => (
      <AutoSearchConditionFields table={conditionTable} Input={Input} FieldLabel={FieldLabel} />
    ),
    getResultColumns: () => autoResultColumns<TItem>(displayDataTable),
    search,
    // アイテムの値をすべて含めた文字列にする。キーになる項目をメタデータから確実には決められないため
    getItemKey: item => JSON.stringify(item),
    refField: {
      codePath,
      namePath,
      createConditionFromCode: code => {
        const condition = autoGenerated.createNewSearchCondition()
        RHF.set(condition.filter, codePath, code)
        return condition
      },
      toFilter: item => {
        const filter: RHF.FieldValues = {}
        RHF.set(filter, codePath, RHF.get(item, codePath))
        RHF.set(filter, namePath, RHF.get(item, namePath))
        return filter
      },
    },
  })
}

/** 外部参照の入力欄に表示するコードと名称のパスを、メタデータから決める */
function findCodeAndNamePath<TItem>(
  title: string,
  displayDataTable: AggregateMetadata.Table,
  conditionTable: AggregateMetadata.Table,
): { codePath: RHF.Path<TItem>, namePath: RHF.Path<TItem> } {
  // 参照先の直下の、検索条件で範囲指定にならない単語の項目
  const candidates = entriesOf(displayDataTable).filter(({ path, member }) => {
    if (member.kind !== 'value' || member.parent !== null || member.type !== 'word') return false
    const conditionMember = conditionTable[path]
    return conditionMember !== undefined && conditionMember.stringSearchBehavior !== STRING_SEARCH_BEHAVIOR_RANGE
  })
  const code = candidates.find(({ member }) => member.isKey)
    ?? candidates.find(({ path }) => conditionTable[path].stringSearchBehavior === STRING_SEARCH_BEHAVIOR_EXACT)
    ?? candidates[0]
  if (code === undefined) {
    throw new Error(`${title} の検索ダイアログを自動で組み立てられません。コードにできる文字列型の項目が無いため、検索ダイアログを個別に定義してください。`)
  }
  const name = candidates.find(candidate => candidate !== code) ?? code
  return {
    codePath: code.path as RHF.Path<TItem>,
    namePath: name.path as RHF.Path<TItem>,
  }
}

/** メタデータの検索挙動のうち、完全一致を表す値 */
const STRING_SEARCH_BEHAVIOR_EXACT = 'Exact'
