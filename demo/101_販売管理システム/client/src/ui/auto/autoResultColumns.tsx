import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import * as ReadOnlyColumn from "../ReadOnlyColumn"
import { ancestorsOf, displayPathOf, entriesOf, valueInputKindOf } from "./metadataTable"

/**
 * 検索結果のグリッドの読み取り専用列を、画面表示用データのメタデータの表から機械的に組み立てる。
 *
 * - 画面表示用データの値項目を、メタデータの表の順にすべて列にする。外部参照先や子集約の項目も列になる。
 * - 子配列の中の項目は、1行に収まらないので列にしない。
 * - 列見出しは、外部参照先や子集約の項目と区別できるよう、親の表示用名称を前に付ける。
 * - 金額・数量・小数は数値表示列（右寄せ・桁区切り）にする。連番や件数のような整数に桁区切りを付けると読みにくいため、それ以外の整数は文字列表示列にする。
 * - 対応する表示が無い型（バイナリなど）の項目は列にしない。
 *
 * 行は、表のキーのパスでそのまま値を引ける形であること（画面表示用データや、外部参照先の参照用データ）。
 */
export function autoResultColumns<TRow>(table: AggregateMetadata.Table): EG2.EditableGridColumn<TRow>[] {
  return entriesOf(table).flatMap(({ path, member }): EG2.EditableGridColumn<TRow>[] => {
    if (member.kind !== 'value') return []
    if (ancestorsOf(table, member).some(ancestor => ancestor.member.kind === 'children')) return []

    const header = displayPathOf(table, path)
    const getValue = (row: TRow): unknown => RHF.get(row, path)
    switch (valueInputKindOf(member)) {
      case 'numeric':
        return isAmount(member)
          ? [ReadOnlyColumn.numeric<TRow>(header, getValue, { columnId: path })]
          : [ReadOnlyColumn.text<TRow>(header, row => toText(getValue(row)), { columnId: path })]
      case 'checkBox':
        return [ReadOnlyColumn.text<TRow>(header, row => getValue(row) ? '✓' : '', { columnId: path })]
      case 'text':
      case 'textArea':
      case 'date':
      case 'enum':
        return [ReadOnlyColumn.text<TRow>(header, row => toText(getValue(row)), { columnId: path })]
      case undefined:
        return []
    }
  })
}

/** 桁区切りを付けて表示すべき数値かどうか */
function isAmount(member: AggregateMetadata.Value): boolean {
  return member.type === 'decimal' || member.isCurrency === true || member.isQuantity === true
}

/** セルに表示する文字列。文字列と数値以外は表示しない */
function toText(value: unknown): string {
  return typeof value === 'string' || typeof value === 'number' ? String(value) : ''
}
