import React from "react"
import * as RHF from "react-hook-form"
import type { AggregateMetadata } from "../../__autoGenerated"
import type { BoundInputs } from "../form-input/bindInputs"
import type { FieldLabelProps } from "../form/FieldLabel"
import { AutoFieldGroups, AutoValueInput } from "./AutoFieldGroups"
import { entriesOf, valueInputKindOf } from "./metadataTable"

export type AutoSearchConditionFieldsProps<TFilter extends RHF.FieldValues> = {
  /** 検索条件の絞り込み条件のメタデータの表 */
  table: AggregateMetadata.Table
  /** useSearchConditionForm の戻り値の Input */
  Input: BoundInputs<TFilter>
  /** useSearchConditionForm の戻り値の FieldLabel */
  FieldLabel: (props: FieldLabelProps<TFilter>) => React.ReactNode
  /** すべての入力欄を読み取り専用にするかどうか。未指定の場合は false */
  isReadOnly?: boolean
}

/**
 * 検索条件欄の中身を、メタデータの表から機械的に組み立てる。
 * 検索ボタンなどは含まない。useSearchConditionForm のフォームの中に置くこと。
 *
 * - 絞り込み条件のすべての値項目に入力欄を置く。外部参照先や子集約の項目も、それぞれ個別の入力欄になる。
 *   外部参照を検索ダイアログで選ぶ入力欄は使わない。参照先のどの項目でも絞り込めるようにするため。
 * - 入力欄の種類は値の型から決まる（数値・日付は範囲指定、列挙体は複数選択など）。対応する入力欄が無い型の項目は表示しない。
 * - 項目の並びはメタデータの表の順で、親（外部参照・子集約）ごとに見出しを付けて分ける。並びや幅は調整できない。
 *   調整したい場合はこの部品を使わず、検索条件欄を個別に組み立てること。
 */
export function AutoSearchConditionFields<TFilter extends RHF.FieldValues>(props: AutoSearchConditionFieldsProps<TFilter>): React.ReactNode {
  const { table, Input, FieldLabel, isReadOnly } = props
  const entries = React.useMemo(() => entriesOf(table).filter(({ member }) =>
    member.kind === 'value' && valueInputKindOf(member) !== undefined), [table])

  return (
    <AutoFieldGroups
      table={table}
      entries={entries}
      renderField={({ path, member }) => (
        // 1項目
        <FieldLabel name={path as RHF.Path<TFilter>}>
          <AutoValueInput Input={Input} name={path} member={member as AggregateMetadata.Value} isReadOnly={isReadOnly} />
        </FieldLabel>
      )}
    />
  )
}
