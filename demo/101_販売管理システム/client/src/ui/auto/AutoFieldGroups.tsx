import React from "react"
import * as RHF from "react-hook-form"
import type { AggregateMetadata } from "../../__autoGenerated"
import type { BoundInputs } from "../input/bindInputs"
import { FieldColumn, FieldGroup } from "../FieldGroup"
import { displayPathOf, valueInputKindOf, type TableEntry } from "./metadataTable"

/**
 * 項目を、親（構造体のルート・外部参照・子集約）ごとの FieldGroup に分けて並べる。ui フォルダ内部でのみ使用する。
 *
 * - 親が構造体のルートの項目は見出し無し、それ以外は親の位置を見出しにする。
 *   ラベルには項目自身の表示用名称しか出ないので、どの外部参照の項目かを見出しで示すため。
 * - FieldGroup の中は、項目が多ければ2列に分ける。意味の切れ目は分からないので、前半と後半で機械的に分ける。
 * - 各項目の描画は renderField に任せる。
 */
export function AutoFieldGroups({ table, entries, renderField }: {
  /** 項目の表示名と親子関係を引く表 */
  table: AggregateMetadata.Table
  /** 並べる項目。この順に並ぶ */
  entries: TableEntry[]
  /** 1項目分の描画。FieldLabel で囲んだものを返すこと */
  renderField: (entry: TableEntry) => React.ReactNode
}): React.ReactNode {
  const groups = groupByParent(entries)

  return (
    <div className="flex flex-col gap-4">
      {groups.map(group => (
        // 親ごとの枠
        <FieldGroup key={group.parentPath ?? ''} title={group.parentPath === null ? undefined : displayPathOf(table, group.parentPath)}>
          {splitIntoColumns(group.entries).map((column, columnIndex) => (
            // 列
            <FieldColumn key={columnIndex}>
              {column.map(entry => (
                <React.Fragment key={entry.path}>
                  {renderField(entry)}
                </React.Fragment>
              ))}
            </FieldColumn>
          ))}
        </FieldGroup>
      ))}
    </div>
  )
}

/**
 * 値項目の入力部品。値の型に合った入力部品をメタデータから選ぶ。ui フォルダ内部でのみ使用する。
 * 対応する入力部品が無い値の場合は何も描画しない。
 */
export function AutoValueInput<TValues extends RHF.FieldValues>({ Input, name, member, isReadOnly }: {
  /** フォームと結びついた入力部品 */
  Input: BoundInputs<TValues>
  /** 入力対象の項目 */
  name: string
  /** 入力対象の項目のメタデータ */
  member: AggregateMetadata.Value
  /** 読み取り専用かどうか。未指定の場合は false */
  isReadOnly?: boolean
}): React.ReactNode {
  const path = name as RHF.Path<TValues>
  switch (valueInputKindOf(member)) {
    case 'text': return <Input.TextBox name={path} isReadOnly={isReadOnly} />
    case 'textArea': return <Input.TextArea name={path} isReadOnly={isReadOnly} />
    case 'numeric': return <Input.NumericTextBox name={path} isReadOnly={isReadOnly} />
    case 'date': return <Input.DateInput name={path} isReadOnly={isReadOnly} />
    case 'checkBox': return <Input.CheckBox name={path} isReadOnly={isReadOnly} />
    case 'enum': return <Input.EnumSelection name={path} isReadOnly={isReadOnly} />
    case undefined: return null
  }
}

/** 項目を親ごとにまとめる。まとまりは、その親の項目が最初に現れた順に並ぶ */
function groupByParent(entries: TableEntry[]): { parentPath: string | null, entries: TableEntry[] }[] {
  const groups = new Map<string | null, TableEntry[]>()
  for (const entry of entries) {
    const group = groups.get(entry.member.parent)
    if (group) group.push(entry)
    else groups.set(entry.member.parent, [entry])
  }
  return Array.from(groups, ([parentPath, entries]) => ({ parentPath, entries }))
}

/** 項目が多ければ前半と後半の2列に分ける */
function splitIntoColumns(entries: TableEntry[]): TableEntry[][] {
  if (entries.length <= MAX_ITEMS_IN_SINGLE_COLUMN) return [entries]
  const half = Math.ceil(entries.length / 2)
  return [entries.slice(0, half), entries.slice(half)]
}

/** これ以下の項目数なら1列にする */
const MAX_ITEMS_IN_SINGLE_COLUMN = 3
