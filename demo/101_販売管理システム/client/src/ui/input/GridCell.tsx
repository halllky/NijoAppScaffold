import React from "react"
import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import { findMemberMetadata, type GridBinding } from "../FormBinding"
import { hasMessages, type Messages } from "../MessageList"
import type { ColumnOptionsBase } from "./InputProps"

/*
 * 列定義ヘルパーで作る列のうち、どの値の型の列にも共通する部分。
 * ui フォルダ内部でのみ使用する。
 *
 * - 見出しはメタデータの表示用名称。
 * - セルは、そのセルの項目に対するメッセージ（クライアント側エラー・サーバー側メッセージとも）があれば色で示し、マウスを乗せると内容を表示する。
 * - 編集の確定・貼り付け・クリアでは、行オブジェクトを複製して項目の値だけを書き換えたものを返す。
 */

/** 値の型ごとに異なる、セルの描画・編集・文字列との変換 */
export type CellDefinition = {
  /** セルの中身の描画 */
  render: (args: { value: unknown, rowKey: string, isReadOnly: boolean }) => React.ReactNode
  /** セルエディタ。未指定の場合はセルエディタで編集しない */
  editor?: EG2.EditableGridCellEditor
  /** 値を、セルエディタの初期値とコピーの文字列にする */
  toText: (value: unknown) => string
  /**
   * セルエディタで確定した文字列か貼り付けた文字列を、項目の値にする。
   * 書き込まない場合（解釈できない文字列の貼り付けなど）は undefined を返す。
   * current は書き込む前の項目の値。
   */
  fromText: (text: string, current: unknown) => { value: unknown } | undefined
  /** 右寄せにするなら true */
  alignRight?: boolean
  /** セルの中で折り返して全文を表示するなら true。未指定の場合は1行に収まらない部分を省略する */
  wrap?: boolean
  /** セルを選んだ状態でのキー操作。利用側がオプションで指定したものより先に呼ばれる */
  onCellKeyDown?: (args: Parameters<NonNullable<EG2.EditableGridLeafColumn<unknown>['onCellKeyDown']>>[0]) => void
}

/**
 * 列定義ヘルパーで作る列を組み立てる。
 * path は行オブジェクトから見たパス。
 * セルの描画に使う値の型は列定義の配列（EditableGridColumn）に入れたときと同じく any になる。
 */
export function defineCellColumn<TRow>(
  binding: GridBinding,
  path: string,
  options: ColumnOptionsBase<TRow> | undefined,
  cell: CellDefinition,
): EG2.EditableGridLeafColumn<TRow, any> {
  const member = findCellMemberMetadata(binding, path)
  const { header, columnId, onCellKeyDown, ...rest } = options ?? {}
  const headerText = header ?? (member.displayNameIsEmpty ? '' : member.displayName)

  const column: EG2.EditableGridLeafColumn<TRow, readonly [unknown, Messages]> = {
    ...rest,
    columnId: columnId ?? path,
    renderHeader: () => (
      <div className="px-1 text-sm truncate select-none" title={headerText}>
        {headerText}
      </div>
    ),
    // メッセージは行オブジェクトの外にあるので、セルの描画に使う値に含めて変化を検知させる
    getValuesForRender: (row, _rowIndex, rowKey) => [
      RHF.get(row, path),
      getCellMessages(binding, rowKey, path),
    ] as const,
    renderBody: ({ deps: [value, messages], rowKey, isReadOnly }) => (
      <CellFrame messages={messages} isReadOnly={isReadOnly} alignRight={cell.alignRight} wrap={cell.wrap}>
        {cell.render({ value, rowKey, isReadOnly })}
      </CellFrame>
    ),
    editor: cell.editor,
    cellToText: row => cell.toText(RHF.get(row, path)),
    textToCell: (row, text) => {
      const written = cell.fromText(text, RHF.get(row, path))
      if (written === undefined) return undefined
      const next = structuredClone(row)
      RHF.set(next as RHF.FieldValues, path, written.value)
      return next
    },
    onCellKeyDown: args => {
      cell.onCellKeyDown?.(args)
      if (!args.event.defaultPrevented) onCellKeyDown?.(args)
    },
  }
  return column
}

/** 列の項目のメタデータを引く。path は行オブジェクトから見たパス */
export function findCellMemberMetadata(binding: GridBinding, path: string): AggregateMetadata.Member {
  return findMemberMetadata(binding.form.metadata, `${binding.arrayName}.${path}`)
}

/** 行キーと行オブジェクトから見たパスから、その行の項目のフォーム全体から見たパスを求める。行が無ければ undefined */
export function toCellFormPath(binding: GridBinding, rowKey: string, path: string): string | undefined {
  const rowIndex = binding.findRowIndex(rowKey)
  return rowIndex === undefined ? undefined : `${binding.arrayPath}.${rowIndex}.${path}`
}

/** セルの項目に対するメッセージ */
function getCellMessages(binding: GridBinding, rowKey: string, path: string): Messages {
  const cellFormPath = toCellFormPath(binding, rowKey, path)
  return cellFormPath === undefined
    ? NO_MESSAGES
    : binding.form.getFieldMessages(cellFormPath)
}

const NO_MESSAGES: Messages = { errors: [], warnings: [], informations: [] }

/**
 * セルの外枠。メッセージがあれば色で示し、マウスを乗せると内容を表示する。
 * 編集できるセルは、どこが入力できるか分かるよう背景を白にする。
 */
function CellFrame({ messages, isReadOnly, alignRight, wrap, children }: {
  messages: Messages
  isReadOnly: boolean
  alignRight?: boolean
  wrap?: boolean
  children?: React.ReactNode
}) {
  const messageClassName = messages.errors.length > 0 ? 'bg-rose-100 outline outline-rose-500 -outline-offset-1'
    : messages.warnings.length > 0 ? 'bg-amber-100 outline outline-amber-500 -outline-offset-1'
      : messages.informations.length > 0 ? 'bg-sky-100'
        : isReadOnly ? '' : 'bg-white'
  const title = hasMessages(messages)
    ? [...messages.errors, ...messages.warnings, ...messages.informations].join('\n')
    : undefined

  return (
    <div
      title={title}
      // セルは横並びの flex なので、flex-1 で幅を、既定の stretch で高さをセルいっぱいにする。
      // セルエディタの枠線と文字の縦位置をそろえるため、同じ太さの透明な枠線を付ける
      className={`flex-1 min-w-0 px-1 text-sm border border-transparent ${wrap ? 'whitespace-pre-wrap break-all' : 'truncate'} ${alignRight ? 'text-right' : ''} ${messageClassName}`}
    >
      {children}
    </div>
  )
}

