import React from "react"
import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import * as Icon from "@heroicons/react/24/solid"
import { Allotment, LayoutPriority } from "allotment"
import useEvent from "react-use-event-hook"
import { useLocation } from "react-router-dom"
import type { ASC_SUFFIX, DESC_SUFFIX } from "../../__autoGenerated"
import { PageBase } from "../PageBase"
import { PageTitle } from "../parts/PageTitle"
import { Breadcrumb, type BreadcrumbItem } from "../parts/Breadcrumb"
import { Button } from "../parts/Button"
import { NowLoading } from "../parts/NowLoading"
import { Pager } from "../parts/Pager"
import type { SearchConditionBase, UseSearchConditionFormReturn } from "../useSearchConditionForm"
import { usePagedSearch, type SearchResult } from "../usePagedSearch"
import { useSearchParamsAsCondition } from "./useSearchParamsAsCondition"
import { SortDropdown, type SortComboItem, type SortValue } from "./SortDropdown"

export type { SortComboItem }

/** 一覧検索画面で扱える検索条件。絞り込み条件に加えて、並び順とページングの指定を持つ */
export type PageableSearchCondition = SearchConditionBase & {
  sort: string[]
  skip?: string | null
  take?: string | null
}

/** 検索条件の並び順に指定できるメンバー。並び順の要素から昇順・降順の接尾辞を除いたもの */
export type SortableMemberOf<TSearchCondition extends PageableSearchCondition>
  = RemoveSortSuffix<TSearchCondition['sort'][number]>

export type SearchPageBaseProps<TSearchCondition extends PageableSearchCondition, TItem> = {
  /**
   * 検索条件欄のフォーム。useSearchConditionForm の戻り値をそのまま渡す。
   * 検索条件欄の入力コンポーネントとラベルは、このフォームのものを使うこと。
   */
  form: Pick<
    UseSearchConditionFormReturn<TSearchCondition>,
    'formMethods' | 'RootErrors' | 'setServerMessages' | 'clearServerMessages' | 'createNewSearchCondition'
  >
  /** ページタイトル。ブラウザのタイトルバーにも表示されます。 */
  pageTitle?: string
  /**
   * パンくずリストとしてページタイトルの前に表示する、このページより上位のページ。最上位から順に並べる。
   * 未指定の場合はページタイトルだけを表示する。
   */
  breadcrumb?: BreadcrumbItem[]
  /** 検索条件欄のデフォルトサイズ（ピクセル） */
  searchConditionDefaultSize?: number
  /** ヘッダー部分のページタイトルの横の部分のレイアウト */
  header?: React.ReactNode
  /**
   * 検索条件欄。この欄はformタグの内側に配置されます。
   * 検索ボタン・クリアボタンと、どの項目とも紐づかないメッセージはこのコンポーネントが表示するので、ここには含めない。
   */
  searchCondition: React.ReactNode
  /** 検索結果エリアのグリッドの列定義 */
  defineSearchResultColumns: [
    () => EG2.EditableGridColumn<TItem>[],
    deps: React.DependencyList
  ]
  /** 並び順コンボボックスの選択肢。未指定の場合はコンボボックスを表示しない */
  sortOptions?: SortComboItem<SortableMemberOf<TSearchCondition>>[]
  /**
   * 既定の検索条件生成処理。URLに検索条件が無いときと、クリアボタンが押されたときの検索条件になる。並び順の初期値もここで指定する。
   * 未指定の場合は空の検索条件。
   */
  createInitialCondition?: () => TSearchCondition
  /** クリア操作後のフック */
  onCleared?: (condition: TSearchCondition) => void
  /**
   * サーバー側の検索処理を呼ぶ。
   * condition の skip と take はこのコンポーネントがページングのために設定したものになっている。
   * signal は、検索中に次の検索が始まったときに中断するためのもの。サーバー呼び出しに渡すこと。
   */
  search: (condition: TSearchCondition, signal: AbortSignal) => Promise<SearchResult<TItem>>
}

/**
 * 一覧検索画面のベースコンポーネント。
 *
 * ### このコンポーネントの責務
 * - ページの枠のレイアウト（検索条件、結果、ページャ）
 * - 検索処理の呼び出しと結果の保持
 * - 検索処理が返したメッセージの表示
 * - ページング管理
 * - 並び順の指定
 * - URLのクエリパラメータと検索条件オブジェクトの同期
 *
 * ### 利用側の責務
 * - 検索条件フォームの作成（useSearchConditionForm）
 * - 検索条件フォームのレイアウト
 * - 検索結果一覧のレイアウト
 * - サーバー側の検索処理の呼び出し方
 * - 初期検索条件やソート選択肢などの設定値の提供
 */
export function SearchPageBase<TSearchCondition extends PageableSearchCondition, TItem>(
  props: SearchPageBaseProps<TSearchCondition, TItem>
) {
  const { formMethods, RootErrors, setServerMessages, clearServerMessages, createNewSearchCondition } = props.form
  const { control, reset, handleSubmit, setValue, getValues } = formMethods
  const createInitialCondition = props.createInitialCondition ?? createNewSearchCondition

  //#region 状態

  // 検索の実行と結果。ページを移動するときは、最後に検索した条件を使う
  const { searched, isSearching, searchPage } = usePagedSearch(props.search, setServerMessages)
  const items = searched?.result.currentPageItems ?? EMPTY_ITEMS as TItem[]
  const totalCount = searched?.result.totalCount ?? 0
  const pageIndex = searched?.pageIndex ?? 0
  const pageSize = searched?.pageSize ?? DEFAULT_PAGE_SIZE

  // URLのクエリパラメータを検索条件オブジェクトとして扱うためのフック
  const {
    searchParamsAsCondition,
    applyConditionToUrl,
  } = useSearchParamsAsCondition(createNewSearchCondition)

  // 検索条件欄を折りたたんでいるかどうか
  const [searchConditionVisible, setSearchConditionVisible] = React.useState(true)

  // 検索条件欄の form 要素。ヘッダの検索ボタンは form 属性でこの要素と結びつく
  const formRef = React.useRef<HTMLFormElement>(null)
  const formId = React.useId()

  //#endregion 状態

  //#region 検索

  // URLのクエリパラメータを正とした検索条件をフォームに反映し、検索する。
  const location = useLocation()
  const searchByUrl = useEvent(() => {
    // マージ戦略:
    // URLにパラメータがある場合 -> URLの状態(searchParamsAsCondition)を正とする
    // URLにパラメータがない場合 -> 画面の初期値(createInitialCondition)を正とする
    // ※ searchParamsAsCondition は「空の条件」で初期化されているため、
    //    URLパラメータがない時にこれを使うと初期値 (初期ソート順など) が消えてしまいます。
    const hasSearchParams = location.search !== "" && location.search !== "?"
    const nextCondition = hasSearchParams
      ? searchParamsAsCondition
      : createInitialCondition()

    reset(nextCondition)

    // 決定した検索条件を正として検索を実行
    const take = Number(nextCondition.take) || DEFAULT_PAGE_SIZE
    const skip = Number(nextCondition.skip) || 0
    searchPage(nextCondition, Math.floor(skip / take), take)
  })

  // 画面初期表示、ブラウザバック、ブラウザフォワード、F5リロード、検索操作などでURLへの遷移が起きたら検索する（URLとの同期）。
  // 依存配列を location.search ではなく location.key にしているのは、同じ条件で検索ボタンを押したときのように
  // URLが変わらない遷移でも検索し直すため。key は遷移のたびに変わる。
  // 画面から離れたときの中断は usePagedSearch が行う
  React.useEffect(() => {
    searchByUrl()
  }, [location.key, searchByUrl])

  // 画面を開いたら、検索条件欄の最初の入力欄にフォーカスを移す（DOM との同期）
  React.useEffect(() => {
    formRef.current?.querySelector<HTMLElement>('input, select, textarea')?.focus()
  }, [])

  // 検索ボタンが押されたとき、またはフォーム内でEnterされたときの処理。
  // 検索条件欄で入力された内容で、1ページ目に戻る条件で検索を実行する。
  const handleSearch = handleSubmit(condition => {
    applyConditionToUrl({
      ...condition,
      skip: '0',
      take: pageSize.toString(),
    })
  })

  // ページャでページが変更されたときの処理。
  // 現在フォームで入力されている値ではなく、最後に検索した条件をもとにして検索を実行する。
  const handlePageChange = (newPage: number) => {
    if (!searched) return
    applyConditionToUrl({
      ...searched.condition,
      skip: (newPage * pageSize).toString(),
      take: pageSize.toString(),
    })
  }

  // 並び順が変更されたときの処理。
  // 現在フォームで入力されている値と新しい並び順で、1ページ目に戻る条件で検索を実行する。
  const sort = RHF.useWatch({ control, name: SORT_PATH as RHF.Path<TSearchCondition> }) as SortValue<SortableMemberOf<TSearchCondition>>[] | undefined
  const handleSortChange = (newSort: SortValue<SortableMemberOf<TSearchCondition>>[]) => {
    setValue(SORT_PATH as RHF.Path<TSearchCondition>, newSort as RHF.PathValue<TSearchCondition, RHF.Path<TSearchCondition>>, { shouldDirty: true })
    applyConditionToUrl({
      ...getValues(),
      sort: newSort,
      skip: '0',
      take: pageSize.toString(),
    })
  }

  // クリアボタンが押されたときの処理。検索条件を初期値に戻して、1ページ目から検索し直す
  const handleClear = () => {
    const initial: TSearchCondition = {
      ...createInitialCondition(),
      skip: '0',
      take: pageSize.toString(),
    }
    reset(initial)
    clearServerMessages()
    applyConditionToUrl(initial)
    props.onCleared?.(initial)
  }

  //#endregion 検索

  //#region グリッド

  // グリッドの列定義・行キー
  const [getColumnsFn, columnDeps] = props.defineSearchResultColumns
  const columns = React.useMemo(getColumnsFn, columnDeps)
  const rowKeys = React.useMemo(() => items.map((_, index) => index.toString()), [items])
  const getLatestRowObject = React.useCallback((index: number) => items[index], [items])

  //#endregion グリッド

  //#region レンダリング

  return (
    <PageBase
      browserTitle={props.pageTitle}
      className="overflow-hidden"
      header={(
        <>
          <div className="flex-1 flex items-center gap-2">
            {/* パンくずリスト。リンクをボタンの中に置けないので、ページタイトルのボタンの外に置く */}
            {props.breadcrumb && (
              <Breadcrumb items={props.breadcrumb} />
            )}
            {/* ページタイトル。クリックで検索条件欄を折りたたむ */}
            <button
              type="button"
              className="flex-1 flex items-center gap-1 cursor-pointer select-none"
              onClick={() => setSearchConditionVisible(prev => !prev)}
            >
              {searchConditionVisible ? (
                <Icon.ChevronDownIcon className="w-4 h-4" />
              ) : (
                <Icon.ChevronRightIcon className="w-4 h-4" />
              )}
              <PageTitle>
                {props.pageTitle}
              </PageTitle>
            </button>
          </div>

          {props.header}

          {/* クリア・検索 */}
          <Button outline onClick={handleClear}>
            クリア
          </Button>
          <Button submit fill form={formId}>
            検索
          </Button>
        </>
      )}
      contents={(
        <Allotment vertical
          defaultSizes={[props.searchConditionDefaultSize ?? 200, 999]}
          separator={false}
          proportionalLayout={false} // ページサイズ変更時に検索結果欄だけ伸縮するようにするため
          className="pb-1"
        >

          {/* 検索条件欄。検証はブラウザに任せず react-hook-form の検証ルールで行う */}
          <Allotment.Pane snap minSize={50} visible={searchConditionVisible} className="pb-1">
            <form
              ref={formRef}
              id={formId}
              noValidate
              className="h-full overflow-auto flex flex-col gap-2 py-1"
              onSubmit={handleSearch}
            >
              {/* どの項目にも表示されないメッセージ */}
              <RootErrors />

              {props.searchCondition}
            </form>
          </Allotment.Pane>

          {/* 件数表示、ソート順指定、検索結果欄 */}
          <Allotment.Pane
            priority={LayoutPriority.High} // ページサイズ変更時に検索結果欄だけ伸縮する
            className="relative"
          >
            <div className="h-full flex flex-col">

              <div className="flex flex-wrap items-center py-1">
                {/* 件数表示 */}
                <div className="min-w-48 text-sm text-gray-600">
                  {isSearching && (
                    <>検索中...</>
                  )}
                  {!isSearching && totalCount > 0 && (
                    <>
                      全{totalCount}件中 {pageIndex * pageSize + 1} - {Math.min((pageIndex + 1) * pageSize, totalCount)} 件を表示
                    </>
                  )}
                  {!isSearching && totalCount === 0 && (
                    <>全0件</>
                  )}
                </div>

                <div className="basis-4"></div>

                {/* ソート順指定 */}
                <SortDropdown
                  className="ml-2 min-w-[200px]"
                  sortOptions={props.sortOptions}
                  value={sort ?? []}
                  onChange={handleSortChange}
                />
              </div>

              {/* 検索結果 */}
              <EG2.EditableGrid
                rowKeys={rowKeys}
                getLatestRowObject={getLatestRowObject}
                columns={columns}
                clearSelectionOnBlur
                className="flex-1 border border-gray-600"
              />
            </div>

            {isSearching && (
              <NowLoading opacity={0} />
            )}
          </Allotment.Pane>

        </Allotment>
      )}
      footer={(
        <Pager
          pageIndex={pageIndex}
          pageSize={pageSize}
          totalCount={totalCount}
          onPageChange={handlePageChange}
          disabled={isSearching}
        />
      )}
    />
  )

  //#endregion レンダリング
}

const EMPTY_ITEMS: unknown[] = []

/** URLで1ページの件数が指定されていないときの、1ページの件数 */
const DEFAULT_PAGE_SIZE = 20

/** 検索条件のうち、並び順のプロパティ名 */
const SORT_PATH = 'sort'

/** 並び順の要素から昇順・降順の接尾辞を除く */
type RemoveSortSuffix<T>
  = T extends `${infer TMember}${ASC_SUFFIX}` ? TMember
  : T extends `${infer TMember}${DESC_SUFFIX}` ? TMember
  : never
