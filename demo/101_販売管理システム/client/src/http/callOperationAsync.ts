import { UUID } from "uuidjs"
import * as AutoGenerated from "../__autoGenerated"
import { callAspNetCoreApiAsync } from "./callAspNetCoreApiAsync"

/**
 * 自動生成されたクエリ（一覧検索、参照検索）またはコマンドのエンドポイントを呼び出す。
 * サーバー側のエンドポイントの処理と対になっており、HTTPリクエスト・レスポンスの形はこの2つの間の取り決めである。
 */
export async function callOperationAsync<TName extends AutoGenerated.Operation.Name>(
  name: TName,
  parameter: AutoGenerated.Operation.ParamType[TName],
  options?: OperationOptions,
): Promise<OperationResult<AutoGenerated.Operation.ReturnType[TName]>> {

  // -------------------------
  // 注意:
  // この関数の処理は NijoAppScaffold として決まった仕様があるわけではない。
  // 実際の処理はアプリケーションごとの仕様に応じて適宜カスタマイズすること。
  // 多くの場合、クライアント側からサーバー側のエンドポイントを呼び出す方式はアプリケーション全体で統一されているべきであるため、
  // この関数の処理をクライアント側共通のヘルパー関数として実装し、各画面から呼び出す形にすることが望ましい。
  // -------------------------

  try {
    // 添付ファイルを処理する。
    // リクエスト全体は Content-Type: multipart/form-data で送信する。
    // 処理の引数は "parameter" という名前のフィールドにJSONをまるごと格納する。
    // 添付ファイルは、ファイル1件ごとにUUIDを発番し、そのUUIDをキーとしてファイル本体のバイナリをそのフィールドに格納する。
    const formData = new FormData()
    const stringifiedParameter = JSON.stringify(parameter, (_, value) => {
      // FileListならばこのタイミングでファイル1件ごとにUUIDを発番し、別フィールドにファイルの実体（Blob）を格納する
      if (value instanceof FileList) {
        const fileMetadataList: FileAttachmentMetadata[] = []
        for (const file of value) {
          const uuid = UUID.generate()
          formData.append(uuid, file)
          fileMetadataList.push({
            id: uuid,
            fileName: file.name,
            fileSize: file.size,
          })
        }
        return fileMetadataList
      }

      // HTTP通信量削減のため、null, 空文字, 空配列、空オブジェクトはシリアライズしない
      function isEmptyValueRecursive(value: unknown): boolean {
        if (value === null) return true
        if (typeof value === 'string' && value === '') return true
        if (Array.isArray(value) && value.length === 0) return true
        if (typeof value === 'object' && Object.values(value).every(isEmptyValueRecursive)) return true
        return false
      }
      if (isEmptyValueRecursive(value)) return undefined

      return value
    }) ?? '{}' // 引数が空の場合も、サーバー側で空のオブジェクトとして解釈できるようにする
    formData.append('parameter', stringifiedParameter)

    // -------------------------
    // 「～しますがよろしいですか？」の確認メッセージが表示される前の、エラーチェックのみを行なうHTTPリクエストでは、
    // クエリパラメータに `confirmed` を指定しない。
    // 確認メッセージが承諾された後の本処理を行なうHTTPリクエストでは、クエリパラメータに `confirmed=true` を指定する。
    // オプションで確認済みと指定されている場合は1巡目から `confirmed=true` を指定する。
    const searchParams = new URLSearchParams()
    if (options?.confirmed) {
      searchParams.append(CONFIRMED, 'true')
    }

    while (true) {
      const url = AutoGenerated.Operation.Endpoint[name] + '?' + searchParams.toString()
      const response = await callAspNetCoreApiAsync(url, {
        method: 'POST',
        body: formData,
        signal: options?.signal,
      })

      // ログイン状態が切れていて、利用者がログインし直さなかった
      if (response.status === 401) {
        return { type: 'error', detail: { error: ['ログイン状態が切れています。ログインし直してから、もう一度操作してください。'] } }
      }

      // 422 は、処理は実行されたが、入力エラーなどのメッセージがあることを示す
      if (response.status === 422) {
        const json = await response.json() as OperationResponse<unknown>
        return { type: 'error', detail: json.detail }
      }

      // それ以外で 200-299 でない場合は、サーバーからの応答が無い、サーバー側で復旧不可のエラーが発生した、などを示す
      if (!response.ok) {
        return {
          type: 'error',
          detail: { error: [await toDisplayErrorText(response)] },
        }
      }

      const json = await response.json() as OperationResponse<AutoGenerated.Operation.ReturnType[TName]>

      // 「保存しますがよろしいですか？」などの確認が必要な場合。
      // 利用者が承諾したら、確認済みとしてリクエストを送り直す
      if (json.requiresConfirmation) {
        let confirmMessage = json.confirms.join('\n')
        if (confirmMessage === '') {
          // 基本的には Command Model の Execute メソッド内で明示的に文言が指定されているが、
          // もし確認メッセージが空の場合（実装漏れの場合）はデフォルトのメッセージを表示する。
          confirmMessage = '処理を確定しますか？'
        }
        if (window.confirm(confirmMessage)) {
          searchParams.set(CONFIRMED, 'true')
          continue
        } else {
          return { type: 'canceled' }
        }
      }

      return { type: 'ok', returnValue: json.returnValue, detail: json.detail }
    }

  } catch (error) {
    if (error instanceof DOMException && error.name === 'AbortError') {
      return { type: 'canceled' }
    }
    return { type: 'error', detail: { error: [handleUnknownError(error)] } }
  }
}

/**
 * 画面の読み込み処理（React Router の loader）から、自動生成されたクエリまたはコマンドを呼び出す。
 * 確認メッセージは出さない。成功したら戻り値を返し、それ以外は例外を送出する（ルートのエラー画面に表示される）。
 *
 * @param signal loader の引数の request.signal。画面遷移が中断されたら、サーバーの呼び出しも中断する
 */
export async function loadOperationAsync<TName extends AutoGenerated.Operation.Name>(
  name: TName,
  parameter: AutoGenerated.Operation.ParamType[TName],
  signal: AbortSignal,
): Promise<AutoGenerated.Operation.ReturnType[TName]> {
  const result = await callOperationAsync(name, parameter, { confirmed: true, signal })
  if (result.type === 'ok') {
    return result.returnValue

  } else if (result.type === 'error') {
    throw new Error(toFlattenStringList(result.detail).join('\n') || '処理に失敗しました。')

  } else {
    // 画面遷移が中断された場合。React Router は中断された読み込みの結果を使わない
    throw new Error('処理が中断されました。')
  }
}

