// 内部処理用ヘルパー関数等

/** {@link callOperationAsync} の結果 */
export type OperationResult<TSuccess>
  = { type: 'ok', returnValue: TSuccess, detail: OperationMessages }
  | { type: 'canceled' }
  | { type: 'error', detail: OperationMessages }

/**
 * 未知のエラーを、画面上に表示できる文字列に変換する。
 */
const handleUnknownError = (error: unknown): string => {
  if (error instanceof Error) {
    return error.message
  } else if (typeof error === 'string') {
    return error
  } else {
    return JSON.stringify(error)
  }
}

/**
 * 未知のレスポンスを、画面上に表示できる文字列に変換する。
 */
const toDisplayErrorText = async (response: Response): Promise<string> => {
  // ok の場合はここに来ないはず
  if (response.ok) {
    return '不明なエラーが発生しました'
  }

  try {
    const bodyText = await response.clone().text()
    try {
      const json: unknown = JSON.parse(bodyText)

      if (typeof json === 'string') {
        return json
      } else if (typeof (json as { message: string }).message === 'string') {
        return (json as { message: string }).message
      } else {
        return bodyText
      }
    } catch {
      return bodyText
    }
  } catch (error) {
    return `HTTP ${response.status} ${response.statusText}`
  }
}

/**
 * {@link callOperationAsync} が付けるクエリパラメータの名前。利用者が確認済みであることを表す。
 * 「～しますがよろしいですか？」の確認メッセージが表示される前の、エラーチェックのみを行なうHTTPリクエストでは付されず、
 * 確認メッセージが承諾された後の本処理を行なうHTTPリクエストではtrueが指定される。
 * サーバー側は、これが無ければ入力チェックのみを行う。
 */
const CONFIRMED = "confirmed"

export type OperationOptions = {
  /** 確認済みとして呼び出す。確認メッセージを表示せず、1回目のリクエストで本処理まで行う */
  confirmed?: true
  /** 中断用シグナル */
  signal?: AbortSignal
}

/**
 * {@link callOperationAsync} が受け取るHTTPレスポンスの本体。
 * サーバー側が返すレスポンスの型と合わせる必要がある。
 */
type OperationResponse<T> = {
  /** 詳細メッセージ。パラメータの型と同じ構造をもち、フィールドごとにそのフィールドに対するメッセージが格納される。 */
  detail: OperationMessages
  /** 確認メッセージ */
  confirms: string[]
  /** 利用者の確認を得てから、確認済みとして送り直す必要があるかどうか */
  requiresConfirmation: boolean
  /** トーストメッセージ */
  toastMessage?: string
  /** バックエンドからの戻り値 */
  returnValue: T
}

/**
 * サーバーから返されるメッセージ（レスポンスの detail プロパティ）。
 * 処理の引数と同じ構造をもち、項目ごとにその項目に対するメッセージが格納される。
 */
export type OperationMessages = {
  error?: string[]
  warn?: string[]
  info?: string[]
  children?: { [key: string]: OperationMessages }
}

/**
 * エラー・警告・情報メッセージのオブジェクトを項目単位に変換する。
 * 例えば以下のオブジェクトは ['aaa.1.bbb: エラー1, 情報1'] に変換される。
 *
 * ```
 * {
 *   children: {
 *     aaa: {
 *       children: {
 *         '1': {
 *           children: {
 *             bbb: {
 *               error: ['エラー1'],
 *               info: ['情報1']
 *             }
 *           }
 *         }
 *       }
 *     }
 *   }
 * }
 * ```
 */
export const toFlattenStringList = (detail: OperationMessages): string[] => {
  const result: string[] = []
  const collectMessagesRecursively = (path: string[], current: OperationMessages) => {
    // error, warn, info を全部まとめて表示
    const allMessages = [...(current.error ?? []), ...(current.warn ?? []), ...(current.info ?? [])]
    if (allMessages.length > 0) {
      const key = path.join('.')
      if (key === '') {
        result.push(allMessages.join(', '))
      } else {
        result.push(`${key}: ${allMessages.join(', ')}`)
      }
    }

    // 子要素を再帰的に処理
    if (current.children) {
      for (const [key, child] of Object.entries(current.children)) {
        collectMessagesRecursively([...path, key], child)
      }
    }
  }
  collectMessagesRecursively([], detail)
  return result
}

/**
 * 添付ファイルのメタデータ。
 * ファイル1件ごとに発番されるID、ファイル名、ファイルサイズを保持する。
 */
type FileAttachmentMetadata = {
  id: string
  fileName: string
  fileSize: number
}
