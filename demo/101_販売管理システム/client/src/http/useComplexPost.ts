import React from "react"
import * as AutoGenerated from "../__autoGenerated"
import { useLoginLogout } from "../useLoginLogout"
import { callComplexPostEndpointAsync, type ComplexPostOptions, type ComplexPostResult } from "./callComplexPostEndpointAsync"

/**
 * 自動生成されたクエリ（一覧検索、参照検索）またはコマンドのエンドポイントを呼び出す関数を返す。
 *
 * ログインしていないと応答された場合は、ログイン状態をクリアしてログイン画面に戻し、canceled を返す。
 * 呼び出し元の画面はログイン画面に置き換わるので、canceled のときは何もしなくてよい。
 */
export function useComplexPost() {
  const { notifySessionExpired } = useLoginLogout()

  return React.useCallback(async <TName extends AutoGenerated.CommandQuery.Name>(
    type: TName,
    requestBody: AutoGenerated.CommandQuery.ParamType[TName],
    options?: ComplexPostOptions,
  ): Promise<ComplexPostResult<AutoGenerated.CommandQuery.ReturnType[TName]>> => {
    const result = await callComplexPostEndpointAsync(type, requestBody, options)
    if (result.type === 'unauthorized') {
      notifySessionExpired()
      return { type: 'canceled' }
    }
    return result
  }, [notifySessionExpired])
}
