/**
 * メタデータから求めた入力制約の検証。エラーならメッセージを、エラーでなければ undefined を返す。
 * 外部参照のコードの照合のように、非同期で検証するものは Promise を返してよい。
 */
export type FieldValidator = (value: unknown) => string | undefined | Promise<string | undefined>

/**
 * 入力コンポーネントの検証ルールを、react-hook-form の検証ルールにする。
 * 未入力の検証、メタデータから求めた検証、利用側が追加した独自の検証の順に評価し、最初のエラーを返す。
 *
 * 検索条件の範囲指定のように1つの項目を複数の入力欄で入力する場合は、そのうち1つの入力欄にだけ検証ルールを付け、
 * itemValueOf で項目全体の値を返すようにする。利用側の検証には項目全体の値が渡る。
 */
export function toRegisterRules(params: {
  rules: InputRules | undefined
  validators?: FieldValidator[]
  itemValueOf?: (fieldValue: unknown, formValues: RHF.FieldValues) => unknown
  /**
   * 入力欄に、値として解釈できない入力が残っていればエラーメッセージを返す。他のどの検証よりも先に評価する。
   * 入力途中の日付のように、フォームの値としては空になっていても入力欄には何かが入っていることがあり、
   * それを未入力のエラーとして示すと利用者が混乱するため。
   */
  checkUnparsableInput?: () => string | undefined
}): Pick<RHF.RegisterOptions, 'validate'> {
  const { rules, validators = [], itemValueOf = value => value, checkUnparsableInput } = params
  return {
    validate: async (fieldValue, formValues) => {
      const unparsable = checkUnparsableInput?.()
      if (unparsable !== undefined) return unparsable
      const value = itemValueOf(fieldValue, formValues)
      if (rules?.required && isEmptyValue(value)) return '必須です。'
      for (const validator of validators) {
        const error = await validator(value)
        if (error !== undefined) return error
      }
      return rules?.validate?.(value)
    },
  }
}

/** 未入力かどうか。オブジェクトはすべてのプロパティが未入力なら未入力とみなす */
function isEmptyValue(value: unknown): boolean {
  if (value === null || value === undefined || value === '' || value === false) return true
  if (Array.isArray(value)) return value.length === 0
  if (typeof value === 'object') return Object.values(value).every(isEmptyValue)
  return false
}

/**
 * 項目が、入力コンポーネントが扱える値の型であることを確かめて、値のメタデータとして返す。
 * 扱えない型の場合は例外を投げる。
 */
export function assertValueMember(
  member: AggregateMetadata.Member,
  path: string,
  componentName: string,
  isAcceptable: (member: AggregateMetadata.Value) => boolean,
): AggregateMetadata.Value {
  if (member.kind !== 'value' || !isAcceptable(member)) {
    const actual = member.kind === 'value' ? (member.type ?? member.enumType ?? '不明') : member.kind
    throw new Error(`${componentName} は ${path} の型（${actual}）を扱えません。`)
  }
  return member
}

/**
 * フォーカスしたときに入力欄の文字列を全選択する。戻り値のイベントハンドラを入力欄に付けること。
 * クリックでフォーカスした場合は、マウスボタンを離したときのキャレットの配置で全選択が解除されるので、その既定の動作を止める。
 * 既にフォーカスがある入力欄のクリックでは、通常どおりキャレットを置く。
 */
export function useSelectAllOnFocus(): {
  onFocus: React.FocusEventHandler<HTMLInputElement>
  onMouseDown: React.MouseEventHandler<HTMLInputElement>
  onMouseUp: React.MouseEventHandler<HTMLInputElement>
} {
  /** フォーカスの無い状態からのクリック中かどうか */
  const isFocusingByClickRef = React.useRef(false)
  return {
    // フォーカス時に表示する文字列が変わる入力欄もあるので、描画し直した後に選択する
    onFocus: e => {
      const input = e.currentTarget
      setTimeout(() => input.select(), 0)
    },
    onMouseDown: e => {
      isFocusingByClickRef.current = document.activeElement !== e.currentTarget
    },
    onMouseUp: e => {
      if (!isFocusingByClickRef.current) return
      isFocusingByClickRef.current = false
      e.preventDefault()
    },
  }
}

/** 入力欄の枠と背景。読み取り専用の場合は枠と背景色を消して値だけを表示する */
export function inputFrameClassName(isReadOnly: boolean | undefined): string {
  return isReadOnly
    ? 'border border-transparent bg-transparent'
    : 'border border-gray-700 bg-white focus-within:outline focus-within:outline-blue-500'
}

/**
 * 列定義ヘルパーで作った列の、各行の項目に付ける検証ルール。
 * グリッドのセルは react-hook-form に登録された入力欄を持たないため、グリッドが行ごとの項目にこの検証ルールを登録する。
 */
export type ColumnRules = {
  /** 検証する項目の、行オブジェクトから見たパス */
  path: string
  /** 検証。cellFormPath はその行の項目の、フォーム全体から見たパス */
  validate: (value: unknown, cellFormPath: string) => string | undefined | Promise<string | undefined>
}

/** 列に検証ルールを結びつける。列定義の型を変えずに済むよう、列のオブジェクトとは別に持つ */
export function attachColumnRules<TColumn extends object>(column: TColumn, rules: ColumnRules): TColumn {
  columnRules.set(column, rules)
  return column
}

/** 列に結びつけた検証ルールを返す。無ければ undefined */
export function getColumnRules(column: object): ColumnRules | undefined {
  return columnRules.get(column)
}

const columnRules = new WeakMap<object, ColumnRules>()

