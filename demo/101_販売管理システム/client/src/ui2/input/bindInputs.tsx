import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import type { FormBinding, GridBinding } from "../FormBinding"
import { TextBox, textColumn, type TextBoxProps, type TextColumnOptions } from "./TextBox"
import { TextArea, textAreaColumn, type TextAreaProps, type TextAreaColumnOptions } from "./TextArea"
import { NumericTextBox, numericColumn, type NumericTextBoxProps, type NumericColumnOptions } from "./NumericTextBox"
import { DateInput, dateColumn, type DateInputProps, type DateColumnOptions } from "./DateInput"
import { CheckBox, checkBoxColumn, type CheckBoxProps, type CheckBoxColumnOptions } from "./CheckBox"
import { EnumSelection, enumColumn, type EnumSelectionProps, type EnumColumnOptions } from "./EnumSelection"
import { RefTo, refToColumn, type RefToProps, type RefToColumnOptions } from "./RefTo"

/**
 * フォームと結びついた入力コンポーネントの一式。
 * どのコンポーネントも、入力制約と表示名はメタデータから決まる。
 * 項目の値の型に合ったものを使うこと。合わないものを使った場合は描画時に例外を投げる。
 *
 * TTable はフォームのメタデータの表の型。外部参照の入力欄で、name から検索ダイアログのパラメータの型を決めるのに使う。
 */
export type BoundInputs<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table = AggregateMetadata.Table,
> = {
  /** 単語（1行の文字列） */
  TextBox: (props: TextBoxProps<TValues>) => React.ReactNode
  /** 文章（複数行の文字列） */
  TextArea: (props: TextAreaProps<TValues>) => React.ReactNode
  /** 数値 */
  NumericTextBox: (props: NumericTextBoxProps<TValues>) => React.ReactNode
  /** 日付・日時・年月 */
  DateInput: (props: DateInputProps<TValues>) => React.ReactNode
  /** 真偽値 */
  CheckBox: (props: CheckBoxProps<TValues>) => React.ReactNode
  /** 列挙体 */
  EnumSelection: (props: EnumSelectionProps<TValues>) => React.ReactNode
  /**
   * 外部参照。参照先のデータは検索ダイアログで選ぶ。
   * 検索ダイアログは name から決まるので指定しない。パラメータが必要な検索ダイアログの場合だけ params を指定する。
   */
  RefTo: <TName extends RHF.Path<TValues>>(props: RefToProps<TValues, TTable, TName>) => React.ReactNode
}

/**
 * 入力コンポーネントの一式をフォームと結びつける。
 * 戻り値の各コンポーネントの参照は、binding が同じである限り変わらない。
 * 参照が変わると入力欄が再マウントされ、入力中の内容やフォーカスが失われるため。
 */
export function bindInputs<
  TValues extends RHF.FieldValues,
  TTable extends AggregateMetadata.Table,
>(binding: FormBinding<TValues>): BoundInputs<TValues, TTable> {
  return {
    TextBox: props => <TextBox {...props} binding={binding} />,
    TextArea: props => <TextArea {...props} binding={binding} />,
    NumericTextBox: props => <NumericTextBox {...props} binding={binding} />,
    DateInput: props => <DateInput {...props} binding={binding} />,
    CheckBox: props => <CheckBox {...props} binding={binding} />,
    EnumSelection: props => <EnumSelection {...props} binding={binding} />,
    RefTo: props => <RefTo {...props} binding={binding} />,
  }
}

/**
 * EditableGrid の列定義ヘルパー。
 * path は行オブジェクトから見たパス。見出しと入力制約はメタデータから決まる。
 * フォーム用の入力コンポーネントと同じく、項目の値の型に合ったものを使うこと。
 *
 * TTable はフォームのメタデータの表の型、TArrayPath はグリッドで編集する配列のフォーム上のパス。
 * 外部参照の列で、path から検索ダイアログのパラメータの型を決めるのに使う。
 */
export type GridColumnHelper<
  TRow,
  TTable extends AggregateMetadata.Table = AggregateMetadata.Table,
  TArrayPath extends string = string,
> = {
  /** 単語（1行の文字列）の列 */
  text: (path: RHF.Path<TRow>, options?: TextColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /** 文章（複数行の文字列）の列 */
  textArea: (path: RHF.Path<TRow>, options?: TextAreaColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /** 数値の列 */
  numeric: (path: RHF.Path<TRow>, options?: NumericColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /** 日付・日時・年月の列 */
  date: (path: RHF.Path<TRow>, options?: DateColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /** 真偽値の列 */
  checkBox: (path: RHF.Path<TRow>, options?: CheckBoxColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /** 列挙体の列 */
  enumeration: (path: RHF.Path<TRow>, options?: EnumColumnOptions<TRow>) => EG2.EditableGridLeafColumn<TRow>
  /**
   * 外部参照の列。参照先のデータは検索ダイアログで選ぶ。
   * 検索ダイアログは path から決まるので指定しない。パラメータが必要な検索ダイアログの場合だけ options の params が必須になる。
   */
  refTo: <TPath extends RHF.Path<TRow>>(
    path: TPath,
    ...options: OptionalIfNoRequiredProps<RefToColumnOptions<TRow, TTable, `${TArrayPath}.${TPath}`>>
  ) => EG2.EditableGridLeafColumn<TRow>
}

/** 列定義ヘルパーをグリッドと結びつける */
export function createGridColumnHelper<
  TRow,
  TTable extends AggregateMetadata.Table,
  TArrayPath extends string,
>(binding: GridBinding): GridColumnHelper<TRow, TTable, TArrayPath> {
  return {
    text: (path, options) => textColumn(binding, path, options),
    textArea: (path, options) => textAreaColumn(binding, path, options),
    numeric: (path, options) => numericColumn(binding, path, options),
    date: (path, options) => dateColumn(binding, path, options),
    checkBox: (path, options) => checkBoxColumn(binding, path, options),
    enumeration: (path, options) => enumColumn(binding, path, options),
    refTo: (path, ...options) => refToColumn(binding, path, options[0]),
  }
}

/** 必須のプロパティが無いオプションなら、引数を省略できるようにする */
type OptionalIfNoRequiredProps<TOptions> = {} extends TOptions ? [options?: TOptions] : [options: TOptions]
