import React from "react"
import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import { findMemberMetadata, type GridBinding } from "../FormBinding"
import { assertValueMember, attachColumnRules, inputFrameClassName, toRegisterRules, useSelectAllOnFocus, type ColumnOptionsBase, type InputPropsBase, type WithFormBinding } from "./InputProps"
import { createTextCellEditor, defineCellColumn, findCellMemberMetadata, type TextInputFilter } from "./GridCell"

/*
 * 数値の入力欄。
 * フォーム用とグリッド用で以下の仕様を共有する。
 *
 * - 右寄せで表示する。
 * - 整数部・小数部の桁数はメタデータから決める。
 *   総合桁数・小数部桁数の指定が無い場合は値の型から決める（整数・シーケンスは小数部なし、年は整数部4桁など）。
 * - 金額項目は接尾辞「円」、数量項目は接尾辞「個」を付け、いずれも3桁カンマ区切りで表示する。どちらでもない項目には付けない。
 * - 数値として解釈できない文字の入力は受け付けない。全角数字・全角記号は半角に読み替える。
 * - 桁数を超える値は切り捨てず、そのまま保持してクライアント側エラーにする。貼り付けの場合も同じ。
 *   整数部の切り捨ては値そのものを変えてしまい、ユーザーが気付かないまま誤った値が保存されるおそれがあるため。
 * - 3桁カンマ区切りは表示上だけのもので、フォームの値にはカンマを含めない。
 * - 検索条件のフォームでは、範囲指定（下限〜上限）の2つの入力欄になる。
 */

//#region フォーム用

export type NumericTextBoxProps<TValues extends RHF.FieldValues> = InputPropsBase<TValues> & {
  /** 未入力のときに表示する文字列。検索条件のフォームでは下限と上限の両方に表示される */
  placeholder?: string
}

/** 数値の入力欄（フォーム用） */
export function NumericTextBox<TValues extends RHF.FieldValues>(props: WithFormBinding<NumericTextBoxProps<TValues>, TValues>): React.ReactNode {
  const { binding, name, isReadOnly, rules, className, placeholder } = props
  const formPath = binding.toFormPath(name)
  const member = assertValueMember(findMemberMetadata(binding.metadata, name), name, 'NumericTextBox', isNumericMember)
  const format = numericFormatOf(member)
  const validateDigits = (value: unknown) => validateNumericDigits(toNumericText(value), format)

  // 画面表示用データでは1つの入力欄
  if (binding.kind === 'display-data') {
    return (
      <NumericInput
        id={binding.toElementId(formPath)}
        formPath={formPath}
        control={binding.formMethods.control}
        rules={toRegisterRules({ rules, validators: [validateDigits] })}
        format={format}
        isReadOnly={isReadOnly}
        placeholder={placeholder}
        className={className}
      />
    )
  }

  // 検索条件では範囲指定。範囲全体に対する検証は下限の入力欄に付ける
  const rangeOf = (_: unknown, formValues: RHF.FieldValues) => RHF.get(formValues, formPath) as NumericRange | undefined
  return (
    <div className={`flex items-center gap-1 ${className ?? ''}`}>
      {/* 下限 */}
      <NumericInput
        id={binding.toElementId(formPath)}
        formPath={`${formPath}.from`}
        control={binding.formMethods.control}
        rules={toRegisterRules({
          rules,
          itemValueOf: rangeOf,
          validators: [
            range => validateDigits((range as NumericRange | undefined)?.from),
            range => validateNumericRange(range as NumericRange | undefined),
          ],
        })}
        format={format}
        isReadOnly={isReadOnly}
        placeholder={placeholder}
        className="flex-1 min-w-0"
      />
      <span className="select-none">～</span>
      {/* 上限 */}
      <NumericInput
        formPath={`${formPath}.to`}
        control={binding.formMethods.control}
        rules={toRegisterRules({ rules: undefined, validators: [validateDigits] })}
        format={format}
        isReadOnly={isReadOnly}
        placeholder={placeholder}
        className="flex-1 min-w-0"
      />
    </div>
  )
}

/**
 * 1つの数値の入力欄。
 * 入力中は書式を外した文字列を、入力中でなければカンマ区切りの文字列を表示する。
 * 入力中の文字列はフォームの値とは別に持ち、フォーカスアウト時と Enter キーでフォームの値に反映する。
 * IME で変換中の全角文字を半角に読み替えると変換が壊れるため、入力中の文字列はフォームの値と別にしている。
 * Enter キーでも反映するのは、Enter キーによるフォームの送信で入力中の値が送信されるようにするため。
 */
function NumericInput({ id, formPath, control, rules, format, isReadOnly, placeholder, className }: {
  id?: string
  formPath: string
  control: RHF.Control<RHF.FieldValues>
  rules: Pick<RHF.RegisterOptions, 'validate'>
  format: NumericFormat
  isReadOnly: boolean | undefined
  placeholder: string | undefined
  className?: string
}) {
  const { field } = RHF.useController({ name: formPath, control, rules })
  const value = toNumericText(field.value)

  /** 入力中の文字列。入力中でなければ undefined */
  const [draft, setDraft] = React.useState<string>()
  const selectAllOnFocus = useSelectAllOnFocus()

  const handleFocus: React.FocusEventHandler<HTMLInputElement> = e => {
    if (!isReadOnly) setDraft(value)
    selectAllOnFocus.onFocus(e)
  }
  const handleChange: React.ChangeEventHandler<HTMLInputElement> = e => {
    if ((e.nativeEvent as InputEvent).isComposing) {
      setDraft(e.target.value)
      return
    }
    const accepted = NUMERIC_INPUT_FILTER.accept(e.target.value)
    if (accepted !== undefined) setDraft(accepted)
  }
  /** 入力中の文字列をフォームの値に反映し、反映した文字列を返す。入力中でなければ undefined */
  const commitDraft = () => {
    if (draft === undefined) return undefined
    const committed = commitNumericText(draft)
    if (committed !== value) field.onChange(committed)
    return committed
  }
  const handleKeyDown: React.KeyboardEventHandler<HTMLInputElement> = e => {
    if (e.key !== 'Enter' || e.nativeEvent.isComposing) return
    const committed = commitDraft()
    if (committed !== undefined) setDraft(committed)
  }
  const handleBlur = () => {
    commitDraft()
    setDraft(undefined)
    field.onBlur()
  }

  return (
    <div className={`inline-flex items-center px-1 py-px ${inputFrameClassName(isReadOnly)} ${className ?? ''}`}>
      <input
        type="text"
        id={id}
        ref={field.ref}
        name={field.name}
        inputMode={format.decimalDigit > 0 ? 'decimal' : 'numeric'}
        value={draft ?? formatNumeric(value, { ...format, suffix: undefined })}
        onFocus={handleFocus}
        onMouseDown={selectAllOnFocus.onMouseDown}
        onMouseUp={selectAllOnFocus.onMouseUp}
        onChange={handleChange}
        onCompositionEnd={e => setDraft(NUMERIC_INPUT_FILTER.sanitize(e.currentTarget.value))}
        onKeyDown={handleKeyDown}
        onBlur={handleBlur}
        readOnly={isReadOnly}
        placeholder={isReadOnly ? undefined : placeholder}
        spellCheck={false}
        autoComplete="off"
        className="flex-1 min-w-0 w-full text-right bg-transparent outline-none"
      />
      {/* 接尾辞（単位） */}
      {format.suffix && (
        <span className="pl-1 select-none whitespace-nowrap">{format.suffix}</span>
      )}
    </div>
  )
}

