/** 数値の書式 */
type NumericFormat = {
  /** 整数部の最大桁数 */
  integerDigit: number
  /** 小数部の最大桁数。0 の場合は小数を入力できない */
  decimalDigit: number
  /** 3桁カンマ区切りで表示するかどうか */
  commaSeparated: boolean
  /** 接尾辞（単位）。無い場合は undefined */
  suffix: string | undefined
}

/** 検索条件の範囲指定の値 */
type NumericRange = { from?: string | null, to?: string | null }

function isNumericMember(member: AggregateMetadata.Value): boolean {
  return member.type === 'int' || member.type === 'decimal' || member.type === 'sequence' || member.type === 'year'
}

/** メタデータから数値の書式を求める */
function numericFormatOf(member: AggregateMetadata.Member): NumericFormat {
  let integerDigit: number
  let decimalDigit: number
  if (member.kind === 'value' && member.type === 'year') {
    integerDigit = 4
    decimalDigit = 0
  } else if (member.kind === 'value' && member.type === 'decimal') {
    // 桁数の指定が無い場合はデータベースの既定の精度（総合18桁・小数部2桁）に合わせる
    const totalDigit = member.totalDigit ?? 18
    decimalDigit = member.decimalPlace ?? (member.totalDigit === undefined ? 2 : 0)
    integerDigit = Math.max(totalDigit - decimalDigit, 0)
  } else {
    // 整数・シーケンス。桁数の指定が無い場合は32ビット整数に収まる桁数
    integerDigit = member.totalDigit ?? 10
    decimalDigit = 0
  }

  const suffix = member.isCurrency ? '円' : member.isQuantity ? '個' : undefined
  return {
    integerDigit,
    decimalDigit,
    commaSeparated: suffix !== undefined,
    suffix,
  }
}

/** 値の確定時の正規化。全角を半角に読み替え、カンマを除く。桁数の超過はここでは扱わない */
function normalizeNumeric(value: string): string {
  return value
    .replace(/[０-９]/g, char => String.fromCharCode(char.charCodeAt(0) - 0xFEE0))
    .replace(/[．。]/g, '.')
    .replace(/[−－ー‐–—―]/g, '-')
    .replace(/[,，\s]/g, '')
}

/** 桁数の検証。整数部か小数部が桁数を超えていればエラーメッセージを、超えていなければ undefined を返す */
function validateNumericDigits(value: string, format: NumericFormat): string | undefined {
  if (value === '') return undefined
  if (!isNumericText(value)) return '数値を入力してください。'

  const [integerPart, decimalPart = ''] = value.replace('-', '').split('.')
  if (integerPart.replace(/^0+/, '').length > format.integerDigit) {
    return `整数部は${format.integerDigit}桁以内で入力してください。`
  }
  if (decimalPart.length > format.decimalDigit) {
    return format.decimalDigit === 0
      ? '小数は入力できません。'
      : `小数部は${format.decimalDigit}桁以内で入力してください。`
  }
  return undefined
}

/** 表示用の文字列にする。カンマ区切りと接尾辞を付ける */
function formatNumeric(value: string | null | undefined, format: NumericFormat): string {
  if (value === null || value === undefined || value === '') return ''
  let text = value
  if (format.commaSeparated && isNumericText(value)) {
    const [integerPart, decimalPart] = value.split('.')
    const sign = integerPart.startsWith('-') ? '-' : ''
    const digits = integerPart.replace('-', '').replace(/\B(?=(\d{3})+(?!\d))/g, ',')
    text = `${sign}${digits}${decimalPart === undefined ? '' : `.${decimalPart}`}`
  }
  return format.suffix ? `${text}${format.suffix}` : text
}

/**
 * 数値の入力欄とセルエディタで入力できる文字の制限。
 * 全角は半角に読み替え、数値として解釈できない文字の入力は受け付けない。
 */
const NUMERIC_INPUT_FILTER: TextInputFilter = {
  accept: text => {
    const normalized = normalizeNumeric(text)
    return isNumericText(normalized) ? normalized : undefined
  },
  sanitize: text => sanitizeNumericText(text),
}

/** 数値として解釈できる途中までの文字列か（符号・小数点だけの入力途中も含む） */
function isNumericText(value: string): boolean {
  return /^-?\d*\.?\d*$/.test(value)
}

/** 数値として解釈できない文字を取り除く。符号は先頭のものだけ、小数点は最初のものだけを残す */
function sanitizeNumericText(value: string): string {
  const normalized = normalizeNumeric(value).replace(/[^0-9.-]/g, '')
  const sign = normalized.startsWith('-') ? '-' : ''
  const [integerPart, ...decimalParts] = normalized.replace(/-/g, '').split('.')
  return decimalParts.length === 0
    ? `${sign}${integerPart}`
    : `${sign}${integerPart}.${decimalParts.join('')}`
}

/**
 * 入力を確定するときの文字列。末尾の小数点や、符号・小数点だけの入力を取り除く。
 * 整数部を省略した入力（「.5」など）は整数部に 0 を補う。
 */
function commitNumericText(value: string): string {
  const normalized = normalizeNumeric(value)
    .replace(/\.$/, '')
    .replace(/^(-?)\./, (_, sign: string) => `${sign}0.`)
  return normalized === '-' ? '' : normalized
}

/** フォームの値を数値の文字列として読む */
function toNumericText(value: unknown): string {
  if (value === null || value === undefined) return ''
  return typeof value === 'string' ? value : String(value)
}

/** 範囲指定の下限が上限を超えていればエラーメッセージを返す */
function validateNumericRange(range: NumericRange | undefined): string | undefined {
  const from = range?.from ?? ''
  const to = range?.to ?? ''
  if (from === '' || to === '' || !isNumericText(from) || !isNumericText(to)) return undefined
  return Number(from) > Number(to) ? '下限が上限を超えています。' : undefined
}

