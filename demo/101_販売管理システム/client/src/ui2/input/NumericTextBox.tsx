//#region グリッド用

export type NumericColumnOptions<TRow> = ColumnOptionsBase<TRow>

/** 数値の列（グリッド用） */
export function numericColumn<TRow>(
  binding: GridBinding,
  path: RHF.Path<TRow>,
  options?: NumericColumnOptions<TRow>,
): EG2.EditableGridLeafColumn<TRow> {
  const member = assertValueMember(findCellMemberMetadata(binding, path), path, 'numeric 列', isNumericMember)
  const format = numericFormatOf(member)

  const column = defineCellColumn(binding, path, options, {
    render: ({ value }) => formatNumeric(toNumericText(value), format),
    editor: NUMERIC_CELL_EDITOR,
    toText: toNumericText,
    fromText: text => {
      const committed = commitNumericText(normalizeNumeric(text))
      return isNumericText(committed) ? { value: committed } : undefined
    },
    alignRight: true,
  })
  // 桁数の超過は切り捨てずにクライアント側エラーにする
  return attachColumnRules(column, {
    path,
    validate: value => validateNumericDigits(toNumericText(value), format),
  })
}

/**
 * 数値のセルエディタ。参照を使い回すためモジュールのトップレベルで作る。
 * 入力できる文字の制限はフォームの入力欄と同じものを使う。制限はこのファイルの後ろで定義しているので、呼び出し時に参照する
 */
const NUMERIC_CELL_EDITOR = createTextCellEditor({
  multiline: false,
  inputFilter: {
    accept: text => NUMERIC_INPUT_FILTER.accept(text),
    sanitize: text => NUMERIC_INPUT_FILTER.sanitize(text),
  },
  alignRight: true,
})

