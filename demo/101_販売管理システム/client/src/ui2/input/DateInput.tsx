import * as RHF from "react-hook-form"
import * as EG2 from "@halllky/editable-grid"
import type { AggregateMetadata } from "../../__autoGenerated"
import { findMemberMetadata, type GridBinding } from "../FormBinding"
import { assertValueMember, inputFrameClassName, toRegisterRules, type ColumnOptionsBase, type InputPropsBase, type WithFormBinding } from "./InputProps"
import { createTextCellEditor, defineCellColumn, findCellMemberMetadata } from "./GridCell"

/*
 * 日付・日時・年月の入力欄。
 * フォーム用とグリッド用で以下の仕様を共有する。
 *
 * - 日付・日時・年月のどれを入力するかは、メタデータの値の型から決める。
 * - 表示の書式と、フォームの値として保持する文字列の書式は、フォームとグリッドで同じ。
 * - 日付として解釈できない値は確定時に空にする。グリッドへの貼り付けの場合も同じ。
 * - 検索条件のフォームでは、範囲指定（開始〜終了）の2つの入力欄になる。
 */

//#region フォーム用

export type DateInputProps<TValues extends RHF.FieldValues> = InputPropsBase<TValues>

/** 日付・日時・年月の入力欄（フォーム用）。基本的にはブラウザのネイティブな入力コントロールの仕様に従う */
export function DateInput<TValues extends RHF.FieldValues>(props: WithFormBinding<DateInputProps<TValues>, TValues>): React.ReactNode {
  const { binding, name, isReadOnly, rules, className } = props
  const formPath = binding.toFormPath(name)
  const kind = dateKindOf(findMemberMetadata(binding.metadata, name), name)

  // 画面表示用データでは1つの入力欄
  if (binding.kind === 'display-data') {
    return (
      <NativeDateInput
        id={binding.toElementId(formPath)}
        formPath={formPath}
        control={binding.formMethods.control}
        rules={toRegisterRules({ rules })}
        kind={kind}
        isReadOnly={isReadOnly}
        className={className}
      />
    )
  }

  // 検索条件では範囲指定。範囲全体に対する検証は開始の入力欄に付ける
  return (
    <div className={`flex flex-wrap items-center gap-1 ${className ?? ''}`}>
      {/* 開始 */}
      <NativeDateInput
        id={binding.toElementId(formPath)}
        formPath={`${formPath}.from`}
        control={binding.formMethods.control}
        rules={toRegisterRules({
          rules,
          itemValueOf: (_, formValues) => RHF.get(formValues, formPath),
          validators: [range => validateDateRange(range as DateRange | undefined)],
        })}
        kind={kind}
        isReadOnly={isReadOnly}
      />
      <span className="select-none">～</span>
      {/* 終了 */}
      <NativeDateInput
        formPath={`${formPath}.to`}
        control={binding.formMethods.control}
        rules={toRegisterRules({ rules: undefined })}
        kind={kind}
        isReadOnly={isReadOnly}
      />
    </div>
  )
}

/** ブラウザのネイティブな日付・日時・年月の入力欄1つ */
function NativeDateInput({ id, formPath, control, rules, kind, isReadOnly, className }: {
  id?: string
  formPath: string
  control: RHF.Control<RHF.FieldValues>
  rules: Pick<RHF.RegisterOptions, 'validate'>
  kind: DateKind
  isReadOnly: boolean | undefined
  className?: string
}) {
  const { field } = RHF.useController({ name: formPath, control, rules })

  return (
    <input
      type={kind === 'date' ? 'date' : kind === 'datetime' ? 'datetime-local' : 'month'}
      id={id}
      ref={field.ref}
      name={field.name}
      value={typeof field.value === 'string' ? field.value : ''}
      // ネイティブの入力欄は解釈できない値を空文字として渡すので、そのまま正規化すれば空になる
      onChange={e => field.onChange(normalizeDate(e.target.value, kind))}
      onBlur={field.onBlur}
      readOnly={isReadOnly}
      className={`block px-1 py-px outline-none ${inputFrameClassName(isReadOnly)} ${className ?? ''}`}
    />
  )
}

//#endregion フォーム用

//#region グリッド用

export type DateColumnOptions<TRow> = ColumnOptionsBase<TRow>

/** 日付・日時・年月の列（グリッド用） */
export function dateColumn<TRow>(
  binding: GridBinding,
  path: RHF.Path<TRow>,
  options?: DateColumnOptions<TRow>,
): EG2.EditableGridLeafColumn<TRow> {
  const kind = dateKindOf(findCellMemberMetadata(binding, path), path)
  const toText = (value: unknown) => typeof value === 'string' ? formatDate(value) : ''

  return defineCellColumn(binding, path, options, {
    render: ({ value }) => toText(value),
    editor: DATE_CELL_EDITOR,
    toText,
    fromText: text => ({ value: normalizeDate(text, kind) }),
  })
}

/** 日付のセルエディタ。区切り文字を含む様々な書式で手入力できるよう、文字列のまま受け付けて確定時に解釈する */
const DATE_CELL_EDITOR = createTextCellEditor({ multiline: false })

