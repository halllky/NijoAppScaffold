//#region フォームとグリッドで共有する仕様

/** 入力する値の種類 */
type DateKind = 'date' | 'datetime' | 'yearmonth'

/** 検索条件の範囲指定の値 */
type DateRange = { from?: string | null, to?: string | null }

/** メタデータから入力する値の種類を求める。日付系の型でない場合は例外を投げる */
function dateKindOf(member: AggregateMetadata.Member, path?: string): DateKind {
  const value = assertValueMember(member, path ?? '', 'DateInput', m => m.type === 'date' || m.type === 'datetime' || m.type === 'yearmonth')
  return value.type as DateKind
}

/**
 * 値の確定時の正規化。解釈できない値は空文字にする。
 * 年月日の区切りは「-」「/」「.」「年月日」のいずれでもよく、区切りの無い8桁（年月は6桁）も受け付ける。
 * 日時の時刻は空白か T の後に「時:分」で書く。時刻が無い場合は 0時0分 とする。
 * 正規化後の書式は、日付 `YYYY-MM-DD`、日時 `YYYY-MM-DDTHH:mm`、年月 `YYYY-MM`（ブラウザのネイティブな入力欄の値と同じ）。
 */
function normalizeDate(value: string, kind: DateKind): string {
  const text = value.trim().normalize('NFKC')
  if (text === '') return ''

  const [datePart, timePart, ...rest] = text.split(/[\sT]+/)
  if (rest.length > 0) return ''

  // 日付の部分
  const compact = /^(\d{4})(\d{2})(\d{2})?$/.exec(datePart)
  const separated = /^(\d{4})-(\d{1,2})(?:-(\d{1,2}))?-?$/.exec(datePart.replace(/[年月/.]/g, '-').replace(/日$/, ''))
  const matched = compact ?? separated
  if (!matched) return ''
  const year = Number(matched[1])
  const month = Number(matched[2])
  const day = matched[3] === undefined ? undefined : Number(matched[3])
  if (month < 1 || month > 12) return ''
  if (day !== undefined) {
    const date = new Date(year, month - 1, day)
    if (date.getFullYear() !== year || date.getMonth() !== month - 1 || date.getDate() !== day) return ''
  }
  const yearMonth = `${pad(year, 4)}-${pad(month, 2)}`
  if (kind === 'yearmonth') return timePart === undefined ? yearMonth : ''
  if (day === undefined) return ''
  const date = `${yearMonth}-${pad(day, 2)}`
  if (kind === 'date') return timePart === undefined ? date : ''

  // 時刻の部分
  if (timePart === undefined) return `${date}T00:00`
  const time = /^(\d{1,2})[:時](\d{1,2})分?(?::\d{1,2})?$/.exec(timePart)
  if (!time) return ''
  const hour = Number(time[1])
  const minute = Number(time[2])
  if (hour > 23 || minute > 59) return ''
  return `${date}T${pad(hour, 2)}:${pad(minute, 2)}`
}

/** 表示用の文字列にする。ブラウザのネイティブな入力欄の日本語表示に合わせ、区切りを「/」、日付と時刻の間を空白にする */
function formatDate(value: string): string {
  const [date, time] = value.split('T')
  const formattedDate = date.replace(/-/g, '/')
  return time === undefined ? formattedDate : `${formattedDate} ${time}`
}

/** 範囲指定の開始が終了より後ならエラーメッセージを返す。値の書式が同じなので文字列のまま比較できる */
function validateDateRange(range: DateRange | undefined): string | undefined {
  const from = range?.from ?? ''
  const to = range?.to ?? ''
  if (from === '' || to === '') return undefined
  return from > to ? '開始が終了より後になっています。' : undefined
}

function pad(value: number, length: number): string {
  return value.toString().padStart(length, '0')
}

