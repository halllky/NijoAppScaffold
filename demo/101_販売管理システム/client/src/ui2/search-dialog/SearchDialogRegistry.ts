import type { AggregateMetadata } from "../../__autoGenerated"
import type { SearchDialog } from "./defineSearchDialog"

/**
 * 外部参照先と、その参照先のデータを選ぶ検索ダイアログの対応表の型。
 * キーはメタデータの refTo（`ref-to:〇〇`）、値は defineSearchDialog の戻り値。
 *
 * 外部参照の入力欄は、項目の name からメタデータの refTo を引き、この対応表から検索ダイアログを決める。
 * そのため画面側は検索ダイアログを指定しなくてよく、ダイアログを開くときのパラメータの型も name から決まる。
 *
 * ui2 ではこの型は空で、プロジェクト側がモジュール拡張で中身を足す。
 * 対応表の実体は SearchDialogHost に渡す。型だけ登録して実体を渡し忘れた場合は、入力欄の描画時に例外を投げる。
 *
 * 登録の例:
 * ```ts
 * export const searchDialogs = {
 *   'ref-to:従業員': 従業員検索ダイアログ,
 * }
 * type SearchDialogs = typeof searchDialogs
 * declare module "（このファイルへの相対パス）" {
 *   interface SearchDialogRegistry extends SearchDialogs { }
 * }
 * ```
 */
export interface SearchDialogRegistry { }

/** 検索ダイアログを開くときのパラメータの props。パラメータが不要な検索ダイアログでは指定しなくてよい */
export type SearchDialogParamsProp<TOpenParams> = [TOpenParams] extends [void]
  ? { params?: undefined }
  : { params: TOpenParams }

/**
 * メタデータの表 TTable のうち、パス TPath の外部参照項目に対応する検索ダイアログの、パラメータの props。
 * TPath には配列のインデックスを含めてよい。
 *
 * 外部参照でない項目や、検索ダイアログが登録されていない項目を指定した場合は、
 * 理由を文字列にした型の params が必須になり、コンパイルエラーのメッセージにその理由が出る。
 * メタデータの表の型が具体的でない（キーが string の）場合は、パラメータの型を確かめない。
 */
export type RefToParamsProp<TTable extends AggregateMetadata.Table, TPath extends string>
  = string extends keyof TTable
  ? { params?: unknown }
  : RemoveArrayIndex<TPath> extends keyof TTable
  ? RefToParamsPropOfMember<TTable[RemoveArrayIndex<TPath>], RemoveArrayIndex<TPath>>
  : { params: `${TPath} はメタデータにありません` }

type RefToParamsPropOfMember<TMember, TKey extends string>
  = TMember extends { kind: 'ref', refTo: infer TRefTo extends string }
  ? TRefTo extends keyof SearchDialogRegistry
  ? SearchDialogRegistry[TRefTo] extends SearchDialog<any, infer TOpenParams>
  ? SearchDialogParamsProp<TOpenParams>
  : never
  : { params: `${TRefTo} の検索ダイアログが SearchDialogRegistry に登録されていません` }
  : { params: `${TKey} は外部参照ではありません` }

/** パスから配列のインデックス（半角数字だけの部分）を除く。例: `明細.0.検品者` → `明細.検品者` */
export type RemoveArrayIndex<TPath extends string>
  = TPath extends `${infer THead}.${infer TRest}`
  ? THead extends `${number}`
  ? RemoveArrayIndex<TRest>
  : `${THead}${PrefixDot<RemoveArrayIndex<TRest>>}`
  : TPath extends `${number}` ? '' : TPath

type PrefixDot<T extends string> = T extends '' ? '' : `.${T}`
