import React from "react"
import type { ASC_SUFFIX, DESC_SUFFIX } from "../../__autoGenerated"
import { MultiSelect } from "../../ui/MultiSelect"

/** 並び順コンボボックスの選択肢。昇順・降順の2つの選択肢に展開される */
export type SortComboItem<TMember extends string> = {
  /** ソート可能なメンバー。昇順・降順の接尾辞は付けない */
  key: TMember
  /** 表示名。昇順・降順の表記はコンボボックスが付ける */
  label: string
}

/** 検索条件の並び順の要素。メンバーに昇順・降順の接尾辞を付けたもの */
export type SortValue<TMember extends string> = `${TMember}${ASC_SUFFIX}` | `${TMember}${DESC_SUFFIX}`

/**
 * 一覧検索画面の並び順を指定するコンボボックス。
 * 既に選ばれているメンバーは、昇順・降順のどちらも選択肢から除かれる。
 * 選択肢が無い場合は何も表示しない。
 */
export function SortDropdown<TMember extends string>({ className, sortOptions, value, onChange }: {
  className?: string
  /** 選択肢。未指定の場合は何も表示しない */
  sortOptions: SortComboItem<TMember>[] | undefined
  /** 現在の並び順 */
  value: SortValue<TMember>[]
  /** 並び順が変更されたときに呼ばれる */
  onChange: (value: SortValue<TMember>[]) => void
}) {

  // 選択肢。既に選ばれているメンバーは除く
  const options = React.useMemo((): SortComboItemWithAscDesc<TMember>[] => {
    const selectedMembers = new Set(value.map(removeSortSuffix))
    return (sortOptions ?? [])
      .filter(item => !selectedMembers.has(item.key))
      .flatMap(item => expandAscDesc(item))
  }, [sortOptions, value])

  // 現在の並び順を、選択肢と同じ形にしたもの。選択肢に無い並び順は、そのまま表示する
  const selectedItems = React.useMemo((): SortComboItemWithAscDesc<TMember>[] => {
    const labelMap = new Map((sortOptions ?? []).flatMap(expandAscDesc).map(item => [item.key, item.label]))
    return value.map(key => ({ key, label: labelMap.get(key) ?? key }))
  }, [sortOptions, value])

  if (!sortOptions || sortOptions.length === 0) return null

  return (
    <MultiSelect<SortComboItemWithAscDesc<TMember>>
      className={className}
      value={selectedItems}
      options={options}
      onChange={items => onChange(items.map(item => item.key))}
      getLabel={item => item.label}
      placeholder="並び順"
    />
  )
}

/** 昇順・降順に展開した選択肢 */
type SortComboItemWithAscDesc<TMember extends string> = {
  key: SortValue<TMember>
  label: string
}

const ASC: ASC_SUFFIX = '（昇順）'
const DESC: DESC_SUFFIX = '（降順）'

/** 選択肢を昇順・降順の2つに展開する */
function expandAscDesc<TMember extends string>(item: SortComboItem<TMember>): SortComboItemWithAscDesc<TMember>[] {
  return [
    { key: `${item.key}${ASC}`, label: `${item.label} (昇順)` },
    { key: `${item.key}${DESC}`, label: `${item.label} (降順)` },
  ]
}

/** 並び順の要素から昇順・降順の接尾辞を除いて、メンバーにする */
function removeSortSuffix<TMember extends string>(value: SortValue<TMember>): TMember {
  if (value.endsWith(ASC)) return value.slice(0, -ASC.length) as TMember
  if (value.endsWith(DESC)) return value.slice(0, -DESC.length) as TMember
  return value as string as TMember
}
