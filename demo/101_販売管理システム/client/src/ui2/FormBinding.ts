/**
 * 入力コンポーネント・FieldLabel・RootErrors・グリッドの列が、フォームと結びつくための情報。
 * ui2 フォルダ内部でのみ使用する。画面側はこの型を意識しない。
 *
 * TValues は、各コンポーネントの name の起点となるオブジェクトの型。
 * 画面表示用データのフォームではフォーム全体の値、検索条件のフォームでは絞り込み条件のオブジェクトになる。
 * name をメタデータの表のキーと同じ形にそろえるため、起点をフォーム全体の値とは限らないものにしている。
 *
 * ## 参照の不変性
 * このオブジェクトはフォーム1つにつき1回だけ作り、以後は参照を変えない。
 * 画面側が使う入力コンポーネントは、このオブジェクトを受け取ってコンポーネントの関数を組み立てる形で作られる。
 * そのため、このオブジェクトの参照が変わるとコンポーネントの関数も作り直され、React からは別のコンポーネントに置き換わったように見える。
 * すると入力欄はいったん破棄されて新しく作られるので、入力途中の内容やフォーカスが失われてしまう。
 * そのため、時間とともに変わる値（メッセージなど）をプロパティとして直接持たせてはならない。
 * 変わる値は、最新の値を ref から読む関数として持たせ、変化を画面に反映する必要があるものは購読の手段を併せて持たせる。
 */
export type FormBinding<TValues extends RHF.FieldValues> = {
  /**
   * フォームの種類。
   * 検索条件の場合、各入力コンポーネントは検索条件用の外観になる（数値・日付は範囲指定、列挙体は複数選択など）。
   */
  kind: 'display-data' | 'search-condition'
  /**
   * react-hook-form の useForm の戻り値。
   * フォーム全体の値の型は TValues と一致しないことがあるため、型引数は持たせない。
   * 値の読み書きには必ず toFormPath で変換したパスを使うこと。
   */
  formMethods: RHF.UseFormReturn<RHF.FieldValues>
  /** 項目の表示名や入力制約を引くための表 */
  metadata: AggregateMetadata.Table
  /** name を、フォーム全体の値から見たパスに変換する */
  toFormPath: (name: RHF.Path<TValues>) => string
  /**
   * フォーム全体から見たパスを、その項目の入力欄の HTML 要素の id に変換する。
   * FieldLabel の label 要素の htmlFor と、入力コンポーネントの入力欄の id の両方がこれを使うことで、
   * ラベルのクリックで入力欄にフォーカスが移る。
   * 同じ画面に複数のフォームがあっても重複しないよう、フォームごとに異なる接頭辞が付く。
   */
  toElementId: (formPath: string) => string

  //#region メッセージ
  /**
   * メッセージが変わったときに呼ばれる関数を登録する。戻り値は登録解除の関数。
   * メッセージを表示するコンポーネントは、これと getMessages / getUnboundMessages を useSyncExternalStore で組み合わせて使う。
   * クライアント側エラーの変化と、サーバー側メッセージの変化と、表示領域の登録・解除のいずれでも呼ばれる。
   */
  subscribeMessages: (onChange: () => void) => () => void
  /**
   * 指定した表示領域に表示すべきメッセージを、呼び出した時点の最新の状態から求めて返す。
   * 対象は registerMessageArea で登録した範囲のうち、より内側の表示領域が無い項目に対するもの。
   * 表示領域の項目そのものではなく子孫の項目に対するメッセージには、その項目の表示名が前に付く。
   * 内容が変わっていなければ前回と同じ参照を返す。
   *
   * - クライアント側エラー: react-hook-form の formState.errors のうち、範囲内の項目に対するもの。errors にだけ入る。
   * - サーバー側メッセージ: setServerMessages で受け取ったもののうち、範囲内の項目に対するもの。エラー・警告・情報のすべて。
   */
  getMessages: (formPath: string) => Messages
  /**
   * どの表示領域の範囲にも入らないメッセージを、呼び出した時点の最新の状態から求めて返す。
   * フォームのルート以外に対するメッセージには、その項目の表示名が前に付く。
   * 内容が変わっていなければ前回と同じ参照を返す。
   *
   * - クライアント側エラー: formState.errors.root と、表示領域が無い項目に対する検証エラー。
   * - サーバー側メッセージ: フォームのルートに対するものと、表示領域が無い項目に対するもの。
   */
  getUnboundMessages: () => Messages
  /**
   * 指定した項目そのものに対するメッセージを、表示領域の登録とは関係なく返す。表示名は前に付かない。
   * グリッドのセルのように、他の表示領域と重ねてメッセージを表示するものが使う。
   * 内容が変わっていなければ前回と同じ参照を返す。
   */
  getFieldMessages: (formPath: string) => Messages
  /**
   * 画面上にメッセージの表示領域があることを登録する。戻り値は登録解除の関数。アンマウント時に呼ぶこと。
   * includesDescendants が true の場合、その項目の子孫に対するメッセージも、より内側の表示領域が無ければここに表示する。
   * クライアント側エラーとサーバー側メッセージのどちらにも同じ範囲が適用される。
   */
  registerMessageArea: (formPath: string, options: { includesDescendants: boolean }) => () => void
  //#endregion メッセージ
}

/**
 * グリッドの列が、フォーム上の配列の要素と結びつくための情報。
 * ui2 フォルダ内部でのみ使用する。
 */
export type GridBinding = {
  /** グリッドが属するフォーム */
  form: FormBinding<RHF.FieldValues>
  /** 配列の、フォーム全体の値から見たパス */
  arrayPath: string
  /** 配列の、name の起点から見たパス。列の項目のメタデータを引くのに使う */
  arrayName: string
  /**
   * 行キー（instanceId）から配列のインデックスを求める。
   * 削除済みの行を問い合わせられることがあるため、見つからない場合は undefined を返す。
   */
  findRowIndex: (rowKey: string) => number | undefined
  /** 外部参照先に対応する検索ダイアログを引く。対応表に無い場合は例外を投げる */
  findSearchDialog: (refTo: string) => SearchDialog<RHF.FieldValues, unknown>
  /** 検索ダイアログを開く */
  openDialogInHost: OpenDialogInHost
}

/**
 * メタデータの表から項目の定義を引く。
 * path には、配列のインデックス（半角数字だけの部分）や検索条件の範囲指定の末尾（from / to）を含めてよい。これらは読み飛ばす。
 * 該当する項目が無い場合は例外を投げる。
 */
export function findMemberMetadata(table: AggregateMetadata.Table, path: string): AggregateMetadata.Member {
  const segments = path.split('.').filter(segment => !/^\d+$/.test(segment))
  const key = segments.join('.')
  const member = table[key]
  if (member) return member

  // 範囲指定の末尾は、メタデータの表では範囲指定の項目そのものとして扱う
  const last = segments[segments.length - 1]
  if (last === 'from' || last === 'to') {
    const rangeMember = table[segments.slice(0, -1).join('.')]
    if (rangeMember) return rangeMember
  }
  throw new Error(`メタデータに ${path} がありません。`)
}

/**
 * フォームの FormBinding を作るフック。
 * useDisplayDataForm と useSearchConditionForm が共通で使う。ui2 フォルダ内部でのみ使用する。
 *
 * 戻り値の binding と関数の参照は、このフックを呼んだコンポーネントが生きている間は変わらない。
 * formMethods と metadata は最初に渡したものを使い続ける。
 */
export function useFormBinding<TValues extends RHF.FieldValues>(params: {
  kind: FormBinding<TValues>['kind']
  formMethods: RHF.UseFormReturn<RHF.FieldValues>
  metadata: AggregateMetadata.Table
  /**
   * name の起点の、フォーム全体の値から見たパス。
   * 画面表示用データのフォームでは空文字、検索条件のフォームでは絞り込み条件のプロパティ名。
   */
  nameRoot: string
}): {
  binding: FormBinding<TValues>
  setServerMessages: (detail: PresentationContextDetail | null | undefined) => void
  clearServerMessages: () => void
} {
  const elementIdPrefix = React.useId()

  // メッセージの保持と振り分け
  const [formMessages] = React.useState(() => createFormMessages({
    getValues: () => params.formMethods.getValues(),
    labelOf: formPath => labelOfFormPath(params.metadata, params.nameRoot, formPath),
  }))

  // react-hook-form の検証エラーと値の変化を、メッセージの振り分けに反映する
  const { formMethods } = params
  React.useEffect(() => {
    return formMethods.subscribe({
      formState: { errors: true, values: true },
      callback: state => formMessages.handleFormStateChange(state.errors),
    })
  }, [formMethods, formMessages])

  const [result] = React.useState(() => {
    const { kind, metadata, nameRoot } = params
    const binding: FormBinding<TValues> = {
      kind,
      formMethods: params.formMethods,
      metadata,
      toFormPath: name => nameRoot === '' ? name : `${nameRoot}.${name}`,
      toElementId: formPath => `${elementIdPrefix}${formPath}`,
      subscribeMessages: formMessages.subscribe,
      getMessages: formMessages.getMessages,
      getUnboundMessages: formMessages.getUnboundMessages,
      getFieldMessages: formMessages.getFieldMessages,
      registerMessageArea: formMessages.registerMessageArea,
    }
    return {
      binding,
      setServerMessages: (detail: PresentationContextDetail | null | undefined) => {
        formMessages.setServerMessages(detail, params.formMethods.getValues())
      },
      clearServerMessages: formMessages.clearServerMessages,
    }
  })
  return result
}

/**
 * フォーム全体から見たパスの項目の表示名を求める。
 * name の起点そのものは空文字、name の起点の外側の項目やメタデータに無い項目は undefined を返す。
 */
function labelOfFormPath(metadata: AggregateMetadata.Table, nameRoot: string, formPath: string): string | undefined {
  let name: string
  if (nameRoot === '') {
    name = formPath
  } else if (formPath === nameRoot) {
    name = ''
  } else if (formPath.startsWith(`${nameRoot}.`)) {
    name = formPath.slice(nameRoot.length + 1)
  } else {
    return undefined
  }
  if (name === '') return ''

  try {
    const member = findMemberMetadata(metadata, name)
    return member.displayNameIsEmpty ? '' : member.displayName
  } catch {
    return undefined
  }
}
