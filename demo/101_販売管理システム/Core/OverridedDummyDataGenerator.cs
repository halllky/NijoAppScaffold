using MyApp.Core.Authorization;

namespace MyApp;

/// <summary>
/// デバッグ用のダミーデータ生成。
/// DbContext を直接使ってマスタデータを登録します。
/// 業務データの生成処理がある場合は、マスタデータの登録後にそれを実行します。
/// </summary>
public partial class OverridedDummyDataGenerator {

    /// <param name="context">ダミーデータ生成の中で呼び出すクエリ・コマンドに渡す入出力</param>
    public OverridedDummyDataGenerator(CommandQueryContext context) {
        _context = context;
    }
    protected readonly CommandQueryContext _context;

    public const string ADMIN_USER_ID = "admin";
    public const string DUMMY_USER_PASSWORD = "password123";

    public virtual async Task<IMessageSetter> GenerateAsync(AutoGeneratedApplicationService<CommandQueryContext> applicationService) {
        var db = applicationService.DbContext;

        // 従業員: 管理者
        var adminPassword = PasswordHash.Create(DUMMY_USER_PASSWORD);
        db.従業員DbSet.Add(new 従業員DbEntity {
            従業員番号 = ADMIN_USER_ID,
            氏名 = "デモ用ユーザー",
            パスワード = adminPassword.Hash,
            SALT = adminPassword.Salt,
            従業員の権限 = [new() { 権限区分 = 権限区分.システム管理者 }],
            Version = 0,
        });
        // 従業員: その他
        for (var i = 1; i <= 10; i++) {
            var password = PasswordHash.Create(DUMMY_USER_PASSWORD);
            db.従業員DbSet.Add(new 従業員DbEntity {
                従業員番号 = $"user{i:000}",
                氏名 = $"ユーザー{i:000}",
                パスワード = password.Hash,
                SALT = password.Salt,
                Version = 0,
            });
        }
        await db.SaveChangesAsync();

        var messages = new MessageSetter([], new());

        // 業務データ
        Func<AutoGeneratedApplicationService<CommandQueryContext>, MessageSetter, Task>? generate業務データAsync = null;
        Get業務データ生成処理(ref generate業務データAsync);
        if (generate業務データAsync != null) {
            await generate業務データAsync(applicationService, messages);
        }

        return messages;
    }

    /// <summary>
    /// マスタデータの登録後に実行する、業務データの生成処理を返す。
    /// 生成処理の中で発生したエラーは、引数のメッセージに登録すること。
    /// 業務データが無い場合は実装しなくてよい（実装が無ければ呼び出しごと取り除かれる）。
    /// </summary>
    partial void Get業務データ生成処理(ref Func<AutoGeneratedApplicationService<CommandQueryContext>, MessageSetter, Task>? generateAsync);
}

#endif
