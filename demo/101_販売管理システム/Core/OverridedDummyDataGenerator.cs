using Microsoft.Extensions.DependencyInjection;
using MyApp.Core.Authorization;

namespace MyApp;

/// <summary>
/// デバッグ用のダミーデータ生成。
/// DbContext を直接使ってマスタデータを登録します。
/// 業務データの生成処理がある場合は、マスタデータの登録後にそれを実行します。
/// </summary>
public partial class OverridedDummyDataGenerator {

    /// <param name="context">ダミーデータ生成の中で呼び出すクエリ・コマンドに渡す入出力</param>
    public OverridedDummyDataGenerator(OperationContext context) {
        _context = context;
    }
    protected readonly OperationContext _context;

    public const string ADMIN_USER_ID = "admin";
    public const string DUMMY_USER_PASSWORD = "password123";

    public virtual async Task<IMessageSetter> GenerateAsync(AutoGeneratedApplicationService<OperationContext> applicationService) {
        var db = applicationService.DbContext;

        // 従業員: 管理者
        var adminPassword = PasswordHash.Create(DUMMY_USER_PASSWORD);
        db.従業員DbSet.Add(new 従業員DbEntity {
            従業員番号 = ADMIN_USER_ID,
            氏名 = "デモ用ユーザー",
            パスワード = adminPassword.Hash,
            SALT = adminPassword.Salt,
            従業員の権限 = [new() { 権限区分 = 権限区分.システム管理者 }],
            Version = 0,
        });
        // 従業員: その他
        for (var i = 1; i <= 10; i++) {
            var password = PasswordHash.Create(DUMMY_USER_PASSWORD);
            db.従業員DbSet.Add(new 従業員DbEntity {
                従業員番号 = $"user{i:000}",
                氏名 = $"ユーザー{i:000}",
                パスワード = password.Hash,
                SALT = password.Salt,
                Version = 0,
            });
        }
        await db.SaveChangesAsync();

        // 通知: 管理者宛て。通知の一覧と未読の件数の表示を、画面で確かめられるようにする
        var now = applicationService.ServiceProvider.GetRequiredService<ICurrentTime>().Value;
        db.通知DbSet.AddRange(
            New管理者宛ての通知("ダミーの未読の通知です。リンク先はありません。", null, 既読日時: null, now.AddMinutes(-1)),
            New管理者宛ての通知("ダミーの未読の通知です。従業員の画面へのリンクがあります。", 画面のURL.従業員(), 既読日時: null, now.AddMinutes(-2)),
            New管理者宛ての通知("ダミーの既読の通知です。", null, 既読日時: now, now.AddMinutes(-3)));
        await db.SaveChangesAsync();

        var messages = new MessageSetter([], new());

        // 業務データ
        Func<AutoGeneratedApplicationService<OperationContext>, MessageSetter, Task>? generate業務データAsync = null;
        Get業務データ生成処理(ref generate業務データAsync);
        if (generate業務データAsync != null) {
            await generate業務データAsync(applicationService, messages);
        }

        return messages;
    }

    private static 通知DbEntity New管理者宛ての通知(string 本文, string? リンク先, DateTime? 既読日時, DateTime 作成日時) => new() {
        通知ID = Guid.NewGuid().ToString(),
        宛先 = ADMIN_USER_ID,
        本文 = 本文,
        リンク先 = リンク先,
        既読日時 = 既読日時,
        CreatedAt = 作成日時,
        Version = 0,
    };

    /// <summary>
    /// マスタデータの登録後に実行する、業務データの生成処理を返す。
    /// 生成処理の中で発生したエラーは、引数のメッセージに登録すること。
    /// 業務データが無い場合は実装しなくてよい（実装が無ければ呼び出しごと取り除かれる）。
    /// </summary>
    partial void Get業務データ生成処理(ref Func<AutoGeneratedApplicationService<OperationContext>, MessageSetter, Task>? generateAsync);
}

#endif
