namespace MyApp;

/// <summary>
/// デバッグ用のダミーデータ生成。
/// DbContext を直接使ってマスタデータを登録します。
/// 業務データの生成処理がある場合は、マスタデータの登録後にそれを実行します。
/// </summary>
public partial class OverridedDummyDataGenerator {

    public OverridedDummyDataGenerator(Func<IMessageSetter, IPresentationContext<MessageSetter>> createPresentationContext) {
        _createPresentationContext = createPresentationContext;
    }
    protected readonly Func<IMessageSetter, IPresentationContext<MessageSetter>> _createPresentationContext;

    public const string ADMIN_USER_ID = "admin";
    public const string DUMMY_USER_PASSWORD = "password123";

    public virtual async Task<IMessageSetter> GenerateAsync(AutoGeneratedApplicationService applicationService) {
        var db = applicationService.DbContext;

        // 従業員: 管理者
        var adminSalt = OverridedApplicationService.GenerateSalt();
        db.従業員DbSet.Add(new 従業員DbEntity {
            従業員番号 = ADMIN_USER_ID,
            氏名 = "デモ用ユーザー",
            パスワード = OverridedApplicationService.ComputeHash(DUMMY_USER_PASSWORD, adminSalt),
            SALT = adminSalt,
            入荷担当 = true,
            販売担当 = true,
            システム管理者 = true,
            Version = 0,
        });
        // 従業員: その他
        for (var i = 1; i <= 10; i++) {
            var s = OverridedApplicationService.GenerateSalt();
            db.従業員DbSet.Add(new 従業員DbEntity {
                従業員番号 = $"user{i:000}",
                氏名 = $"ユーザー{i:000}",
                パスワード = OverridedApplicationService.ComputeHash(DUMMY_USER_PASSWORD, s),
                SALT = s,
                入荷担当 = i % 2 == 0,
                販売担当 = i % 3 == 0,
                システム管理者 = false,
                Version = 0,
            });
        }
        await db.SaveChangesAsync();

        var presentationContext = _createPresentationContext(new MessageSetter([], new()));

        // 業務データ
        Func<AutoGeneratedApplicationService, IPresentationContext<MessageSetter>, Task>? generate業務データAsync = null;
        Get業務データ生成処理(ref generate業務データAsync);
        if (generate業務データAsync != null) {
            await generate業務データAsync(applicationService, presentationContext);
        }

        return presentationContext.Messages;
    }

    /// <summary>
    /// マスタデータの登録後に実行する、業務データの生成処理を返す。
    /// 生成処理の中で発生したエラーは、引数の presentationContext のメッセージに登録すること。
    /// 業務データが無い場合は実装しなくてよい（実装が無ければ呼び出しごと取り除かれる）。
    /// </summary>
    partial void Get業務データ生成処理(ref Func<AutoGeneratedApplicationService, IPresentationContext<MessageSetter>, Task>? generateAsync);
}

#endif
