using System.Text;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using MyApp.Core.Authorization;
using NLog.Extensions.Logging;

namespace MyApp;

partial class OverridedApplicationService {

    /// <summary>ログ出力用キー名: ログインユーザーID</summary>
    public const string LOG_SCOPEPROP_LOGIN_USERID = "LoginUserId";
    /// <summary>ログ出力用キー名: 処理名</summary>
    public const string LOG_SCOPEPROP_PROCESS_NAME = "ProcessName";
    /// <summary>ログ出力用キー名: 処理1回分の識別子</summary>
    public const string LOG_SCOPEPROP_SCOPE_ID = "ScopeId";

    /// <summary>
    /// DIコンテナへのサービス登録を行う。
    /// </summary>
    /// <param name="services">DIコンテナ</param>
    /// <param name="basePath">実行時設定ファイルのベースパス（appsettings.jsonのあるフォルダ）</param>
    /// <param name="isDevelopment">
    /// 開発環境で動かすかどうか。
    /// 省略すると開発環境として扱う。本番環境で動かす呼び出し元は Web だけで、
    /// それ以外の呼び出し元（単体テスト、マイグレーション）は開発環境の設定で動かすため。
    /// </param>
    public static void ConfigureServices(IServiceCollection services, string basePath, bool isDevelopment = true) {
        if (!Path.IsPathRooted(basePath)) throw new ArgumentException($"{nameof(basePath)}は絶対パスで指定してください。");

        // アプリケーションサービスをDIコンテナに登録
        services.AddScoped<OverridedApplicationService>();
        services.AddScoped<AutoGeneratedApplicationService<OperationContext>>(sp => sp.GetRequiredService<OverridedApplicationService>());

        // 実行時設定ファイルの読み込み設定
        var myAppSection = new ConfigurationBuilder()
            .SetBasePath(basePath)
            .AddJsonFile("appsettings.json", false)
            .AddJsonFile("appsettings.Development.json", true) // 後にAddされたファイルが優先される
            .Build()
            .GetSection(RuntimeSetting.MY_APP_SECTION);
        var settings = new RuntimeSetting();
        myAppSection.Bind(settings);
        settings.GetBusinessTimeZone(); // 業務のタイムゾーンの設定の誤りを、最初に現在時刻を使う時点ではなく起動の時点で知らせる
        services.AddSingleton(settings);

        // DBコンテキスト登録
        services.AddScoped<ICurrentTime, CurrentTime>();
        services.AddSingleton<IDisplayMessageFactory, DefaultMessageFactory>();
        services.AddScoped<AutoGeneratedDbContext>(sp => sp.GetRequiredService<OverridedDbContext>());
        services.AddDbContext<OverridedDbContext>((services, options) => {

            // SQLiteを使用する
            var settings = services.GetRequiredService<RuntimeSetting>();
            var connStr = settings.GetCurrentProfile().ConnStr;
            options.UseSqlite(connStr, builder => {
                // マイグレーションファイルが生成されるアセンブリを指定する。
                // 既定では DbContext が宣言されているプロジェクトになる。
                builder.MigrationsAssembly(typeof(OverridedApplicationService).Assembly.FullName);
            });

            // データの保存処理は変更追跡オフが前提
            options.UseQueryTrackingBehavior(QueryTrackingBehavior.NoTracking);
        });

        // ログインユーザー
        services.AddScoped<LoginUserProvider>();
        services.AddSingleton<LoginFailureHistory>();
        services.AddScoped<ICurrentUser>(sp => sp.GetRequiredService<LoginUserProvider>());

        // ログ設定。Error 以上のログは、エラーの通知で運用担当者にメールで知らせる
        var errorNotifier = Core.運用担当への通知.ErrorNotifier.Create(settings, basePath);
        services.AddSingleton(errorNotifier);
        LogSettings.ConfigureServices(services, myAppSection, basePath, errorNotifier);

        // 外部システム連携（エラーの通知のメールも含む）。
        // DI コンテナができる前なので、設定についてのログは、この場で作るロガーで出力する
        using var startupLoggerFactory = LoggerFactory.Create(logging => logging.AddNLog());
        if (!isDevelopment && settings.ErrorNotification.UseMock == true) {
            startupLoggerFactory.CreateLogger<OverridedApplicationService>().LogWarning("エラーの通知のメールはモックで動いています。");
        }
        Configure外部システム(services, settings, isDevelopment, startupLoggerFactory.CreateLogger<OverridedApplicationService>());
    }

    /// <summary>
    /// 外部システム連携に必要なサービスをDIコンテナに登録する。
    /// 外部システムごとに、どの実装（本物、モックなど）を使うかを設定から決める。
    /// その設定が省略されていたら、例外を投げて起動を止める。
    /// 開発環境以外でモックを使うときは、その外部システムの名前を Warning でログに出力する。
    /// 連携する外部システムが無い場合は実装しなくてよい（実装が無ければ呼び出しごと取り除かれる）。
    /// </summary>
    /// <param name="services">DIコンテナ</param>
    /// <param name="settings">実行時設定</param>
    /// <param name="isDevelopment">開発環境で動かすかどうか</param>
    /// <param name="logger">設定についてのログの出力先</param>
    static partial void Configure外部システム(IServiceCollection services, RuntimeSetting settings, bool isDevelopment, ILogger logger);
}
